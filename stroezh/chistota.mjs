const IZNESENI = /^export\s+(?:async\s+)?(function|class|const|let|interface|type|enum)\s+([A-Za-z_$][\w$]*)/gm;

/**
 * ТИПЪТ НЕ Е ФУНКЦИЯ · първата поправка на самия обход.
 *
 * Първото пускане обяви 143 „мъртви" имена, и повечето бяха ТИПОВЕ. Това е
 * лъжлива находка: тип, който стои в подписа на изнесена функция, ТРЯБВА да е
 * изнесен — иначе онзи, който вика функцията, няма как да назове онова, което
 * тя връща. TypeScript го иска изрично при декларации.
 *
 * Затова обходът дели двете: изнесен ТИП в публичен подпис е част от лицето
 * на модула; изнесена ФУНКЦИЯ без нито един външен викащ е мъртва.
 */
const TIPOVE = new Set(['interface', 'type', 'enum']);

const imenata = new Map();
for (const f of kod) {
  for (const [, kakvo, ime] of chist.get(f).matchAll(IZNESENI)) {
    imenata.set(ime, { kade: f, tip: TIPOVE.has(kakvo), vKod: 0, vTest: 0 });
  }
}

/** Стои ли този тип на ред, който ИЗНАСЯ нещо — тоест в лицето на модула. */
function vPublichenPodpis(ime, f) {
  return publichniPodpisi(f).some(
    (podpis) =>
      !new RegExp(`^export\\s+(?:async\\s+)?\\w+\\s+${ime}\\b`).test(podpis) &&
      new RegExp(`\\b${ime}\\b`).test(podpis),
  );
}

/**
 * ПУБЛИЧНИТЕ ПОДПИСИ на един файл, всеки СЛЕПЕН в един ред · седмата поправка.
 *
 * Дотук проверката гледаше ЕДИН ред. Подпис на няколко реда я излъга веднага:
 *
 *   export function sgani(
 *     verigi: readonly (readonly Sabitie[])[],
 *     kogato: string,
 *   ): SgunatoOgledalo {
 *
 * Върнатият тип стои на ред, който НЕ почва с `export` — тъй че `SgunatoOgledalo`
 * излезе „излишен export", макар да е самото лице на модула. Обход, който кара
 * да се махне точно онова, което държи подписа, е по-скъп от липсващ.
 *
 * Затова редовете се слепват: от реда с `export` до онзи, който затваря
 * подписа (`{` или `;`). Таванът от 20 реда е спирачка за файл без затваряне —
 * обходът предпочита да пропусне, вместо да увисне.
 */
function publichniPodpisi(f) {
  const redove = chist.get(f).split('\n');
  const podpisi = [];
  for (let i = 0; i < redove.length; i += 1) {
    if (!/^export\b/.test(redove[i])) continue;
    let podpis = redove[i];
    for (let k = 1; k < 20 && !/[{;]\s*$/.test(podpis); k += 1) {
      const sled = redove[i + k];
      if (sled === undefined) break;
      podpis += ` ${sled.trim()}`;
    }
    // ТЯЛОТО НА ИЗНЕСЕН ТИП СЪЩО Е ЛИЦЕ. `RezyumeNaVeriga` стои само вътре в
    // полетата на изнесен `interface` — а онзи, който го получава, трябва да
    // може да назове какво е получил. Затова при тип се чете до затварящата
    // скоба, не до отварящата.
    if (/^export\s+(?:declare\s+)?(interface|type|class|enum)\b/.test(redove[i])) {
      for (let k = 1; k < 200; k += 1) {
        const sled = redove[i + k];
        if (sled === undefined) break;
        podpis += ` ${sled.trim()}`;
        if (/^\}/.test(sled)) break;
      }
    }
    podpisi.push(podpis);
  }
  return podpisi;
}

/** Колко пъти името се среща В СВОЯ файл, без реда на декларацията си. */
function vSvoyaFayl(ime, f) {
  return chist
    .get(f)
    .split('\n')
    .filter(
      (red) =>
        !new RegExp(`^export\\s+(?:async\\s+)?\\w+\\s+${ime}\\b`).test(red) &&
        new RegExp(`\\b${ime}\\b`).test(red),
    ).length;
}

function prebroy(faylove, pole) {
  for (const f of faylove) {
    const t = chist.get(f);
    for (const [ime, zapis] of imenata) {
      if (f === zapis.kade) continue;
      if (new RegExp(`\\b${ime}\\b`).test(t)) zapis[pole] += 1;
    }
  }
}
prebroy(kod, 'vKod');
prebroy([...testove, ...prohod], 'vTest');

/**
 * ТРИТЕ СЪСТОЯНИЯ, и разликата между тях е скъпа.
 *
 *   · **мъртво** · името не се среща НИКЪДЕ освен в собствената си декларация.
 *     Това е дефект: код, който не участва, но се чете, поддържа и мести;
 *   · **излишен `export`** · ползва се, но само ВЪТРЕ в своя файл. Не е дефект,
 *     а обещание за лице на модула, което никой не е поискал. Изнесеният тип
 *     в подписа на изнесена функция ТРЯБВА да е изнесен и не влиза тук;
 *   · **само тест** · НИКОЙ не го вика освен тестът — нито друг файл, нито
 *     собственият му. Това НЕ е мъртъв код (обходът веднъж го обяви така,
 *     защото ТЕСТ БРОИ ЗА ВИКАЩ) — то е непостроена възможност с тест,
 *     `docs/09` §3;
 *   · **изнесено за теста** · вика се ВЪТРЕ в своя файл и отвън само тестът го
 *     стига. Обратното на непостроена възможност: то е ПОСТРОЕНО и жицата му
 *     е вътрешна, а `export` съществува само за да има тест.
 *
 * ═══ ЗАЩО ЧЕТВЪРТОТО СЪСТОЯНИЕ Е ОТДЕЛНО · платено със собствено число ═══
 *
 * Дотук вътрешният викащ не се броеше и четирите имена в `app/redaktsiya.ts` —
 * всяко от които се вика на два реда по-долу в същия файл — влизаха в „само
 * тест". Тоест честният списък на непостроеното носеше в себе си построеното.
 *
 * Това е по-скъпо, отколкото изглежда: този списък е СУРОВИНАТА, по която се
 * тръгва да се търсят обявени, но незакачени възможности (точно така се намери
 * `mozheDaRedaktiraKolona` — правило 23 без нито един викащ). Надут списък
 * значи истинските находки да се крият сред верните случаи, а обход, който
 * праща човека на грешно място, се спира да се чете след третия път.
 */
for (const [ime, z] of imenata) {
  if (z.vKod > 0) continue;
  const vatre = vSvoyaFayl(ime, z.kade);
  if (z.vTest === 0 && vatre === 0) {
    nahodka('1 · мъртво', z.kade, 0, `„${ime}" · не се среща НИКЪДЕ освен в декларацията си`);
  } else if (z.vTest === 0) {
    // ТИП В ПУБЛИЧЕН ПОДПИС НЕ Е ИЗЛИШЕН · шестата поправка на обхода.
    // Шапката го обявяваше отдавна, а кодът го прилагаше само за обход 3.
    // Затова `Tochnost` — типът на втория довод на изнесената `zakragli` —
    // излезе като „излишен export" в мига, в който четецът на лексеми
    // прогледна за `app/`. Тип, който стои на ред с `export`, Е част от лицето
    // на модула: без него викащият няма как да назове онова, което подава.
    if (z.tip && vPublichenPodpis(ime, z.kade)) continue;
    nahodka('2 · излишен export', z.kade, 0, `„${ime}" · ползва се само ВЪТРЕ в своя файл`);
  } else if (!z.tip) {
    if (vatre > 0) {
      nahodka('3б · изнесено за теста', z.kade, 0, `„${ime}" · вика се ВЪТРЕ в своя файл`);
    } else {
      nahodka('3 · само тест', z.kade, 0, `изнесено „${ime}" · вика го САМО тестът`);
    }
  }
}

// ── 3 · ПРАЗНО ПОЛЕ, КОЕТО УЧАСТВА ────────────────────────────────────────

/**
 * Празният низ и `undefined` минават за число в JavaScript: `Number('')` е 0,
 * а `Number(undefined)` е NaN. И двете влизат мълчаливо в сбор.
 *
 * Ловят се ТРИ израза, всеки от които е бил истински дефект в този проект:
 *   · `Number(нещо ?? '')` — празното става нула;
 *   · `parseFloat` и `parseInt` върху поле от форма без проверка;
 *   · `as never` върху сума — то изключва проверката на типа ИЗЦЯЛО и точно
 *     така „undefined" мина за пари и нарисува „NaN €" (`pari.ts`).
 */
const PRAZNI = [
  [/Number\(\s*[^)]*\?\?\s*''\s*\)/g, "Number(… ?? '') · празното става НУЛА мълчаливо"],
  [/\bparseFloat\s*\(/g, 'parseFloat · празното дава NaN и влиза в сбор'],
  // `parseInt` БЕЗ основа · с основа (8 · 16) той чете вече проверен низ и е
  // верен. Първото пускане обяви и двата верни случая — обход, който брани
  // правилното, кара човек да го „поправи" в грешно.
  [/\bparseInt\s*\([^,)]*\)/g, 'parseInt без основа · „08" става 0 на стари четци'],
  [/_st[^\n]*\bas never\b/g, 'сума през „as never" · проверката на типа пада ИЗЦЯЛО'],
];

for (const f of kod) {
  const redove = chist.get(f).split('\n');
  redove.forEach((red, i) => {
    for (const [izraz, duma] of PRAZNI) {
      izraz.lastIndex = 0;
      if (izraz.test(red)) nahodka('4 · празно поле', f, i + 1, duma);
    }
  });
}

// ── 4 · ИЗЛИШНИ РЕДОВЕ ────────────────────────────────────────────────────

for (const f of kod) {
  const tekst = chist.get(f);
  const redove = tekst.split('\n');

  /**
   * ГЛЪТНАТ ОТКАЗ · `catch` без НИТО ЕДИН ред и без НИТО ЕДНА дума.
   *
   * Търси се в СУРОВИЯ текст. Първото пускане обяви 12 находки и всичките
   * дванайсет бяха обяснени — `catch { // частен прозорец: пак работи, само не
   * помни }`. Изчистването маха коментара и обяснението изглежда като мълчание.
   *
   * Точно това е разликата, която този проект пази: отказ, КАЗАН с дума, не е
   * глътнат. Глътнат е онзи, който не оставя нищо.
   */
  for (const m of tekstat.get(f).matchAll(/catch\s*(?:\([^)]*\))?\s*\{\s*\}/g)) {
    nahodka(
      '5 · излишен ред',
      f,
      tekstat.get(f).slice(0, m.index).split('\n').length,
      'глътнат отказ · `catch {}` без ред и без дума',
    );
  }

  // УСЛОВИЕ, КОЕТО ВИНАГИ Е ВЯРНО.
  for (const m of tekst.matchAll(/\bif\s*\(\s*(?:true|1)\s*\)/g)) {
    nahodka('5 · излишен ред', f, tekst.slice(0, m.index).split('\n').length, 'условие, което винаги е вярно');
  }

  // ЗАКОМЕНТИРАН КОД · ред, който е бил код, а сега е коментар. Търси се в
  // ЦЕЛИЯ текст (не в изчистения) и само при явни белези: коментар, който
  // завършва с „;" или „{", тоест изречение на код, не на български.
  tekstat.get(f).split('\n').forEach((red, i) => {
    const t = red.trim();
    if (!t.startsWith('//')) return;
    const tyalo = t.slice(2).trim();
    if (/[;{]$/.test(tyalo) && /[A-Za-z_$][\w$]*\s*[=(.]/.test(tyalo)) {
      nahodka('5 · излишен ред', f, i + 1, `закоментиран код · „${tyalo.slice(0, 48)}"`);
    }
  });

  /**
   * ТРИ ПРАЗНИ РЕДА подред · нито дял, нито дъх.
   *
   * Брои се в СУРОВИЯ текст, не в изчистения. Първото пускане обяви 10 640
   * находки, защото изчистването превръща коментарите в празни редове — а този
   * проект носи дълги обяснения над всяка функция. Обход, който брои
   * собственото си обяснение за боклук, е по-лош от липсващ.
   */
  const surovi = tekstat.get(f).split('\n');
  for (let i = 2; i < surovi.length; i += 1) {
    if (surovi[i].trim() === '' && surovi[i - 1].trim() === '' && surovi[i - 2].trim() === '') {
      nahodka('5 · излишен ред', f, i + 1, 'три празни реда подред');
    }
  }
}

