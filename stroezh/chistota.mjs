// ── 7 · ДУБЛИРАНО · еднакви блокове ───────────────────────────────────────

/**
 * Търсят се блокове от ПЕТ смислени реда, повторени дословно на две места.
 * Пет е границата, под която съвпадението е случайно (три реда затваряне на
 * скоби се повтарят навсякъде и не значат нищо).
 *
 * ═══ СПИСЪК НЕ Е ЛОГИКА · третата поправка на обхода ═══
 *
 * Първото пускане обяви 67 „дублирани" блока. Почти всички бяха СПИСЪЦИ —
 * съседни редове от списък с внасяния или полета на интерфейс. Два файла,
 * които внасят едни и същи седем имена, не дублират логика; те ползват един
 * и същ модул, което е точно каквото трябва.
 *
 * Затова блок се брои само когато носи ДЕЙСТВИЕ: поне два от петте реда трябва
 * да са изречения — повикване, присвояване, връщане или условие.
 */
const DEYSTVIE = /(?:\breturn\b|\bif\s*\(|=>|[\w$)\]]\s*\(|[^=!<>]=[^=])/;

const BLOK = 5;
const blokove = new Map();
for (const f of kod) {
  const redove = sNizove
    .get(f)
    .split('\n')
    .map((r, i) => ({ tekst: r.trim(), red: i + 1 }))
    .filter((r) => r.tekst !== '' && r.tekst !== '}' && r.tekst !== '});' && r.tekst !== '{');
  for (let i = 0; i + BLOK <= redove.length; i += 1) {
    const parcheta = redove.slice(i, i + BLOK);
    const klyuch = parcheta.map((r) => r.tekst).join('\n');
    if (klyuch.length < 120) continue;
    if (parcheta.filter((r) => DEYSTVIE.test(r.tekst)).length < 2) continue;
    const veche = blokove.get(klyuch);
    if (veche) {
      if (veche.kade !== f || Math.abs(veche.red - redove[i].red) > BLOK) {
        nahodka(
          '8 · дублирано',
          f,
          redove[i].red,
          `${BLOK} реда, еднакви с ${relative(KOREN, veche.kade)}:${veche.red}`,
        );
      }
    } else {
      blokove.set(klyuch, { kade: f, red: redove[i].red });
    }
  }
}

