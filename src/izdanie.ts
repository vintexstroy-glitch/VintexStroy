export type Stepen = 'alfa' | 'beta' | 'prilozhenie';

export interface Izdanie {
  readonly stepen: Stepen;
  readonly ime: string;
  /** какво носи ТОВА издание — казано на глас, включително непълнотата */
  readonly opis: string;
  readonly gotovo: boolean;
}

/**
 * РЕДЪТ НА ИЗДАНИЯТА · негов, дословно: приложенията идват СЛЕД HTML версията.
 *
 * Изброен е целият, а не само днешният: издание, което не се вижда в реда си,
 * оставя въпроса „а после какво" — и точно него плаща онзи, който купува.
 */
export const IZDANIYA: readonly Izdanie[] = Object.freeze([
  {
    stepen: 'alfa',
    ime: 'Стартъп Алфа',
    opis: 'изцяло работеща HTML версия с непълна функционалност',
    gotovo: true,
  },
  {
    stepen: 'beta',
    ime: 'Стартъп Бета',
    opis: 'същият двигател, попълнена функционалност',
    gotovo: false,
  },
  {
    stepen: 'prilozhenie',
    ime: 'Приложения',
    opis: 'десктоп и телефон — СЛЕД HTML версията',
    gotovo: false,
  },
]);

/** Днешното издание — първото незавършено отгоре надолу. */
export const SEGA: Izdanie = IZDANIYA.find((i) => i.gotovo) ?? IZDANIYA[0]!;

/** Едно изречение за шапката и за доклада. */
export function sDumi(i: Izdanie = SEGA): string {
  return `${i.ime} · ${i.opis}`;
}
