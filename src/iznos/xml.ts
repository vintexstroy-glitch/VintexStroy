/**
 * Екранира текст за XML съдържание и за стойност на атрибут.
 *
 * Управляващите знаци (освен таб, нов ред и връщане) са НЕВАЛИДНИ в XML 1.0 —
 * не се екранират, а се заменят с видим белег: по-добре точка в един ред,
 * отколкото файл, който валидаторът на НАП отхвърля цял, без да каже къде.
 */
export function ekvXML(t: string): string {
  return t
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, '·');
}

/** Един елемент с текст вътре. Празният текст пак дава елемент — не изчезва. */
export function el(ime: string, tekst: string | number): string {
  return `<${ime}>${ekvXML(String(tekst))}</${ime}>`;
}

