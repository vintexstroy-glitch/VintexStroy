/**
 * ТАКТЪТ · кое събитие е ПРЕДИ друго, когато веригите са няколко.
 *
 * ═══ ЗАЩО ИЗОБЩО ТРЯБВА ═══
 *
 * Докато писачът беше един, редът беше `seq`: монотонен, безспорен, вграден в
 * подписа. Станат ли писачите повече, всяка верига тръгва от `seq 1` и
 * броячите им нямат нищо общо помежду си. Трябва наредба МЕЖДУ веригите.
 *
 * ═══ ХИБРИДНИЯТ ЧАСОВНИК · и защо не се добавя нищо към събитието ═══
 *
 * Модерната норма за наредба между писачи без сървър е хибриден логически
 * часовник: физическо време + брояч + номер на писача, като номерът разчупва
 * равенството. Ползват го CockroachDB, MongoDB и YugabyteDB.
 *
 * Тук и трите вече ги ИМА, и трите са ПОДПИСАНИ (`hash.ts` · `kanonichno`):
 *
 *   · `ts`        — физическото време
 *   · `seq`       — броячът, монотонен в рамките на своята верига
 *   · `naematel`  — номерът на писача (ключът на веригата)
 *
 * Затова към събитието не се добавя НИТО ЕДНО поле. Това не е пестеливост:
 * поле за наредба ИЗВЪН подписа решава кое плащане е последно, а неподписано
 * поле, което решава такова нещо, е точно дупката, затворена в ADR-049.
 *
 * ═══ ЗАЩО ТУПЪЛ, А НЕ СЛЕПЕН НИЗ ═══
 *
 * Изкушението е един низ `ts|naematel|seq`, чието азбучно сравнение е и
 * логическото. Отхвърлено: разделителят става част от данните. Ключът на
 * веригата се строи от имейл, а „|" е позволен знак в локалната част по
 * RFC 5322 — тоест някой ден един имейл би могъл да размести наредбата на
 * чужди събития. Сравнението поле по поле няма разделител, значи няма и как
 * да бъде подведено.
 */

import type { Sabitie } from './sabitie.js';

/** Наредбата на едно събитие · трите ѝ части, в тежестта им. */
export interface Takt {
  /** физическото време в милисекунди · `NaN` не се допуска (виж `taktNaSabitie`) */
  readonly kogato: number;
  /** ключът на веригата — той е номерът на писача */
  readonly veriga: string;
  /** броячът в тази верига */
  readonly seq: number;
}

/**
 * Тактът на едно събитие.
 *
 * `ts` се СВЕЖДА до милисекунди, вместо да се сравнява като текст: Вратата
 * иска само „парсимо време", тъй че `2026-08-26` и `2026-08-26T00:00:00.000Z`
 * са еднакво законни, а като текст вторият стои след първия по случайност, не
 * по смисъл. Числото няма този въпрос.
 *
 * Непарсимо време не може да стигне дотук — `proveriValidnost` във Вратата го
 * отказва, преди събитието да се подпише. Стигне ли все пак (внесен файл от
 * чужд ред), пада на НУЛА: непознатото време отива най-отпред, където се вижда,
 * вместо да се пръсне произволно из потока.
 */
export function taktNaSabitie(s: Sabitie): Takt {
  const kogato = Date.parse(s.ts);
  return Object.freeze({
    kogato: Number.isNaN(kogato) ? 0 : kogato,
    veriga: s.naematel,
    seq: s.seq,
  });
}

/**
 * ТОТАЛНА и ДЕТЕРМИНИРАНА наредба.
 *
 * Тотална, защото последният разчупвач е двойката (верига, seq), а тя е
 * уникална по построение: две събития с един и същ ключ на верига и един и същ
 * `seq` са едно и също събитие.
 *
 * Детерминирана, защото не гледа нищо освен подписани полета — редът на
 * подаване на веригите не влиза в сметката. Точно това пази пермутационният
 * тест: разбъркаш ли веригите, потокът излиза БАЙТ ЗА БАЙТ същият.
 */
export function sravniTakt(a: Takt, b: Takt): number {
  if (a.kogato !== b.kogato) return a.kogato - b.kogato;
  if (a.veriga !== b.veriga) return a.veriga < b.veriga ? -1 : 1;
  return a.seq - b.seq;
}

/**
 * Същото, но от събития · за четене и за тестове.
 *
 * ГОРЕЩИЯТ ПЪТ НЕ МИНАВА ОТТУК, и това е измерено, не предположено: сливането
 * прави десетки хиляди сравнения, а всяко викане тук плаща по два `Date.parse`
 * и два замразени обекта. При 10 000 събития в пет вериги това извади 25,2 ms
 * при бюджет 20 — тоест мярката улови собствената ми разсипия.
 *
 * Затова сливането смята такта ВЕДНЪЖ на събитие и после сравнява готовото
 * (`sravniTakt`). Тази функция остава за местата, където яснотата тежи повече
 * от милисекундите.
 */
export function sravniPoTakt(a: Sabitie, b: Sabitie): number {
  return sravniTakt(taktNaSabitie(a), taktNaSabitie(b));
}

/**
 * ФИЗИЧЕСКАТА ЧАСТ на хибридния часовник · моето време не се връща назад.
 *
 * Часовникът на устройството скача: часова зона, ръчна поправка, дрейф на NTP.
 * Скочи ли назад, две мои събития получават `ts` в обратен ред — и понеже
 * `ts` тежи повече от `seq`, собствената ми верига се показва разбъркана.
 *
 * Затова следващото време е `max(сега, последното ми + 1 ms)`. Един милисекунда
 * напред е достатъчно: `seq` е следващият разчупвач и той никога не се
 * повтаря в една верига.
 *
 * Стяга се САМО СВОЯТА верига. Чуждото време не се пипа — то е подписано и
 * поправянето му би било пренаписване на чужд запис.
 */
export function naprediChasovnika(posledenTs: string | undefined, sega: string): string {
  if (posledenTs === undefined) return sega;
  const predi = Date.parse(posledenTs);
  const tozi = Date.parse(sega);
  if (Number.isNaN(predi) || Number.isNaN(tozi)) return sega;
  return tozi > predi ? sega : new Date(predi + 1).toISOString();
}
