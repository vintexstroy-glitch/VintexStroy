/**
 * ДУМИТЕ НА ЕДНА ГРЕШКА · един дом за израза, преписан 28 пъти.
 *
 * Грешка с име носи `message`; всичко друго се казва както е.
 *
 * **Класове НЕ се изброяват поименно.** Изглежда точно и е капан: списък от
 * два-три класа пада на `String(err)` за всеки следващ и залепва ЛАТИНСКОТО
 * име на класа пред българското изречение. Така отказът на замразен период
 * се четеше „GreshkaZamrazen: Периодът е заключен…", а пропуснатият ред в
 * таблица — „GreshkaVrata: …". Платено със седем намерени места.
 */
export function dumiZaGreshka(e: unknown): string {
  return e instanceof Error ? e.message : String(e);
}
