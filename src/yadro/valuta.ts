/**
 * ВАЛУТАТА · ДВЕ, избира се ЕДНА, и не се сменя.
 *
 * Негова дума (И96, 25.08): „**Левът вече не съществува.** Използвай евро и
 * долар, и двете май са с центове. И да се изписва спрямо нормите за евро и за
 * долар. Засега да е с евро и долар за начало."
 *
 * ЗАЩО ТОВА НЕ ВРЪЩА СВАЛЕНАТА МАШИНАРИЯ. На 23.08 оттук паднаха осем валути,
 * `Paket.valuti` и цял слой избор — защото валутата беше ЕДНА и никой не викаше
 * тези неща. Сега изборът е ИСТИНСКИ: две валути, всяка със свои норми на
 * изписване. Но онова, което падна тогава, си остава паднало — **курс няма**.
 * Валутата се избира при регистрация, Журналът се пише в нея, и толкова.
 * Смяна в движение би преоценила всяко записано число.
 *
 * НОРМИТЕ НА ИЗПИСВАНЕ ЖИВЕЯТ ТУК, НЕ В ЕКРАНА. Дотук `kakvoPishe` беше заковал
 * българските правила в кода си: запетая за дробните, тясна пауза за хилядите,
 * знак накрая. Долар, изписан по тези правила, дава „1 234,56 $" — което не е
 * долар, а евро с чужд знак. Затова всяка валута носи СВОИТЕ три правила:
 * къде стои знакът, какво дели хилядите и какво дели дробните.
 *
 * КЪДЕ ОТИДЕ ВИДЪТ НА КОЛОНАТА. Той си остана в колоната: `VidStoynost` в
 * `src/domein/vid-stoynost.ts` казва дали колоната е пари, процент, число,
 * текст или дата. Валутата казва КАК се пишат парите; колоната — КОИ са пари.
 *
 * ЗА НАЙ-МАЛКАТА ЕДИНИЦА, честно. Всичко, което човек ВИЖДА, е в цели единици.
 * Но вътре се пази най-малката, защото ДДС, изваден от обща цена, ражда центове:
 * без тях инвариантът „основа + ДДС == обща" пада, а с него и правило 7.
 */

export interface Valuta {
  /** ISO кодът — по него се сверява, не по знака */
  readonly kod: string;
  readonly znak: string;
  readonly ime: string;
  /** колко най-малки единици прави една цяла (за евро и долар: 100) */
  readonly drobni: number;
  /** стои ли знакът ПРЕД числото · „$1,234.56" срещу „1 234,56 €" */
  readonly predi: boolean;
  /** какво дели хилядите · тясна пауза при евро, запетая при долар */
  readonly hilyadi: string;
  /** какво дели дробните · запетая при евро, точка при долар */
  readonly drobenZnak: string;
}

/** Евро · знакът отзад, тясна пауза за хилядите, запетая за дробните. */
export const EVRO: Valuta = Object.freeze({
  kod: 'EUR',
  znak: '€',
  ime: 'евро',
  drobni: 100,
  predi: false,
  hilyadi: '\u202F',
  drobenZnak: ',',
});

/** Долар · знакът ОТПРЕД, запетая за хилядите, ТОЧКА за дробните. */
export const DOLAR: Valuta = Object.freeze({
  kod: 'USD',
  znak: '$',
  ime: 'долар',
  drobni: 100,
  predi: true,
  hilyadi: ',',
  drobenZnak: '.',
});

/**
 * ДВЕТЕ · изброени ПОИМЕННО. Трета се добавя ТУК, където се вижда, и заедно
 * със своите норми на изписване — не само със знак.
 */
export const VALUTI: readonly Valuta[] = Object.freeze([EVRO, DOLAR]);

const PO_KOD = new Map(VALUTI.map((v) => [v.kod, v]));

/**
 * Валутата по ISO код. Непознат код се отказва С ДУМИ, не пада към евро:
 * тиха замяна тук значи числа, прочетени в грешна валута — и никой не разбира.
 */
export function valuta(kod: string): Valuta {
  const v = PO_KOD.get(kod.trim().toUpperCase());
  if (!v) {
    throw new RangeError(
      `Няма валута „${kod}". Има: ${VALUTI.map((x) => `${x.kod} (${x.ime})`).join(' · ')}.`,
    );
  }
  return v;
}

/**
 * ТРИТЕ ТОЧНОСТИ · негови, дословно:
 *
 *   „Цените, които са за продажба, се закръглят на ЦЯЛО; за сметките —
 *    закръглени на СТОТИЦИ евро."
 *   „Цените НАГОРЕ, сметките към най-близкото."
 *
 * `tochno` е как се ПАЗИ — Журналът, ДДС-то и сверките не закръглят никога.
 *
 * ЗАЩО ВАЛУТАТА СЕ ПОДАВА, щом евро и долар са и двете със сто цента: защото
 * дотук тук пишеше `EVRO.drobni` направо — закована валута вътре в сметка, която
 * се представя за обща. Днес не боли; в деня, в който влезе валута с друга
 * дробна част, ще заболи тихо. Подадена, тя не може да се размине.
 */
export type Tochnost = 'tochno' | 'tsyalo' | 'stotitsi';

/**
 * Закръгля сума (в най-малки единици) до поисканата точност.
 *
 * ЗАКОНЪТ: закръгленото НИКОГА не влиза в сбор. Сумата се смята точно и се
 * закръгля веднъж, накрая — сбор от закръглени числа не е закръглен сбор.
 * Пази го `tests/valuta.test.ts`, не дисциплината.
 *
 * Посоките са различни НАРОЧНО:
 *   `tsyalo`   — цените · НАГОРЕ  (продажна цена не пада от закръгляне)
 *   `stotitsi` — сметките · към НАЙ-БЛИЗКОТО (отчетът не лъже системно нагоре)
 */
export function zakragli(suma: number, t: Tochnost, v: Valuta = EVRO): number {
  if (!Number.isSafeInteger(suma)) {
    throw new RangeError(`Закръгля се цяла сума в най-малки единици; получено: ${suma}`);
  }
  if (t === 'tochno') return suma;

  if (t === 'tsyalo') {
    // цените · НАГОРЕ — по абсолютна стойност, за да не „порасне" разход
    const kam = v.drobni;
    const znak = suma < 0 ? -1 : 1;
    return znak * Math.ceil(Math.abs(suma) / kam) * kam;
  }

  // сметките · СТОТИЦИ, към най-близкото; на точната среда — далече от нулата,
  // както човек закръгля на ръка (149 50 → 100, 150 00 → 200)
  const kam = 100 * v.drobni;
  const znak = suma < 0 ? -1 : 1;
  return znak * Math.round(Math.abs(suma) / kam) * kam;
}

/**
 * ЦЕНАТА НАГОРЕ ДО СТОТИЦА · изходът на Калкулатора.
 *
 * Негово: „Закръгля се от калкулатора и участва с ЦЯЛА СУМА ДО СТОТИЦА." ·
 * „Цените НАГОРЕ." Двете заедно дават една посока, а неговата собствена ценова
 * листа я потвърждава: всяка цена там завършва на две нули (215 400 · 224 800 ·
 * 38 700 · 72 500). Затова цената е отделна функция, не трета точност — тя е
 * решение на Калкулатора, а не начин на показване.
 */
export function tsenaNagore(suma: number, v: Valuta = EVRO): number {
  if (!Number.isSafeInteger(suma)) {
    throw new RangeError(`Закръгля се цяла сума в най-малки единици; получено: ${suma}`);
  }
  const kam = 100 * v.drobni;
  const znak = suma < 0 ? -1 : 1;
  return znak * Math.ceil(Math.abs(suma) / kam) * kam;
}

/**
 * Колко „изяде" закръглянето — за да се ВИЖДА, не да се преглъща.
 *
 * Правило 7: когато Сметки показват стотици, разликата с точното се изписва
 * („закръглено: −33 €"), иначе сверката вход↔изход изглежда счупена, а е точна.
 */
export function razlikaOtZakraglyane(suma: number, t: Tochnost, v: Valuta = EVRO): number {
  return zakragli(suma, t, v) - suma;
}
