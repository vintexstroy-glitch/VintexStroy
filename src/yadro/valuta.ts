/**
 * ВАЛУТАТА · сумата носи валутата си.
 *
 * Негово решение от 12.08, взето РАНО нарочно:
 *
 *   „Валутата — единственото, което е скъпо да се добави по-късно. СУМАТА НОСИ
 *    ВАЛУТАТА СИ (+30, глобално готово) ★"
 *
 * И от 23.08, за модела на Винтекс:
 *
 *   „ЛЕВ НЯМА. Моделът на Винтекс избира да се ползва думата и знакът за Евро.
 *    ПРИ СЪЗДАВАНЕ се избира азбука с език и валута, която се използва в
 *    сметките."
 *
 * КАК СУМАТА НОСИ ВАЛУТАТА СИ, без да се пипне всеки запис: валутата се избира
 * ВЕДНЪЖ при създаване и влиза в Журнала като събитие. Оттам всяка сума в този
 * Журнал е в нея — носи я през Журнала, в който живее. Журнал с една валута не
 * сменя валутата си: това би преоценило историята.
 *
 * ЗА НАЙ-МАЛКАТА ЕДИНИЦА, честно. Негова дума: „пишеш в евро, не в евроцента"
 * — и всичко, което човек ВИЖДА, е в евро. Но вътре се пази най-малката
 * единица, защото ДДС, изваден от обща цена, ражда центове: без тях инвариантът
 * „основа + ДДС == обща" пада, а с него и правило 7. Пази се точно, показва се
 * в евро.
 */

export interface Valuta {
  /** ISO кодът — по него се сверява, не по знака */
  readonly kod: string;
  readonly znak: string;
  readonly ime: string;
  /** колко най-малки единици прави една цяла (за евро: 100) */
  readonly drobni: number;
}

export const EVRO: Valuta = Object.freeze({ kod: 'EUR', znak: '€', ime: 'евро', drobni: 100 });

/**
 * Валутите, които изобщо се предлагат — по една на ред, изброени поименно.
 * Коя от тях вижда човекът при създаване, казва ПАКЕТЪТ (`domein/azbuki.ts`).
 */
export const VALUTI: readonly Valuta[] = Object.freeze([
  EVRO,
  { kod: 'PLN', znak: 'zł', ime: 'злота', drobni: 100 },
  { kod: 'CZK', znak: 'Kč', ime: 'крона', drobni: 100 },
  { kod: 'RON', znak: 'lei', ime: 'лея', drobni: 100 },
  { kod: 'TRY', znak: '₺', ime: 'лира', drobni: 100 },
  { kod: 'UAH', znak: '₴', ime: 'гривня', drobni: 100 },
  { kod: 'GBP', znak: '£', ime: 'паунд', drobni: 100 },
  { kod: 'CHF', znak: 'Fr', ime: 'франк', drobni: 100 },
]);

const PO_KOD = new Map(VALUTI.map((v) => [v.kod, v]));

/** Непознат код пада към еврото — моделът на Винтекс. */
export function valuta(kod: string | null | undefined): Valuta {
  return (kod && PO_KOD.get(kod)) || EVRO;
}

/**
 * ТРИТЕ ТОЧНОСТИ · негови, дословно:
 *
 *   „Цените, които са за продажба, се закръглят на ЦЯЛО; за сметките —
 *    закръглени на СТОТИЦИ евро."
 *   „Цените НАГОРЕ, сметките към най-близкото."
 *
 * `tochno` е как се ПАЗИ — Журналът, ДДС-то и сверките не закръглят никога.
 */
export type Tochnost = 'tochno' | 'tsyalo' | 'stotitsi';

/**
 * Закръгля сума (в най-малки единици) до поисканата точност.
 *
 * ЗАКОНЪТ: закръгленото НИКОГА не влиза в сбор. Сумата се смята точно и се
 * закръгля веднъж, накрая — сбор от закръглени числа не е закръглен сбор.
 * Пази го tests/zakragliane.test.ts, не дисциплината.
 *
 * Посоките са различни НАРОЧНО:
 *   `tsyalo`   — цените · НАГОРЕ  (продажна цена не пада от закръгляне)
 *   `stotitsi` — сметките · към НАЙ-БЛИЗКОТО (отчетът не лъже системно нагоре)
 */
export function zakragli(suma: number, t: Tochnost, v: Valuta = EVRO): number {
  if (!Number.isSafeInteger(suma)) {
    throw new RangeError(`Закръгля се цяла сума в най-малки единици; получено: ${suma}`);
  }
  if (t === 'tochno') return suma;

  if (t === 'tsyalo') {
    // цените · НАГОРЕ — по абсолютна стойност, за да не „порасне" разход
    const kam = v.drobni;
    const znak = suma < 0 ? -1 : 1;
    return znak * Math.ceil(Math.abs(suma) / kam) * kam;
  }

  // сметките · СТОТИЦИ, към най-близкото; на точната среда — далече от нулата,
  // както човек закръгля на ръка (149 50 → 100, 150 00 → 200)
  const kam = 100 * v.drobni;
  const znak = suma < 0 ? -1 : 1;
  return znak * Math.round(Math.abs(suma) / kam) * kam;
}

/**
 * Колко „изяде" закръглянето — за да се ВИЖДА, не да се преглъща.
 *
 * Правило 7: когато Сметки показват стотици, разликата с точното се изписва
 * („закръглено: −33 €"), иначе сверката вход↔изход изглежда счупена, а е точна.
 */
export function razlikaOtZakraglyane(suma: number, t: Tochnost, v: Valuta = EVRO): number {
  return zakragli(suma, t, v) - suma;
}
