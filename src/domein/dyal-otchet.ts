/**
 * ГОТОВИТЕ ПЕРИОДИ · неговата дума *(р75·[64])*: „Да се добавят и бутони за
 * избор на готов период от време."
 *
 * Три, не десет: последните дванайсет месеца (подразбираното досега, вече с
 * име), тази година и миналата. Смятат се от „днес" — закован период щеше да
 * остарее с календара (урокът на §91).
 */
export interface GotovPeriod {
  readonly klyuch: string;
  readonly ime: string;
  readonly ot: string;
  readonly do: string;
}

export function gotovitePeriodi(dnes: string): readonly GotovPeriod[] {
  const g = Number(dnes.slice(0, 4));
  const m = dnes.slice(5, 7);
  return Object.freeze([
    {
      klyuch: 'dvanayset',
      ime: 'последните 12 месеца',
      ot: `${g - 1}-${m}-01`,
      do: dnes,
    },
    { klyuch: 'tazi', ime: `тази година`, ot: `${g}-01-01`, do: dnes },
    {
      klyuch: 'minalata',
      ime: `миналата година`,
      ot: `${g - 1}-01-01`,
      do: `${g - 1}-12-31`,
    },
  ]);
}

