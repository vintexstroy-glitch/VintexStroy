/**
 * КЛЮЧЪТ НА АКАУНТА · кой Журнал се отваря.
 *
 * Вторият критерий на матрицата (ADR-007) е КОЛКО АКАУНТА. Дотук отговорът в
 * кода беше един закован ред — `const NAEMATEL = 'vintexstroy'` — и заради него
 * вторият акаунт не съществуваше, колкото и планът да го позволява.
 *
 * ЕДНА ДУМА, ДВА СМИСЪЛА — и това е капанът, който плати този резен:
 *
 *   `naematel`  — ЧИЙ Е ЖУРНАЛЪТ · ключът, който дели моите записи от чуждите
 *   `naemetel`  — ЧОВЕКЪТ, който плаща наема (`Naem.naemetel`)
 *
 * Различават се с ЕДНА буква и значат несвързани неща. Затова новото се пише с
 * думата „акаунт": `klyuchNaAkaunta`. Полето в събитието остава `naematel`,
 * защото **влиза в хеша** (`yadro/hash.ts` · `kanonichno`) — преименуването му
 * би счупило веригата на всеки вече записан Журнал (правило 4).
 *
 * ЗАЩО ИМЕЙЛЪТ Е КЛЮЧЪТ. Самоличността идва от доставчика и приложението няма
 * своя (правило 13 · ADR-004). Имейлът е единственото, което доставчикът дава и
 * което не се мени зад гърба ни — а и вече се записва като `actor`.
 */

import type { Samolichnost } from '../yadro/samolichnost.js';

export class GreshkaAkaunt extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'GreshkaAkaunt';
  }
}

/**
 * КЛЮЧЪТ НА АЛФА · първият Журнал, писан преди този резен.
 *
 * Той е записан под „vintexstroy" и **не се преселва**: `naematel` влиза в
 * хеша, значи преписването му е ново съдържание на старо събитие — точно това,
 * което правило 1 и правило 4 забраняват.
 *
 * Затова ключът не е „кой съм аз", а „кой Журнал вече съществува тук".
 * Съществуващият се отваря с името, с което е роден; новите тръгват с имейл.
 */
export const KLYUCH_OT_ALFA = 'vintexstroy';

/**
 * Имейлът, сведен до ЕДИН вид.
 *
 * „Ivo@Gmail.com" и „ivo@gmail.com" са един и същ акаунт при Google, но два
 * различни низа — а два низа значат два Журнала и тихо изчезнала история.
 *
 * NFC, защото Вратата така пази всичко (правило 12): едно „й" = един запис.
 * Малки букви, защото доставчиците не различават регистъра в адреса.
 */
export function svediImeyl(imeyl: string): string {
  return imeyl.normalize('NFC').trim().toLowerCase();
}

/**
 * Ключът на акаунта за един влязъл човек.
 *
 * Хвърля при празен имейл, вместо да върне празен низ: празният ключ би отворил
 * „акаунта на никого" — Журнал, който се пише, но никой не намира после.
 */
export function klyuchNaAkaunta(s: Samolichnost): string {
  const imeyl = svediImeyl(s.imeyl);
  if (imeyl === '') {
    throw new GreshkaAkaunt('Без имейл няма акаунт — доставчикът не е върнал самоличност.');
  }
  return imeyl;
}

/**
 * КОЙ ЖУРНАЛ СЕ ОТВАРЯ · единственото място, където се решава.
 *
 * Редът е нарочен и е обратен на очакваното: първо се пита „има ли тук вече
 * Журнал от Алфа", и чак после „кой съм аз". Обратният ред би оставил първия
 * Журнал невидим в мига, в който истинският вход тръгне — данните му ще са на
 * диска, но под ключ, който никой повече не пита.
 *
 * `imaZhurnalOtAlfa` идва отвън (от носителя), защото този модул не чете диск.
 */
export function koyZhurnal(s: Samolichnost, imaZhurnalOtAlfa: boolean): string {
  return imaZhurnalOtAlfa ? KLYUCH_OT_ALFA : klyuchNaAkaunta(s);
}

/**
 * Кратко за екрана: под кой ключ работи приложението в момента.
 *
 * Показва се в Таблото. Ключ, който не се вижда никъде, е точно онова, което
 * прави „къде ми отидоха данните" неотговорим въпрос.
 */
export function sDumiZaAkaunta(klyuch: string): string {
  return klyuch === KLYUCH_OT_ALFA
    ? `${klyuch} · първият Журнал, от Стартъп Алфа`
    : `${klyuch} · акаунт по имейл`;
}
