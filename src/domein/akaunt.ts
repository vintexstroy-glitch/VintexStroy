/**
 * КЛЮЧЪТ НА АКАУНТА · кой Журнал се отваря.
 *
 * Вторият критерий на матрицата (ADR-007) е КОЛКО АКАУНТА. Дотук отговорът в
 * кода беше един закован ред — `const NAEMATEL = 'vintexstroy'` — и заради него
 * вторият акаунт не съществуваше, колкото и планът да го позволява.
 *
 * ЕДНА ДУМА, ДВА СМИСЪЛА — и това е капанът, който плати този резен:
 *
 *   `naematel`  — ЧИЙ Е ЖУРНАЛЪТ · ключът, който дели моите записи от чуждите
 *   `naemetel`  — ЧОВЕКЪТ, който плаща наема (`Naem.naemetel`)
 *
 * Различават се с ЕДНА буква и значат несвързани неща. Затова новото се пише с
 * думата „акаунт": `klyuchNaAkaunta`. Полето в събитието остава `naematel`,
 * защото **влиза в хеша** (`yadro/hash.ts` · `kanonichno`) — преименуването му
 * би счупило веригата на всеки вече записан Журнал (правило 4).
 *
 * ЗАЩО ИМЕЙЛЪТ Е КЛЮЧЪТ. Самоличността идва от доставчика и приложението няма
 * своя (правило 13 · ADR-004). Имейлът е единственото, което доставчикът дава и
 * което не се мени зад гърба ни — а и вече се записва като `actor`.
 */

import type { Samolichnost } from '../yadro/samolichnost.js';

export class GreshkaAkaunt extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'GreshkaAkaunt';
  }
}

/**
 * КЛЮЧЪТ НА АЛФА · първият Журнал, писан преди този резен.
 *
 * Той е записан под „vintexstroy" и **не се преселва**: `naematel` влиза в
 * хеша, значи преписването му е ново съдържание на старо събитие — точно това,
 * което правило 1 и правило 4 забраняват.
 *
 * Затова ключът не е „кой съм аз", а „кой Журнал вече съществува тук".
 * Съществуващият се отваря с името, с което е роден; новите тръгват с имейл.
 */
export const KLYUCH_OT_ALFA = 'vintexstroy';

/**
 * Имейлът, сведен до ЕДИН вид.
 *
 * „Ivo@Gmail.com" и „ivo@gmail.com" са един и същ акаунт при Google, но два
 * различни низа — а два низа значат два Журнала и тихо изчезнала история.
 *
 * NFC, защото Вратата така пази всичко (правило 12): едно „й" = един запис.
 * Малки букви, защото доставчиците не различават регистъра в адреса.
 */
export function svediImeyl(imeyl: string): string {
  return imeyl.normalize('NFC').trim().toLowerCase();
}

/**
 * Ключът на акаунта за един влязъл човек.
 *
 * Хвърля при празен имейл, вместо да върне празен низ: празният ключ би отворил
 * „акаунта на никого" — Журнал, който се пише, но никой не намира после.
 */
export function klyuchNaAkaunta(s: Samolichnost): string {
  const imeyl = svediImeyl(s.imeyl);
  if (imeyl === '') {
    throw new GreshkaAkaunt('Без имейл няма акаунт — доставчикът не е върнал самоличност.');
  }
  return imeyl;
}

/**
 * КОЙ ЖУРНАЛ СЕ ОТВАРЯ · единственото място, където се решава.
 *
 * Редът е нарочен и е обратен на очакваното: първо се пита „има ли тук вече
 * Журнал от Алфа", и чак после „кой съм аз". Обратният ред би оставил първия
 * Журнал невидим в мига, в който истинският вход тръгне — данните му ще са на
 * диска, но под ключ, който никой повече не пита.
 *
 * `imaZhurnalOtAlfa` идва отвън (от носителя), защото този модул не чете диск.
 */
export function koyZhurnal(
  s: Samolichnost,
  imaZhurnalOtAlfa: boolean,
  /**
   * ВЪРНАТИЯТ ЖУРНАЛ · ключът на архив, взет с запасния контакт (И100).
   *
   * Подава се САМО след като е ДОКАЗАН: приложението отваря онзи ключ, но
   * преди това чете веригата му и проверява, че сегашният ѝ стопанин съм аз.
   * Тоест този довод е ПОКАЗАЛЕЦ, не право — правото стои в самия Журнал.
   */
  vrasten?: string,
): string {
  if (vrasten) return vrasten;
  return imaZhurnalOtAlfa ? KLYUCH_OT_ALFA : klyuchNaAkaunta(s);
}

/**
 * ЛИЧНИЯТ КЛЮЧ · вторият Журнал на СЪЩИЯ човек (И98).
 *
 * Негово: „Има си и отделен журнал когато се е активирал личния и НИКОГА не
 * се смесват." Отделен журнал значи отделен НАЕМАТЕЛ: `naematel` влиза в хеша
 * (правило 4), носителят е ключиран по него, Вратата отказва чужд наемател —
 * смесването става ФИЗИЧЕСКИ невъзможно, не „непрепоръчително".
 *
 * НАСТАВКА В КРАЯ, не представка. „#" е позволен знак в ЛОКАЛНАТА част на
 * имейл (RFC 5322), но НЕ и в домейна — значи легален имейл никога не
 * ЗАВЪРШВА на „#lichen" и сблъсък между сведен имейл и личен ключ е
 * невъзможен по конструкция, не по договорка. И наредбата помага: в носителя
 * (keyPath по наемател) личният Журнал ляга ДО служебния си близнак.
 *
 * СТРОИ СЕ ОТ ИМЕЙЛА НА ЧОВЕКА, никога от ключа на отворения Журнал: на това
 * устройство отвореният може да е Алфа-ключът на ФИРМАТА (`vintexstroy`), а
 * личното е на ВСЕКИ служител поотделно (И98 т.3).
 */
export const NASTAVKA_LICHEN = '#lichen';

export function klyuchNaLichniya(s: Samolichnost): string {
  return `${klyuchNaAkaunta(s)}${NASTAVKA_LICHEN}`;
}

export function eLichenKlyuch(klyuch: string): boolean {
  return klyuch.endsWith(NASTAVKA_LICHEN);
}

/** Служебният близнак на един личен ключ — за разписките на преноса. */
export function sluzhebniyatNa(lichenKlyuch: string): string {
  return eLichenKlyuch(lichenKlyuch)
    ? lichenKlyuch.slice(0, -NASTAVKA_LICHEN.length)
    : lichenKlyuch;
}

/**
 * ВЕРИГАТА НА ПИСАЧА · вторият писач в ЕДНА книга (ADR-055).
 *
 * Дотук книгата имаше точно една верига и ключът ѝ беше ключът на акаунта.
 * Влезе ли служител със своя имейл, той трябва да пише в СЪЩАТА книга, но в
 * СВОЯ append-only верига — нищо не се слива, нищо не се преномерира.
 *
 * НАСТАВКА, по калъпа на личния ключ, и по същата причина: „#" е позволен знак
 * в ЛОКАЛНАТА част на имейл (RFC 5322), но не и в домейна, значи сведен имейл
 * никога не съдържа „#pero:" и сблъсък между книга и верига е невъзможен по
 * конструкция. И в носителя (keyPath по наемател) веригите на една книга лягат
 * ЕДНА ДО ДРУГА, вместо да се пръснат по азбуката на имейлите.
 *
 * ДВОЕТОЧИЕТО е нарочно: без него `knigataNa` не различава наставката от
 * начало на имейл, а с него краят на наставката е еднозначен.
 */
export const NASTAVKA_PISACH = '#pero:';

/**
 * ВЕРИГАТА-НУЛА не се мигрира (ADR-055).
 *
 * Стопанинът пише там, където книгата вече се пише — под голия ключ на
 * книгата, без наставка. Всеки друг получава своя. Ако беше обратното (и
 * стопанинът с наставка), всяко вече записано събитие щеше да смени веригата
 * си, тоест `naematel` в хеша — правило 1 и правило 4 наведнъж.
 *
 * Кой е стопанинът НЕ се гадае тук: извежда се от първото събитие на книгата
 * (ADR-043) и се подава отвън. Непознат стопанин (нова, още празна книга)
 * значи „аз съм първият" — веригата-нула, а трите правила при Вратата решават
 * дали това е вярно.
 */
export function klyuchNaVerigata(
  kniga: string,
  imeyl: string,
  stopaninat: string | undefined,
): string {
  const moyat = svediImeyl(imeyl);
  if (moyat === '') {
    throw new GreshkaAkaunt('Без имейл няма верига — доставчикът не е върнал самоличност.');
  }
  if (eVerigaNaPisach(kniga)) {
    throw new GreshkaAkaunt(`„${kniga}" вече е верига на писач — книга не се прави от верига.`);
  }
  if (stopaninat === undefined || svediImeyl(stopaninat) === moyat) return kniga;
  if (eLichenKlyuch(kniga)) {
    throw new GreshkaAkaunt('Личният Журнал няма втори писач — той е на един човек (И98).');
  }
  return `${kniga}${NASTAVKA_PISACH}${moyat}`;
}

export function eVerigaNaPisach(klyuch: string): boolean {
  return klyuch.includes(NASTAVKA_PISACH);
}

/** Коя КНИГА е това · веригата на писача сочи книгата, в която стои. */
export function knigataNa(klyuch: string): string {
  const kray = klyuch.indexOf(NASTAVKA_PISACH);
  return kray === -1 ? klyuch : klyuch.slice(0, kray);
}

/** Чия е веригата · `undefined` за веригата-нула, чийто писач е стопанинът. */
export function pisachatNa(klyuch: string): string | undefined {
  const kray = klyuch.indexOf(NASTAVKA_PISACH);
  return kray === -1 ? undefined : klyuch.slice(kray + NASTAVKA_PISACH.length);
}

/**
 * Кратко за екрана: под кой ключ работи приложението в момента.
 *
 * Показва се в Таблото. Ключ, който не се вижда никъде, е точно онова, което
 * прави „къде ми отидоха данните" неотговорим въпрос.
 */
export function sDumiZaAkaunta(klyuch: string): string {
  const pisach = pisachatNa(klyuch);
  if (pisach !== undefined) {
    return `${knigataNa(klyuch)} · моята верига в тази книга (${pisach}) · чуждите се четат, не се пишат`;
  }
  if (klyuch === KLYUCH_OT_ALFA) return `${klyuch} · първият Журнал, от Стартъп Алфа`;
  if (eLichenKlyuch(klyuch)) return `${klyuch} · ЛИЧНИЯТ Журнал · никога не се смесва със служебния`;
  return `${klyuch} · акаунт по имейл`;
}
