/**
 * ЕЗИЦИТЕ · кой избира какво, и кога.
 *
 * Думите на собственика:
 *
 *   „Индивидуално за служителя се избира езикът на интерфейса. А счетоводният
 *    терминал е избор и създаден на език ПРИ ИНСТАЛИРАНЕТО, от избор на
 *    създателя на ГЛАВНИЯ акаунт. За останалите е само избор на езика на
 *    интерфейса на служителите — ТАМ НЯМА ФИЛТЪР ЗА ПРАВА."
 *
 * Оттук три неща:
 *
 *   1. ДВЕ РАЗЛИЧНИ РЕШЕНИЯ. Езикът на ТЕРМИНАЛА се заковава веднъж, при
 *      инсталиране, от главния акаунт. Езикът на ИНТЕРФЕЙСА е на всеки
 *      служител поотделно и се сменя когато си иска.
 *
 *   2. ИЗБОРЪТ НА ЕЗИК НЕ Е ПРАВО. Няма го във `Vazmozhnost`, няма отметка на
 *      Таблото, не се раздава от никого. На какъв език четеш бутоните не е
 *      привилегия — тест го пази.
 *
 *   3. ЕЗИК ≠ ЮРИСДИКЦИЯ. Счетоводните термини НЕ се превеждат: „сторно",
 *      „ДДС", „справка" не са думи, а членове от български закон. Затова
 *      терминалът се заковава — преведеш ли го, обещаваш чужда данъчна
 *      система, каквато двигателят няма.
 *
 * Днес тук стои само българският. Таблицата съществува, за да е ясно КЪДЕ
 * влизат езиците и КОЙ КАКВО избира — изваждането на низовете е свой резен.
 */

import type { Podmnozhestvo } from './azbuki.js';

export interface Ezik {
  readonly klyuch: string;
  /** името на СОБСТВЕНИЯ му език — не преведено */
  readonly ime: string;
  /** коя азбука иска — сверява се срещу пакета от `azbuki.ts` */
  readonly azbuka: Podmnozhestvo;
}

export const EZITSI: readonly Ezik[] = Object.freeze([
  { klyuch: 'bg', ime: 'Български', azbuka: 'cyrillic' },
]);

/** Езикът на терминала и подразбираният за интерфейса. */
export const EZIK_PO_PODRAZBIRANE = 'bg';

const PO_KLYUCH = new Map(EZITSI.map((e) => [e.klyuch, e]));

/** Непознат език пада към българския — по-добре разбираемо, отколкото празно. */
export function ezik(klyuch: string | null | undefined): Ezik {
  return PO_KLYUCH.get(klyuch ?? '') ?? PO_KLYUCH.get(EZIK_PO_PODRAZBIRANE)!;
}

/**
 * ЕЗИКЪТ НА СЧЕТОВОДНИЯ ТЕРМИНАЛ · закован при инсталиране.
 *
 * Взема се ВЕДНЪЖ, от създателя на главния акаунт, и не се сменя после.
 * Причината е в §3 горе: термините са правни понятия, не надписи.
 */
export function ezikNaTerminala(zakovan: string | null | undefined): Ezik {
  return ezik(zakovan);
}

/**
 * ЕЗИКЪТ НА ИНТЕРФЕЙСА · на всеки служител поотделно.
 *
 * Няма филтър, няма право, няма кой да го раздава. Всеки си го избира — и
 * затова е отделен от терминала.
 */
export function ezikNaSluzhitelya(izbran: string | null | undefined): Ezik {
  return ezik(izbran);
}
