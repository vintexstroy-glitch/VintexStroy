/**
 * Петте вида, изброени поименно. Нов вид се добавя ТУК, където се вижда.
 *
 * Списъкът е СТОЙНОСТ, не само тип: съюзът се извежда от него, а не се пише
 * втори път. Два списъка на едно нещо се разминават — тук се разминаваха
 * мълчешком, защото `Record<VidStoynost, …>` изисква пълнота само по типа,
 * а типът и списъкът бяха два отделни реда.
 */
export const VIDOVE_STOYNOST = ['evro', 'protsent', 'chislo', 'tekst', 'data'] as const;

export type VidStoynost = (typeof VIDOVE_STOYNOST)[number];

export const IMENA_NA_VIDOVETE_STOYNOST: Readonly<Record<VidStoynost, string>> = Object.freeze({
  evro: 'евро',
  protsent: 'процент',
  chislo: 'число',
  tekst: 'текст',
  data: 'дата',
});

/** Как изглежда колоната в главата си — знакът след числото. */
export const ZNAK_NA_VIDA: Readonly<Record<VidStoynost, string>> = Object.freeze({
  evro: '€',
  protsent: '%',
  chislo: '',
  tekst: '',
  data: '',
});

/**
 * САМО ЕВРОТО ВЛИЗА В ДВАТА СБОРА.
 *
 * Оттук идва „сумата от колоните С ВАЛУТА" в неговото изречение. Процентът е
 * ставка — сборът на процентите е число без смисъл. Числото е брой или площ —
 * сборът му е брой или площ, не пари.
 */
export function ePari(v: VidStoynost): boolean {
  return v === 'evro';
}

/** Изобщо число ли е — за филтрите и за подредбата, не за сборовете. */
export function eChislo(v: VidStoynost): boolean {
  return v === 'evro' || v === 'protsent' || v === 'chislo';
}

/**
 * ПОДСКАЗКА по заглавието на колоната · ПРЕДЛОЖЕНИЕ, не решение.
 *
 * Човекът потвърждава в Редактора на хедъри. Същото място, на което утре ще
 * застане ИИ-то (правило 18: агентът предлага, човекът записва).
 *
 * Речникът е нарочно КЪС и български: дълъг речник познава повече и греши
 * повече, а грешка тук вкарва чуждо число в сбора на парите.
 */
const DUMI: Readonly<Record<VidStoynost, readonly string[]>> = Object.freeze({
  evro: [
    'сума', 'цена', 'наем', 'стойност', 'салдо', 'депозит', 'вноска', 'заплата',
    'такса', 'комисион', 'разход', 'приход', 'оборот', 'плащане', 'дадени',
    'ддс', 'капаро', 'нотариус', 'кредит', '€', 'евро',
  ],
  protsent: ['%', 'процент', 'ставка', 'дял', 'лихва'],
  chislo: ['брой', 'площ', 'кв', 'м2', 'м²', 'дни', 'стаи', 'етаж', 'номер', '№'],
  data: ['дата', 'падеж', 'срок'],
  tekst: [],
});

export function podskazhiVid(zaglavie: string): VidStoynost {
  const g = zaglavie.trim().toLowerCase();
  if (g === '') return 'tekst';
  // Редът е нарочен: датата и процентът бият еврото, защото „сума на ДДС" и
  // „дата на плащане" носят и двете думи, а по-тясната печели.
  for (const v of ['data', 'protsent', 'evro', 'chislo'] as const) {
    if (DUMI[v].some((d) => g.includes(d))) return v;
  }
  return 'tekst';
}
