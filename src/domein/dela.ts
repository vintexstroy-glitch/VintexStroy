/**
 * ДЕЛАТА · Място → Обект → Дело, плоско, с филтри.
 *
 * Негово преименуване, дословно *(р52·[269]·08.08)*:
 *
 *   „Навсякъде заменяш Проект с Място, за Задача навсякъде заменяй с Дело."
 *
 * И устройството *(И82 · 23.08, потвърждаващо р57·[150])*: Управление е
 * **ТРИ КОЛОНИ С ФИЛТРИ**, не три нива. Място, Обект и Дело са колони на един
 * ред — всяка със своя номенклатура и свой филтър. Йерархия няма.
 *
 * ЗАЩО ТОВА Е ВАЖНО. Три нива значат дърво: за да стигнеш до дело, минаваш през
 * място и обект. Три колони значат таблица: филтрираш по която искаш, в който
 * ред искаш. Второто е това, което той поиска — и то е причината делото да може
 * да няма обект *(р57·[154])*: „задачите без обект ще имат написване мястот на
 * задачата."
 */

/**
 * ОЦЕНКАТА · по Айзенхауер, с неговите думи *(р48·[77]·06.08)*:
 *
 *   „Приоритета го покажи в ъправлението и ги промени както са по Айзенхауер:
 *    Спешно и Важно, Спешно и Не важно, Важно и Не Спешно и Не важно и Не пешно."
 *
 * ЧЕТИРИТЕ квадранта — и НИЩО ПОВЕЧЕ. „Завършено" беше пета стойност
 * (петият цвят, р69·[30]·10.08) до 31.08, когато той я свали *(И124 т.6)*:
 *
 *   „Искам да махнеш от оценка Завършено. Завършено се определя от Състояние
 *    и когато то е Завършено директно оценката става изключена просто без
 *    оценка, не е в дневния ред и влиза в друга таблица която се ползва за
 *    архивиране."
 *
 * Надживените думи стоят с датите си: петият цвят (р69·[30]) и „завършените
 * долу" (р75·[50]) — домът им е ADR-122. Старите Журнали носят петата
 * стойност и тя се чете ПОИМЕННО (`prevediOtsenkata`), не се трие.
 */
export const OTSENKI = [
  'спешно-важно',
  'спешно-неважно',
  'важно-неспешно',
  'нито-едно',
] as const;

export type Otsenka = (typeof OTSENKI)[number];

/** Изключената оценка · завършеното дело е „просто без оценка" (И124 т.6). */
export type OtsenkaNaRed = Otsenka | '';

/** Името на състоянието „завършено" · и на СТАРАТА пета оценка в Журнала. */
export const ZAVARSHENO = 'завършено';

export const IMENA_NA_OTSENKITE: Readonly<Record<Otsenka, string>> = Object.freeze({
  'спешно-важно': 'Спешно и Важно',
  'спешно-неважно': 'Спешно и Не важно',
  'важно-неспешно': 'Важно и Не спешно',
  'нито-едно': 'Не важно и Не спешно',
});

/** Изписването на реда · изключената оценка е тире, не празно петно. */
export function imeNaOtsenkata(o: OtsenkaNaRed): string {
  return o === '' ? '—' : IMENA_NA_OTSENKITE[o];
}

/**
 * Тежестта при подредба · по-малкото е по-нагоре.
 *
 * Негово правило за началната подредба *(р75·[50])*: „По правилото (спешност
 * → Оценка → завършените долу)". „Завършените долу" е НАДЖИВЯНО от И124 т.6 —
 * завършеното не е долу, а в архивната таблица; тук останаха четирите.
 */
export const TEZHEST: Readonly<Record<Otsenka, number>> = Object.freeze({
  'спешно-важно': 0,
  'спешно-неважно': 1,
  'важно-неспешно': 2,
  'нито-едно': 3,
});

/**
 * ПОИМЕННИЯТ ПРЕВОД на старите Журнали (образецът е „ВалутаИзбрана" ·
 * ADR-106): записът не се пипа (правило 1), чете се с днешните очи.
 *
 *   · стара оценка „завършено" ⇒ делото Е завършено: състоянието го казва,
 *     оценката се изключва;
 *   · завършено СЪСТОЯНИЕ с каквато и да е оценка ⇒ оценката се изключва —
 *     „директно оценката става изключена просто без оценка".
 */
export function prevediOtsenkata(
  otsenka: string,
  sastoyanie: string,
): { readonly otsenka: OtsenkaNaRed; readonly sastoyanie: string } {
  if (otsenka === ZAVARSHENO) return { otsenka: '', sastoyanie: ZAVARSHENO };
  if (sastoyanie === ZAVARSHENO) return { otsenka: '', sastoyanie };
  return { otsenka: otsenka as OtsenkaNaRed, sastoyanie };
}

/**
 * ПАЗАЧЪТ НА ОЦЕНКАТА при запис · връща причината за отказ, или празно.
 *
 * Проверява се НАРОЧНО и с думи (прецедентът на състоянието, резен 30):
 * свободна дума в Журнала пада тихо в грешна кофа.
 */
export function proveriOtsenkata(otsenka: string, sastoyanie: string): string {
  // Завършеното е БЕЗ оценка — тя се изключва ДИРЕКТНО при записа („директно
  // оценката става изключена", И124 т.6), затова тук няма какво да се откаже.
  if (sastoyanie === ZAVARSHENO) return '';
  if (otsenka === ZAVARSHENO) {
    return (
      '„Завършено" вече не е оценка, а Състояние (И124 т.6). Запиши ' +
      'състояние „завършено" — оценката се изключва сама.'
    );
  }
  if (otsenka === '') {
    return (
      'Делото не е завършено, а е без оценка — върнато от архива към работа, ' +
      `то иска една от четирите: ${OTSENKI.join(' · ')}.`
    );
  }
  if (!(OTSENKI as readonly string[]).includes(otsenka)) {
    return `Непозната оценка „${otsenka}". Изброените са: ${OTSENKI.join(' · ')}.`;
  }
  return '';
}

/**
 * СЪСТОЯНИЕТО на едно дело.
 *
 * Негово преименуване *(р51·[141])*: „Смени Проекти с Дела и Статус сус
 * Състояние." Стойностите са трите от `р51·[143]`; те не са надживени —
 * надживени са само шестте избора за ЗНАЧИМОСТТА.
 */
export const SASTOYANIYA = ['чака', 'в процес', 'завършено', 'отпаднало'] as const;
type SastoyanieDelo = (typeof SASTOYANIYA)[number];

/**
 * ОТПАДНАЛОТО НЕ Е СТОРНИРАНО · и това е цялата разлика (резен 30).
 *
 * Негова дума *(р?·`izvori/02` 617-618)*: „остават в отедлно наи тфолу тези
 * които са отпаднали но се пази история като бацк уп".
 *
 * ═══ ДВЕ РАЗЛИЧНИ НЕЩА, КОИТО ЛЕСНО СЕ СЛИВАТ ═══
 *
 *   СТОРНО      · „това никога не е трябвало да се записва" — грешка на ръката;
 *   ОТПАДНАЛО   · „беше вярно, но вече няма предмет" — решение на човек.
 *
 * Точно разликата между две от петте кофи на правило 28. Слети, те щяха да
 * дадат книга, в която отменената поръчка изглежда като сгрешен запис.
 *
 * Дотук честен изход нямаше: човек или сторнираше (лъжа за миналото), или
 * слагаше „завършено" (лъжа за настоящето).
 *
 * Историята се пази САМА — отпадането е ново `ДелоЗаписано` върху същата
 * същност, а Журналът е само за добавяне (правило 1). „Бекъп" не се строи.
 */
export const OTPADNALO = 'отпаднало';

/**
 * КОИ ДЕЛА СА ЖИВИ · ЕДИН дом за въпроса (правило 17).
 *
 * Седем места четяха `o.dela.values()` и всяко решаваше само дали да филтрира:
 * едно махаше завършените, друго — нищо. Ново състояние без този дом щеше да
 * се появи на едни екрани и да липсва на други, тихо.
 */
export function zhivite<T extends { readonly sastoyanie: string }>(
  dela: readonly T[],
): readonly T[] {
  return dela.filter((d) => d.sastoyanie !== OTPADNALO);
}

/** И обратното · отпадналите СТОЯТ, отделно, вместо да изчезнат. */
export function otpadnalite<T extends { readonly sastoyanie: string }>(
  dela: readonly T[],
): readonly T[] {
  return dela.filter((d) => d.sastoyanie === OTPADNALO);
}

/**
 * ДНЕВНИЯТ РЕД · живите, по които СЕ РАБОТИ.
 *
 * Завършеното „не е в дневния ред и влиза в друга таблица която се ползва за
 * архивиране" (И124 т.6) — като отпадналото, но по своя причина: отпадналото
 * няма предмет, завършеното е свършено. Двете таблици са две, не една.
 */
export function vDnevniyaRed<T extends { readonly sastoyanie: string }>(
  dela: readonly T[],
): readonly T[] {
  return dela.filter((d) => d.sastoyanie !== OTPADNALO && d.sastoyanie !== ZAVARSHENO);
}

/** Архивът на свършеното · зарежда се по период, не виси в реда. */
export function zavarshenite<T extends { readonly sastoyanie: string }>(
  dela: readonly T[],
): readonly T[] {
  return dela.filter((d) => d.sastoyanie === ZAVARSHENO);
}

export interface Delo {
  readonly id: string;
  /** seq на събитието, което го създаде — сторното сочи именно него */
  readonly seq: number;
  /** ПЪРВА КОЛОНА · адресът, кратко и ясно *(р57·[154])* */
  readonly myasto: string;
  /** ВТОРА КОЛОНА · може да е празна: „задачите без обект" *(р57·[154])* */
  readonly obekt: string;
  /** ТРЕТА КОЛОНА · самото дело */
  readonly ime: string;
  /** човек, не фирма — фирмата е отговорник на МЯСТОТО *(р48·[42] · р48·[44])* */
  readonly otgovornik: string;
  /** YYYY-MM-DD · начало */
  readonly ot: string;
  /** YYYY-MM-DD · край; равен на `ot` значи ЕДНОДНЕВНО дело */
  readonly do: string;
  /** изключена (празна), когато състоянието е „завършено" (И124 т.6) */
  readonly otsenka: OtsenkaNaRed;
  readonly sastoyanie: SastoyanieDelo;
  /** id на дело, под което това е ПОДДЕЛО; празно значи самостоятелно */
  readonly nadDelo: string;
  /** връзка към документ, ако делото има нужда от такъв *(р48·[42])* */
  readonly dokument: string;
  /** ISO време на ПОСЛЕДНОТО записване · не на създаването (резен 30) */
  readonly promeneno: string;
  /** имейлът на онзи, който го е пипнал последен */
  readonly promeniGo: string;
}

/** Еднодневното дело се оцветява различно — и полето, и текстът, и датата. */
export function eEdnodnevno(d: Delo): boolean {
  return d.ot === d.do;
}

/**
 * КОЛКО ДНИ ОСТАВАТ до един срок · отрицателно значи просрочено.
 *
 * Броят се цели дни по календара, не часове: делото няма час, освен когато
 * тръгне към календара *(р59·[92])*.
 *
 * Взима ГОЛА ДАТА, не дело. Три различни ангажимента броят едни и същи дни —
 * вноската, преписката и срещата (резен 39) — и трите ползват този брояч.
 * Обвивка „дни до края на ДЕЛОТО" стоеше тук, докато светофарът я викаше; след
 * като той мина на голата дата, тя остана надпис с един-единствен викащ — теста
 * си (ADR-041), и затова я няма.
 */
export function dniDoSroka(srok: string, dnes: string): number {
  const kray = Date.parse(`${srok}T00:00:00Z`);
  const sega = Date.parse(`${dnes}T00:00:00Z`);
  return Math.round((kray - sega) / 86_400_000);
}

/**
 * СВЕТОФАРЪТ на срока · неговите думи *(р59·[71] · повторено в р74·[12])*:
 *
 *   „цвета на датата или сумат асе променя спрямо наближаването на времето
 *    свети нормално… 1 седмица преди да дойде деня се оцветява автоматично с
 *    жъл цвят текста или цифрите, когато останат 2 дниу свети в червено."
 *
 * Праговете са НЕГОВИ числа: 7 дни и 2 дни. Не се закръглят и не се „оправят".
 */
export type Svetofar = 'normalno' | 'zhalto' | 'cherveno' | 'prosrocheno';

/**
 * СВЕТОФАРЪТ на ГОЛА ДАТА · единственият дом на двата прага (правило 17).
 *
 * „Стщото и за Ъправление и за СМетки" *(р59·[71])* — „същото" значи ЕДНО
 * място, не еднакъв препис на няколко. Преди резен 39 праговете живееха и тук,
 * и в екрана на Контактите: два дома за едно число, и вторият нямаше как да
 * научи, ако първият се смени.
 *
 * Празната дата НЕ свети: подразбран срок би оцветил в червено работа, за която
 * никой не е бързал. И това е ЕДИНСТВЕНАТА липса, която минава мълчаливо.
 *
 * НЕЧЕТИМАТА ДАТА КРЕЩИ, не минава за „нормално". Находка от нарочното счупване
 * (резен 39): махнеш ли пазача за празното, `Date.parse` дава NaN, всички три
 * сравнения с NaN са лъжливи и функцията пак връща „normalno" — тоест сгрешена
 * дата изглеждаше като спокоен срок. За светофар това е най-тихата възможна
 * повреда: той съществува, за да КАЖЕ, а мълчеше.
 */
export function svetofarNaSroka(srok: string, dnes: string): Svetofar {
  if (srok === '') return 'normalno';
  const dni = dniDoSroka(srok, dnes);
  if (Number.isNaN(dni)) {
    throw new Error(
      `Нечетима дата за светофара: „${srok}". Очаква се ГГГГ-ММ-ДД или празно. ` +
        'Празното значи „без срок"; сгрешеното не значи нищо и не бива да минава за спокойно.',
    );
  }
  if (dni < 0) return 'prosrocheno';
  if (dni <= 2) return 'cherveno';
  if (dni <= 7) return 'zhalto';
  return 'normalno';
}

export function svetofar(d: Delo, dnes: string): Svetofar {
  // ОТПАДНАЛОТО НЕ СВЕТИ · срок, който никой няма да гони, не е спешен.
  if (d.sastoyanie === OTPADNALO) return 'normalno';
  // Завършеното не гори. Оценката вече НЕ може да е „завършено" — старите
  // Журнали се превеждат при четене (`prevediOtsenkata`), тук пита Състоянието.
  if (d.sastoyanie === ZAVARSHENO) return 'normalno';
  return svetofarNaSroka(d.do, dnes);
}

/**
 * ПОДРЕДБАТА · „спешност → Оценка → завършените долу" *(р75·[50])*.
 *
 * И по-старото, което не ѝ противоречи *(р48·[93])*: „Подредбата да следва
 * подреба според Пиоритет и после според статуса."
 *
 * Реализация: първо по СРОК (кое гори), после по Оценка, накрая по име — за да
 * е устойчива подредбата при равни. Завършените падат долу заради тежестта 9.
 */
export function podredi(dela: readonly Delo[], dnes: string): Delo[] {
  const gori = (d: Delo) => (svetofar(d, dnes) === 'prosrocheno' ? 0 : 1);
  // Непозната или изключена оценка (стар Журнал, чужд внос) пада НАКРАЯ.
  // Без предпазителя изваждането даваше NaN, NaN е лъжливо за ||, и
  // сравнителят ставаше непоследователен — подредбата се обръщаше мълчешком.
  const tezhest = (d: Delo) => (d.otsenka === '' ? 9 : (TEZHEST[d.otsenka] ?? 9));
  return [...dela].sort(
    (a, b) =>
      tezhest(a) - tezhest(b) ||
      gori(a) - gori(b) ||
      a.do.localeCompare(b.do) ||
      a.ime.localeCompare(b.ime),
  );
}

/**
 * ПОДРЕДБАТА С РЪЧЕН РЕД · „★ Ръчният ред побеждава" *(ред 1496)* (резен 34).
 *
 * Дело с ръчно място стои ТОЧНО там, където е пуснато. Дело БЕЗ такова —
 * родено след последното подреждане или дошло от чужда верига — пада СЛЕД
 * ръчните, в сметнатата подредба.
 *
 * Новото дело НЕ се вмъква между ръчните, защото никой не е казал къде.
 * „Най-отдолу и се вижда" е честният отговор; познато място, което човек не е
 * избрал, е тихо решение вместо него.
 *
 * Празен ръчен ред връща ТОЧНО `podredi` — това е неговият бутон „подреди".
 *
 * Живее ТУК, а не при списъка (`porednost.ts`), защото е подредба на ДЕЛА и
 * стои до правилото, което побеждава. Обратното даваше кръгов внос.
 */
export function podrediSRachen(
  dela: readonly Delo[],
  dnes: string,
  rachen: readonly string[],
): Delo[] {
  const myasto = new Map(rachen.map((id, i) => [id, i]));
  const rachni: Delo[] = [];
  const ostanali: Delo[] = [];
  for (const d of dela) (myasto.has(d.id) ? rachni : ostanali).push(d);
  rachni.sort((a, b) => myasto.get(a.id)! - myasto.get(b.id)!);
  return [...rachni, ...podredi(ostanali, dnes)];
}

/**
 * СГЪВАНЕТО · само дела и поддела.
 *
 * Негови думи, 23.08 (И88): „**Имотите не се сгъват, сгъват се само делата и
 * поддела.**"
 *
 * Затова тук няма сгъване на място или обект — те са КОЛОНИ, а колона не се
 * сгъва (правило 23: колона се СКРИВА, ред се ИЗКЛЮЧВА). Сгъва се дело с
 * поддела под него.
 */
export function imaPoddela(dela: readonly Delo[], id: string): boolean {
  return dela.some((d) => d.nadDelo === id);
}

/**
 * КОИ дела имат деца · ЕДНО минаване за целия екран (резен 12б).
 *
 * `imaPoddela` отговаря за ЕДНО дело и обикаля целия списък — извикана вътре в
 * цикъла за всеки ред, тя прави рисуването O(n²). При дърво от много степени
 * това е първото, което се усеща.
 *
 * И по-важното: множеството се смята от списъка ПРЕДИ сгъването. Иначе свито
 * дело губи собствения си сгъвач — децата му ги няма във видимия списък, значи
 * „има ли деца" отговаря НЕ, бутонът изчезва и свитото не може да се разгъне.
 * Точно това стоеше в кода: сгъването беше еднопосочно.
 */
export function roditeliSDetsa(dela: readonly Delo[]): ReadonlySet<string> {
  const s = new Set<string>();
  for (const d of dela) if (d.nadDelo !== '') s.add(d.nadDelo);
  return s;
}

/**
 * Кои дела се ВИЖДАТ при дадено множество сгънати.
 *
 * Сгънато дело крие подделата си. Подделото на скрито дело също е скрито —
 * иначе сгъването би оставило сираци на екрана.
 */
export function vidimi(dela: readonly Delo[], sgunati: ReadonlySet<string>): Delo[] {
  const po = kartaNaDelata(dela);
  return dela.filter((d) => !podSgunato(po, d, sgunati));
}

/**
 * ПОПРАВЕН ДЕФЕКТ · сгъването оставяше СИРАЦИ.
 *
 * Дотук тук стоеше едно минаване напред, с коментар: „делата идват подредени;
 * поддело сочи НАЗАД към вече видяно дело". **`podredi()` не дава такава
 * гаранция** — тя сортира по тежест на оценката → гори ли → срок → име, и
 * никъде не групира децата под родителя им.
 *
 * СЦЕНАРИЯТ, който чупеше: дядо с оценка „нито-едно" (тежест 3) и внук със
 * „спешно-важно" (тежест 0). Сортировката слага внука ПРЕДИ дядото; при сгънат
 * дядо минаването стига до внука пръв, купчината „скрити" още не съдържа
 * бащата, и внукът ОСТАВА на екрана под скрит родител. Точно сиракът, който
 * функцията обещава да няма.
 *
 * Тестът не го ловеше, защото подаваше РЪЧНО подреден масив и така изпълняваше
 * предположението, вместо да го провери.
 *
 * Сега се върви по ВЕРИГАТА на родителите — редът престава да има значение.
 * `NAY_DALBOKO` е предпазител срещу цикъл: дърво, което сочи само себе си, инак
 * върти безкрайно (Вратата го отказва, но Огледалото чете и стар Журнал).
 */
function podSgunato(
  po: ReadonlyMap<string, Delo>,
  d: Delo,
  sgunati: ReadonlySet<string>,
): boolean {
  let roditel = d.nadDelo;
  for (let i = 0; roditel !== '' && i < NAY_DALBOKO; i += 1) {
    if (sgunati.has(roditel)) return true;
    roditel = po.get(roditel)?.nadDelo ?? '';
  }
  return false;
}

/* ═══════════════════════════════════════════════════════════════════════════
   ДЪРВОТО ПОД ИМОТА · много степени, не две (резен 12б)
   ═══════════════════════════════════════════════════════════════════════════

   Негови думи, 27.08:

     „Да има **разрастване на плана под имот** за задачи, дела, проекти, цели
      **с много стъпки като строителство на сграда** в Гант. Да може когато
      **вкараш нова степен от главното дърво да се прибира при всяка степен с
      една колона**. Виж диаграма на Гант в МС Проджект."

   И същото, негово, отпреди деветнайсет дни *(р52·[231] · 08.08)*:

     „**Направи името на всеки проект в първа колона, а на задачите следващите
      редове да започват от втора колона.**"

   ═══ РЕЧНИКЪТ Е НЕГОВ, И ТОЙ ГО Е ЗАКОВАЛ САМ ═══

   *(р52·[269] · 08.08)*: „**Навсякъде заменяш Проект с Място, за Задача
   навсякъде заменяй с Дело.**" Затова възелът си остава `Delo`, а новото е
   СТЕПЕН. Втори тип „Проект" би бил близнак на делото с друго име — грешката,
   платена вече с ръчния близнак на второстепенния бутон (ADR-058).

   ═══ ДАННИТЕ ВЕЧЕ ГО МОЖЕХА · ЕКРАНЪТ НЕ ═══

   `nadDelo` няма ограничител на дълбочината и тестът за сгъване вече пазеше ТРИ
   нива. Екранът обаче решаваше с БУЛЕВ тест (`d.nadDelo ? … : …`) на три места —
   значи подподделото се рисуваше ТОЧНО като подделото. */

/**
 * НАЙ-ГОЛЯМАТА ДЪЛБОЧИНА, която се смята.
 *
 * Не е ограничение на дървото — то е предпазител срещу ЦИКЪЛ. Вратата отказва
 * цикъл (`praviTsikal`), но Огледалото чете и стар Журнал, писан преди тази
 * проверка; безкраен цикъл там заключва рисуването завинаги.
 */
export const NAY_DALBOKO = 64;

/** Картата id → дело · един превод, ползван от всички обиколки на дървото. */
function kartaNaDelata(dela: readonly Delo[]): Map<string, Delo> {
  return new Map(dela.map((d) => [d.id, d]));
}

/**
 * СТЕПЕНТА на едно дело · 0 за самостоятелно, 1 за поддело, 2 за подподдело…
 *
 * Сирак (`nadDelo` сочи несъществуващо дело) е степен 0, не грешка: `vidimi`
 * вече го показва, вместо да го крие мълчешком, и двете решения трябва да
 * казват едно и също.
 */
export function stepenNa(dela: readonly Delo[], id: string): number {
  const po = kartaNaDelata(dela);
  let roditel = po.get(id)?.nadDelo ?? '';
  let stepen = 0;
  while (roditel !== '' && stepen < NAY_DALBOKO) {
    const gore = po.get(roditel);
    if (!gore) break;
    stepen += 1;
    roditel = gore.nadDelo;
  }
  return stepen;
}

/**
 * ПОДРЕЖДА ПО ДЪРВО · детето ВИНАГИ след родителя си.
 *
 * Вътре в едно ниво важи неговата подредба (`podredi`: спешност → Оценка →
 * завършените долу). Тоест правилото му не се мени — то се прилага на всяко
 * ниво поотделно, вместо върху разбъркана купчина.
 *
 * Сираците вървят като самостоятелни, накрая на своя ред: дело, чийто родител
 * го няма, не бива да изчезне от екрана заради счупена връзка.
 */
export function podredeniPoDarvo(
  dela: readonly Delo[],
  dnes: string,
  /**
   * РЪЧНИЯТ РЕД · „★ Ръчният ред побеждава" *(ред 1496)* (резен 34).
   *
   * Прилага се ВЪТРЕ в едно ниво, не върху целия списък: дървото е по-силно —
   * дете, изкарано пред родителя си, престава да е дете и рисуването се къса.
   * Празен ръчен ред връща точно сметнатата подредба.
   */
  rachen: readonly string[] = [],
): Delo[] {
  const po = kartaNaDelata(dela);
  const deca = new Map<string, Delo[]>();
  for (const d of dela) {
    // Родител, който го няма, се брои за „няма родител" — инак сиракът пада
    // в кофа, която никой не обхожда, и изчезва от екрана.
    const kluch = d.nadDelo !== '' && po.has(d.nadDelo) ? d.nadDelo : '';
    deca.set(kluch, [...(deca.get(kluch) ?? []), d]);
  }
  const izlezli = new Set<string>();
  const red: Delo[] = [];
  const slez = (roditel: string, dalbochina: number): void => {
    if (dalbochina > NAY_DALBOKO) return;
    for (const d of podrediSRachen(deca.get(roditel) ?? [], dnes, rachen)) {
      if (izlezli.has(d.id)) continue; // предпазител срещу цикъл
      izlezli.add(d.id);
      red.push(d);
      slez(d.id, dalbochina + 1);
    }
  };
  slez('', 0);
  return red;
}

/**
 * НОМЕРАТА на степените · 1 · 1.1 · 1.2.3, като в MS Project.
 *
 * СМЯТАТ СЕ, не се записват. Записан, номерът щеше да се разминава при всяко
 * разместване — и всяко разместване щеше да е ново събитие в Журнала за нещо,
 * което е просто позиция (правило 17 · ADR-022).
 *
 * Приема ВЕЧЕ подредените по дърво: номерът е свойство на реда, не на делото.
 */
export function nomeraPoDarvo(podredeni: readonly Delo[]): Map<string, string> {
  const po = kartaNaDelata(podredeni);
  const nomera = new Map<string, string>();
  const broyachi = new Map<string, number>();
  for (const d of podredeni) {
    const roditel = d.nadDelo !== '' && po.has(d.nadDelo) ? d.nadDelo : '';
    const n = (broyachi.get(roditel) ?? 0) + 1;
    broyachi.set(roditel, n);
    const gore = roditel === '' ? '' : nomera.get(roditel);
    nomera.set(d.id, gore === undefined || gore === '' ? String(n) : `${gore}.${n}`);
  }
  return nomera;
}

/**
 * ОБХВАТЪТ НА РОДИТЕЛЯ · от най-ранното до най-късното дете (обобщена лента).
 *
 * СМЯТА СЕ, не се записва. Записан, той щеше да се разминава с децата при всяка
 * промяна на срок — и щеше да има две числа за едно и също (правило 17).
 *
 * Дело без деца връща `null`: то си има СВОИ срокове и обобщена лента не му
 * трябва. Разликата между „няма деца" и „децата покриват нула дни" е важна и не
 * се слива в един празен обхват.
 */
export function obhvatNaDetsata(
  dela: readonly Delo[],
  id: string,
): { readonly ot: string; readonly do: string } | null {
  const po = kartaNaDelata(dela);
  let ot = '';
  let doo = '';
  const slez = (roditel: string, dalbochina: number): void => {
    if (dalbochina > NAY_DALBOKO) return;
    for (const d of dela) {
      if (d.nadDelo !== roditel || d.id === roditel) continue;
      if (ot === '' || d.ot < ot) ot = d.ot;
      if (doo === '' || d.do > doo) doo = d.do;
      slez(d.id, dalbochina + 1);
    }
  };
  if (!po.has(id)) return null;
  slez(id, 0);
  return ot === '' ? null : { ot, do: doo };
}

/**
 * ОБОБЩЕНАТА ЛЕНТА · срокът на родителя, разпънат до децата (резен 12б).
 *
 * Взето от MS Project и записано в плана: „обобщена лента на родителя — ДА,
 * инак родителят е празен ред." Тук обаче има разлика, която не бива да се
 * пропусне: там сроковете на обобщената задача СА изведени и не се въвеждат, а
 * тук `ot` и `do` са ЗАПИСАН ФАКТ в Журнала.
 *
 * Затова лентата се РАЗПЪВА, никога не се свива: покрива и записания срок на
 * родителя, и целия обхват на потомците му. Свиване до децата би скрило
 * записано число зад изведено — точно обратното на правило 1.
 *
 * Връща НОВ списък; нищо не се записва (правило 17: обобщеният срок има един
 * дом — децата — и не се преписва като втори факт).
 *
 * `vsichki` е списъкът ПРЕДИ сгъването: свит родител пак показва докъде стигат
 * скритите му деца — това е целият смисъл на обобщената лента.
 */
export function sObobshteniSrokove(
  redove: readonly Delo[],
  vsichki: readonly Delo[] = redove,
): Delo[] {
  const roditeli = roditeliSDetsa(vsichki);
  return redove.map((d) => {
    if (!roditeli.has(d.id)) return d;
    const obhvat = obhvatNaDetsata(vsichki, d.id);
    if (!obhvat) return d;
    const ot = obhvat.ot < d.ot ? obhvat.ot : d.ot;
    const doo = obhvat.do > d.do ? obhvat.do : d.do;
    return ot === d.ot && doo === d.do ? d : { ...d, ot, do: doo };
  });
}

/**
 * НАВЪТРЕ · НАВЪН · „вкараш нова степен от главното дърво" (резен 12б).
 *
 * Взето от MS Project и в плана поименно. Двете са ЕДНО действие с посока, а не
 * две: и двете менят САМО `nadDelo`, значи и двете са ПОПРАВКА на същото дело —
 * същият `id`, същото събитие. Ново събитие за „преместване" не се строи.
 *
 * `podredeni` идва в РЕДА НА ЕКРАНА нарочно. „Навътре" значи „под реда НАД мен
 * на моето ниво" — това е нещо, което човек вижда, а не изчислява. Функцията
 * остава чиста: редът се подава, не се гадае.
 *
 * Връща `null` за „няма къде" (най-горното на нивото си · вече в корена) и
 * ПРАЗЕН НИЗ за „в корена". Двете не се сливат: празният низ е валиден родител.
 */
export function noviyatRoditel(
  podredeni: readonly Delo[],
  id: string,
  posoka: 'navatre' | 'navan',
): string | null {
  const po = kartaNaDelata(podredeni);
  const d = po.get(id);
  if (!d) return null;
  if (posoka === 'navan') {
    const roditel = d.nadDelo === '' ? undefined : po.get(d.nadDelo);
    return roditel ? roditel.nadDelo : null;
  }
  let predishno: string | null = null;
  for (const x of podredeni) {
    if (x.id === id) break;
    if (x.nadDelo === d.nadDelo) predishno = x.id;
  }
  return predishno;
}

/**
 * ЩЕ НАПРАВИ ЛИ ЦИКЪЛ · проверката, която Вратата пита ПРЕДИ да запише.
 *
 * Дело, направено свой прародител, заключва рисуването завинаги: всяка обиколка
 * на дървото тръгва и не се връща. Дотук такъв пазач НЯМАШЕ — не се стигаше до
 * цикъл само защото формата винаги раждаше нов `id`. С бутони „навътре · навън"
 * се стига веднага.
 *
 * Проверява се и `id === novRoditel`: дело, само на себе си родител, е цикъл с
 * дължина едно и е най-лесният начин да се сгреши.
 */
export function praviTsikal(
  dela: readonly Delo[],
  id: string,
  novRoditel: string,
): boolean {
  if (novRoditel === '') return false;
  if (novRoditel === id) return true;
  const po = kartaNaDelata(dela);
  let gore = novRoditel;
  for (let i = 0; gore !== '' && i < NAY_DALBOKO; i += 1) {
    if (gore === id) return true;
    gore = po.get(gore)?.nadDelo ?? '';
  }
  return false;
}

