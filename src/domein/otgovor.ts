/**
 * ОТГОВОРЪТ НА „МОЖЕ ЛИ" · един дом за формата му (правило 17).
 *
 * Сторното и преносът питаха един и същ въпрос и си бяха написали един и същ
 * отговор — тип с две полета, стойност „може" и помощник „не може, защото".
 * Обходът за чистота (`npm run chistota`) ги намери дословно еднакви.
 *
 * ═══ ЗАЩО ОТКАЗЪТ НОСИ ДУМИ, А НЕ `false` ═══
 *
 * Това е решението, което тук се пази на едно място: „не може" без причина
 * праща човека да гадае какво е сбъркал. Затова `mozhe: false` без текст е
 * невъзможен по конструкция — `ne()` иска причината, а `MOZHE` е единственият
 * начин да се каже „да".
 *
 * ═══ ДВЕ ДУМИ ЗА „КАЗВА", И ТЕ НЕ СЕ СЛИВАТ ═══
 *
 * В кода живеят две имена на полето, което носи текста, и разликата е по
 * СМИСЪЛ, не по недоглеждане:
 *
 *   · **`prichina`** · отказ на ДЕЙСТВИЕ (сторно, пренос). Отговаря на
 *     „защо не стана" — гледа назад към решението;
 *   · **`kazva`** · оценка на ВЪВЕЖДАНЕ (меню, поле, проверка). Отговаря на
 *     „какво да направиш сега" — гледа напред към поправката.
 *
 * Слети в едно име, двете щяха да изглеждат взаимозаменяеми — и първият, който
 * ги размени, щеше да сложи упрек там, където трябва напътствие.
 */

export interface Otgovor {
  readonly mozhe: boolean;
  /** празно, когато може; иначе — с думи, защо не */
  readonly prichina: string;
}

export const MOZHE: Otgovor = Object.freeze({ mozhe: true, prichina: '' });

export function ne(prichina: string): Otgovor {
  return Object.freeze({ mozhe: false, prichina });
}
