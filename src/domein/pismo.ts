/**
 * ПИСМОТО ПРИ ЗАКЪСНЕНИЕ · текстът, не изпращачът.
 *
 * Негови думи: „Едно име и телефон и имейл, за да му се праща имейл, ако
 * закъснее."
 *
 * ЗАЩО НЯМА ИЗПРАЩАЧ. Автоматично изпратено писмо иска сървър, който работи и
 * когато браузърът е затворен — значи месечна сметка и зависимост, а правило 10
 * казва нула зависимости в готовия пакет. Затова тук се строи само ТЕКСТЪТ, а
 * писмото тръгва от пощата на собственика (`mailto:`), с неговия подпис и
 * неговия адрес за отговор. Той го вижда, преди да замине.
 *
 * И това не е по-слабото решение, а по-честното: писмо за пари, което тръгва
 * без някой да го е прочел, се праща и на човек, който е платил вчера в брой.
 *
 * Двете букви разлика, които струват скъпо:
 *
 *   `naematel` — ЧИЙ Е ЖУРНАЛЪТ · ключът на акаунта (`yadro/dnevnik.ts`)
 *   `naemetel` — ЧОВЕКЪТ, който плаща наема (`Naem.naemetel`)
 *
 * Тук се работи с ВТОРИЯ. Първият няма нищо общо с наеми.
 */

import { pishi } from '../yadro/pari.js';

/** Какво трябва да се знае, за да се напише едно писмо. */
interface ZaPismo {
  readonly naemetel: string;
  readonly imeyl: string;
  /** адресът на имота, както се чете от човек */
  readonly imot: string;
  /** периодът във вида „2026-08" */
  readonly period: string;
  /** YYYY-MM-DD */
  readonly padezh: string;
  readonly ostatak_st: number;
  readonly dniZakasnenie: number;
  /** кой праща — името на фирмата от Настройки; празно значи без подпис */
  readonly ot?: string;
}

interface Pismo {
  readonly do: string;
  readonly tema: string;
  readonly tyalo: string;
}

/** „1 ден" · „2 дни" — числото не остава голо до дума в единствено число. */
export function dniSDuma(dni: number): string {
  return `${dni} ${dni === 1 ? 'ден' : 'дни'}`;
}

/**
 * Текстът на напомнянето.
 *
 * Учтиво и КРАТКО, с числата отпред: човек, който е платил, трябва да види за
 * какво става дума на първия ред и да отговори, вместо да чете абзац.
 *
 * Последното изречение не е любезност, а предпазител: плащане в брой, което
 * още не е стигнало до Журнала, е нормално — и писмото трябва да го допуска,
 * иначе праща обвинение вместо напомняне.
 */
export function napishiPismo(z: ZaPismo): Pismo {
  const suma = pishi(z.ostatak_st);
  const redove = [
    `Здравейте, ${z.naemetel},`,
    '',
    `Напомняме за неплатен наем за ${z.period} — ${suma}, с падеж ${z.padezh}` +
      ` (закъснение ${dniSDuma(z.dniZakasnenie)}).`,
    `Имот: ${z.imot}.`,
    '',
    'Ако плащането вече е направено, моля не се съобразявайте с това писмо и ни' +
      ' пишете, за да го отразим.',
  ];
  if (z.ot) redove.push('', `Поздрави,`, z.ot);

  return {
    do: z.imeyl,
    tema: `Неплатен наем за ${z.period} · ${suma}`,
    tyalo: redove.join('\n'),
  };
}

/**
 * АДРЕСЪТ ЗА ПОЩАТА · `mailto:` с попълнени тема и тяло.
 *
 * Връща `null`, когато имейл няма — бутон, който отваря празно писмо, е
 * по-лош от липсващ бутон.
 *
 * `encodeURIComponent`, не `encodeURI`: темата носи „·" и „€", а тялото —
 * нови редове. Полуекранираният адрес отваря писмо с накълцан текст.
 */
export function adresZaPoshta(p: Pismo): string | null {
  if (p.do.trim() === '') return null;
  const tema = encodeURIComponent(p.tema);
  const tyalo = encodeURIComponent(p.tyalo);
  return `mailto:${encodeURIComponent(p.do.trim())}?subject=${tema}&body=${tyalo}`;
}
