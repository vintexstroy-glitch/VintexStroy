/** Броевете по вид · СМЯТАТ се от списъка, не се преписват. */
export function preborenoPoVid(imena: readonly ImeVFayla[]): Readonly<Record<VidVFayla, number>> {
  return Object.freeze({
    firma: imena.filter((i) => i.vid === 'firma').length,
    klient: imena.filter((i) => i.vid === 'klient').length,
    dostavchik: imena.filter((i) => i.vid === 'dostavchik').length,
  });
}

/** Колко от имената ще заминат БЕЗ ЕИК · всяко такова вече си има пречка. */
export function bezEIK(imena: readonly ImeVFayla[]): readonly ImeVFayla[] {
  return imena.filter((i) => !i.sEIK);
}

/**
 * ЕДИН РЕД за едно име · за екрана и за теста, с ЕДИН дом.
 *
 * Пренесен в екрана, този низ щеше да е второ място, което казва същото — а
 * второто място се разминава (правило 17, платено с „132 проверки").
 */
export function edinRedZaImeto(i: ImeVFayla): string {
  return `${i.ime} · ${IMENA_NA_VIDOVETE[i.vid]}${i.sEIK ? '' : ' · БЕЗ ЕИК'}`;
}
