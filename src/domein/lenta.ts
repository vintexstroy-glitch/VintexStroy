/**
 * РЕДЪТ НА МЕНЮТО · какво е ВАЛИДЕН ред, и защо проверката е тук.
 *
 * Негово решение от 28.08 (И111), избрано измежду три: **„И ДВЕТЕ · начален ред
 * + личен"**. Значи два слоя, и само долният е ФАКТ:
 *
 *   · НАЧАЛНИЯТ ред · един за наемателя, пише го само Стопанинът, чете го всеки
 *     → събитие в Журнала, и оттам идва този файл;
 *   · МОЯТ ред · поглед, паметта на екрана, нула събития
 *     → живее в `app/lenta.ts`, а не тук: домейнът не познава екрани.
 *
 * ═══ ЗАЩО ТОЗИ ФАЙЛ СЪЩЕСТВУВА · и той е платен с находка ═══
 *
 * Действието `podrediLentata` тръгна БЕЗ входна проверка, и обходът го хвана
 * навреме. Сметката е точна и си заслужава да се запише:
 *
 *   1. `podredi()` (`app/podredba.ts`) НЕ отсява дубликат от ЗАПОМНЕНИЯ ред —
 *      тя пази реда му, какъвто е.
 *   2. Значи `['imoti','imoti','pari']` минава ПРЕЗ ДВАТА слоя непокътнат.
 *   3. И `main.ts` го превръща в ДВА бутона `data-ekran="imoti"`.
 *   4. **Журналът е само за добавяне (правило 1).** Записан веднъж, дублираният
 *      пункт остава ЗАВИНАГИ — поправката е ново събитие, но лошото пак си стои
 *      в историята и всеки нов четец трябва да го преживее.
 *
 * Затова строгостта е при ВХОДА — същото решение и същата причина като при
 * `TipSabitie` вместо `string` (`tests/sabitiyata.test.ts`).
 *
 * НЕПОЗНАТ КЛЮЧ НЕ СЕ ОТКАЗВА, и това НЕ е пропуск. Ред, записан вчера, носи
 * екран, който днес е скрит по право или изобщо е махнат — `podredi` го отсява
 * мълчаливо и това е правилното поведение. Отказ би значел, че изтриването на
 * един екран заключва подреждането завинаги.
 */

import { bezPovtoreniya, proveriSpisaka } from './red-ot-klyuchove.js';

export class GreshkaLenta extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'GreshkaLenta';
  }
}

/**
 * ПРОВЕРЯВА реда, преди да стане събитие. Връща го нормализиран.
 *
 * Празният ред е ПОЗВОЛЕН и значи „връщам се към обявения в кода" — това е
 * начинът Стопанинът да отмени решението си, без да се трие нищо.
 *
 * Сметката живее в `red-ot-klyuchove.ts`: същата проверка потрябва втори път
 * при ръчния ред на делата (резен 34), и два дома за нея се разминават при
 * първата поправка (правило 17).
 */
export function napraviRedNaLentata(red: readonly string[]): readonly string[] {
  return proveriSpisaka(
    red,
    { edinitsa: 'Екран', kakvo: 'име на екран', sKakvo: 'ключове', koeSeRisuva: 'пунктът' },
    (s) => new GreshkaLenta(s),
  );
}

/**
 * ЧЕТЕ реда от Журнала · снизходително, както `fold()` (правило 1).
 *
 * Писачът вече отказва дубликат — но записът е ЗАВИНАГИ, а книга може да дойде
 * и от другаде (чужда верига, върнат архив, ръчно сглобено събитие). Тогава
 * четенето не бива да рисува пункт два пъти: пази се ПЪРВОТО появяване, защото
 * то е мястото, което човекът е избрал.
 */
export function redOtZhurnala(red: readonly string[] | undefined): readonly string[] {
  return bezPovtoreniya(red);
}
