/**
 * ПАПКАТА НА ОБЕКТА · линк, не достъп (резен 37).
 *
 * ═══ НЕГОВАТА ДУМА ═══
 *
 * „**Различни за различни обекти**, но те са гоогле драйва и има достъп от
 * имейлите които влизат в програмата." *(р57·[110] · 08.08)*
 *
 * ═══ ДВЕ ПОЛОВИНИ, И САМО ЕДНАТА Е НАША ═══
 *
 * Първата половина е НАША: всеки обект носи СВОЙ линк към своя папка. Дотук
 * папка имаше само МЯСТОТО (проектът, резен 31 · ADR-091), а обектите под него
 * делят една — тоест точно онова, което изречението му отрича.
 *
 * Втората половина е при ДОСТАВЧИКА и остава там: „има достъп от имейлите
 * които влизат в програмата" е описание на Драйва, не задача за нас. Правило 14
 * е дословно за това: „Не каним хора, не пазим чужди пароли, не отнемаме
 * достъп." Приложението пази АДРЕСА; кой го отваря, решава Google.
 *
 * ═══ ЗАЩО НЕ СЕ ПРОВЕРЯВА ДАЛИ ПАПКАТА СЪЩЕСТВУВА ═══
 *
 * Проверка би искала мрежа и чужд жетон при всяко рисуване — а офлайн изданието
 * няма нито едното. Линк, който води доникъде, е ЧЕСТНА следа от онова, което
 * човек е написал; мълчаливо махнат, той щеше да изтрие негова работа заради
 * временно отсъствие на обхват (правило 15 · ADR-021).
 */

import { sverka, MERKA, type Sverka } from '../yadro/sverka.js';
import type { Imot } from '../ogledalo/ogledalo.js';

export class GreshkaPapka extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'GreshkaPapka';
  }
}

/**
 * СХЕМИТЕ, които се приемат · и защо са само тези две.
 *
 * `https:` е адресът на всеки облачен диск. `file:` пуска местната папка на
 * онзи, който работи БЕЗ облак — офлайн изданието е пълноправно (CLAUDE.md:
 * „ВСЯКО издание работи офлайн"), и папка там е път на диска, не URL.
 *
 * Всичко друго се отказва ПОИМЕННО. Опасните схеми (`javascript:`, `data:`)
 * не са пропуск в списъка, а изричен отказ: линк в таблица се натиска, а
 * натиснат `javascript:` изпълнява чужд код със всичките права на страницата.
 */
const PUSNATI_SHEMI: readonly string[] = Object.freeze(['https:', 'file:']);

/**
 * ПРОВЕРЯВА линка, преди да стане събитие. Връща го нормализиран.
 *
 * ПРАЗНОТО Е ПОЗВОЛЕНО и значи „още няма папка" — обектът има смисъл и без
 * нея. Поле, което човек е принуден да измисли, се пълни с боклук (дословно
 * същата сметка като при фирмата на мястото, ADR-091).
 */
export function proveriPapkata(vrazka: string): string {
  const t = vrazka.trim();
  if (t === '') return '';

  let shema: string;
  try {
    shema = new URL(t).protocol;
  } catch {
    throw new GreshkaPapka(
      `„${t}" не е адрес. Папката се пише като цял линк — този, който излиза от ` +
        'бутона „Сподели" в Драйва.',
    );
  }
  if (!PUSNATI_SHEMI.includes(shema)) {
    throw new GreshkaPapka(
      `Адрес от вида „${shema}" не се приема. Приемат се само уеб-адрес и местна ` +
        'папка — останалите или не водят до папка, или изпълняват код при натискане.',
    );
  }
  return t;
}

/** Колко обекта имат СВОЯ папка · брои се, не се твърди. */
export function broySPapka(imoti: readonly Imot[]): number {
  return imoti.filter((i) => i.papka !== '').length;
}

/**
 * РАЗЛИЧНИ ЛИ СА · неговата дума е „**различни** за различни обекти".
 *
 * Две обекта с ЕДИН и същ линк не са грешка (спалня и баня в един апартамент
 * може да делят папка), но са НАХОДКА за окото: най-честата причина е копирано
 * поле, което човек е забравил да смени.
 *
 * Затова се БРОЯТ и се КАЗВАТ, а не се отказват при Вратата: отказът щеше да
 * реши вместо него нещо, което той не е питал.
 */
export function povtoreniPapki(imoti: readonly Imot[]): readonly string[] {
  const broy = new Map<string, number>();
  for (const i of imoti) {
    if (i.papka === '') continue;
    broy.set(i.papka, (broy.get(i.papka) ?? 0) + 1);
  }
  return Object.freeze([...broy.entries()].filter(([, n]) => n > 1).map(([v]) => v));
}

/**
 * СВЕРКАТА · РАЗДЕЛЯНЕТО се събира до цялото (правило 7).
 *
 * Всеки обект е или С папка, или БЕЗ — трето няма. Входът е броят обекти;
 * изходът — сборът на двете кофи. Разлика значи, че обект е изпаднал от
 * раздялата, а изпаднал обект изглежда просто като „без папка", тоест като
 * работа за вършене, вместо като загуба.
 *
 * Дотук тук стоеше „обекти ↔ редове" срещу `papkite()` — списък, който никой
 * не рисуваше, защото самата таблица вече показва папката на всеки ред. Списък
 * без викащ е надпис (ADR-041), а сверка срещу надпис не мери нищо.
 */
export function sveriPapkite(imoti: readonly Imot[], kogato: string): Sverka {
  const bez = imoti.filter((i) => i.papka === '').length;
  return sverka('папки · с папка + без папка ↔ обекти', imoti.length, broySPapka(imoti) + bez, kogato, MERKA.broy);
}
