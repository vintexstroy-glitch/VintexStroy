/**
 * КНИГАТА · четенето се отделя от писането (ADR-055 · резен 3).
 *
 * ═══ ЗАЩО ОТДЕЛЕН МОДУЛ ═══
 *
 * Дотук „книга" и „верига" бяха една дума: приложението отваряше един ключ,
 * пишеше в него и четеше от него. Влезе ли втори писач, двете се разделят и
 * посоките стават НЕСИМЕТРИЧНИ:
 *
 *   · ПИША в ЕДНА верига — своята, и в никоя друга (`PoSvoyataVeriga`);
 *   · ЧЕТА от ВСИЧКИ вериги на книгата, сгънати в един поток (`sgani`).
 *
 * Тази несиметричност е целият избор на ADR-055. Слее ли се пак в един ключ,
 * или писането плъзва по чужди вериги, или четенето вижда само своето — и
 * второто е по-лошото, защото не хвърля: служителят би работил седмици в
 * книга, чиято половина не му се показва.
 *
 * ═══ ЛИЧНОТО НЕ Е ВЕРИГА НА КНИГАТА ═══
 *
 * Личният Журнал стои под ключ `имейл#lichen` (ADR-036), а служебната книга на
 * същия човек — под `имейл`. Тоест ПРЕФИКСЪТ ги хваща и двата. Отсяването е
 * тук, а не в носителя: „кое е верига на книгата" е дума на домейна, точно
 * както наставката на личния се подава отвън на Вратата.
 *
 * Проверява се по `knigataNa`, не по „не завършва на #lichen": двете съвпадат
 * днес, но първото ще важи и при трета наставка, а второто трябва да се сети
 * някой да го допише.
 */

import type { Dnevnik } from '../yadro/dnevnik.js';
import type { Sabitie } from '../yadro/sabitie.js';
import { sgani, type SgunatoOgledalo } from '../ogledalo/sgavane.js';
import { knigataNa } from './akaunt.js';

/**
 * Кои вериги има ТАЗИ книга · подредени, с веригата-нула първа.
 *
 * Нулата отпред не е козметика: тя е веригата на стопанина и в нея лежи
 * първото събитие, от което се извежда самият стопанин (ADR-043). Четец, който
 * я търси „някъде в списъка", би работил и обратно — докато някой ден не
 * подаде списъка на нещо, което взима първия елемент.
 */
export async function verigiteNa(dnevnik: Dnevnik, kniga: string): Promise<string[]> {
  const vsichki = await dnevnik.verigi(kniga);
  const nashite = vsichki.filter((k) => knigataNa(k) === kniga);
  return nashite.sort((a, b) => {
    if (a === kniga) return -1;
    if (b === kniga) return 1;
    return a < b ? -1 : a > b ? 1 : 0;
  });
}

/**
 * ЦЯЛАТА книга · всички вериги, сгънати в един детерминиран поток.
 *
 * `kogato` е времето на сверката и се подава отвън по същата причина, поради
 * която го иска и `sgani`: снимка, сама сложила си час, не може да се
 * възпроизведе в тест.
 */
export async function prochetiKnigata(
  dnevnik: Dnevnik,
  kniga: string,
  kogato: string,
): Promise<SgunatoOgledalo> {
  const imena = await verigiteNa(dnevnik, kniga);
  const verigi: Sabitie[][] = [];
  for (const ime of imena) {
    verigi.push(await dnevnik.chetiVsichki(ime));
  }
  return sgani(verigi, kogato);
}
