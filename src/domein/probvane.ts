/**
 * ТРИДЕСЕТТЕ ДНИ ПРОБВАНЕ · срок, не план (резен 32).
 *
 * ═══ НЕГОВАТА ДУМА ═══
 *
 * „с 30 дн[и] б[ез]платно пробване" *(р83·[57])*, потвърдено с „da wavi"
 * *(И86)*, и разчетено там дословно:
 *
 *   „Не се бие с И2: акаунтът остава безплатен, планът остава платен;
 *    **пробването е СРОК преди плащането, не безплатен план**."
 *
 * ═══ ЗАЩО НЕ Е ПЛАН ═══
 *
 * CLAUDE.md е категоричен: „Няма безплатен ПЛАН. Безплатен е АКАУНТЪТ." Ако
 * пробването беше пети план, матрицата на ADR-007 щеше да стане 2×2 плюс едно
 * — тоест да престане да е матрица. То е СРОК върху избрания план, и точно
 * затова тук няма нито един нов запис в `PLANOVE`.
 *
 * ═══ ЗАЩО СЕ СМЯТА, А НЕ СЕ ЗАПИСВА ═══
 *
 * Началото е ПЪРВОТО събитие в Журнала — мигът, в който книгата е започнала.
 * То вече е записано, подписано и в хеш-веригата; втори запис „почнах на"
 * щеше да е второ копие на същия факт, което при първата поправка се разминава
 * с оригинала (правило 20 · прецедентът от резен 28).
 *
 * Оттам нататък всичко е аритметика по календара.
 *
 * ═══ ЧЕСТНА СПИРАЧКА, НЕ КЛЮЧАЛКА ═══
 *
 * CLAUDE.md: „Защитата е честна спирачка, не ключалка… Нарочна измама иска
 * сървър." Изтеклият срок КАЗВА, че е изтекъл — не заключва Журнала и не
 * отнема нито един бутон. Приложение, което заключва данните на човека при
 * изтекъл срок, е взело за заложник неговата книга.
 */

import { sverka, MERKA, type Sverka } from '../yadro/sverka.js';
import type { Sabitie } from '../yadro/index.js';

/** ТРИДЕСЕТ · негово число, и не се закръгля на „месец". */
export const DNI_PROBVANE = 30;

const DEN = 86_400_000;

/** Денят след N дни · цели дни по календара, без часове. */
function sledDni(den: string, dni: number): string {
  return new Date(Date.parse(`${den}T00:00:00Z`) + dni * DEN).toISOString().slice(0, 10);
}

/**
 * НАЧАЛОТО · денят на ПЪРВОТО събитие в книгата.
 *
 * Взима се `ts` на първото събитие, а НЕ датата на записа: пробването брои
 * дните, откакто човекът е тръгнал, а не за кой период е първият му документ.
 * Разход, въведен днес с дата от миналата година, не праща срока в миналото.
 *
 * Празна книга няма начало и връща ПРАЗЕН низ — липсата е ЕДИН вид, не два
 * (`undefined` и `''` биха се разминали при първия викащ, който забрави единия).
 */
export function nachaloNaProbvaneto(sabitiya: readonly Sabitie[]): string {
  const parvo = sabitiya[0];
  return parvo === undefined ? '' : String(parvo.ts).slice(0, 10);
}

export type SastoyanieNaProbvaneto = 'ne-e-zapochnalo' | 'teche' | 'izteklo';

export interface Probvane {
  readonly sastoyanie: SastoyanieNaProbvaneto;
  /** денят на първото събитие · празно, докато книгата е празна */
  readonly nachalo: string;
  /** последният ден, в който срокът важи */
  readonly do_: string;
  /** цели дни ОСТАВАЩИ · отрицателно значи изтекло преди толкова дни */
  readonly ostavat: number;
}

/**
 * СЪСТОЯНИЕТО на пробването · СМЯТА се от НАЧАЛОТО и от деня.
 *
 * Взима НАЧАЛОТО, а не книгата: за едно число не се носи цялата история.
 * Оттам и разделянето — `nachaloNaProbvaneto` се вика ТАМ, където книгата вече
 * е в ръцете (`main.ts`), а Таблото получава готов низ и не научава за Журнала.
 *
 * Денят се ПОДАВА, не се чете от часовника: часовникът е довод и в тестове, и
 * в прохода (същият порт като навсякъде другаде).
 */
export function probvaneto(nachalo: string, dnes: string): Probvane {
  if (nachalo === '') {
    return Object.freeze({
      sastoyanie: 'ne-e-zapochnalo',
      nachalo: '',
      do_: '',
      ostavat: DNI_PROBVANE,
    });
  }
  // Първият ден се БРОИ · срок „30 дни" от 1-ви важи до 30-и, не до 31-ви.
  const do_ = sledDni(nachalo, DNI_PROBVANE - 1);
  const ostavat = Math.round((Date.parse(`${do_}T00:00:00Z`) - Date.parse(`${dnes}T00:00:00Z`)) / DEN);
  return Object.freeze({
    sastoyanie: ostavat >= 0 ? 'teche' : 'izteklo',
    nachalo,
    do_,
    ostavat,
  });
}

/**
 * КАКВО СЕ КАЗВА на човека · едно изречение, без заплаха.
 *
 * Изтеклият срок не отнема нищо и текстът не бива да се преструва, че отнема:
 * това е покана да плати, не ключалка (CLAUDE.md · „честна спирачка").
 */
export function dumiteNaProbvaneto(p: Probvane): string {
  switch (p.sastoyanie) {
    case 'ne-e-zapochnalo':
      return `Пробването е ${DNI_PROBVANE} дни и започва с първия ти запис.`;
    case 'teche':
      return p.ostavat === 0
        ? 'Пробването свършва ДНЕС. Журналът остава твой и след това.'
        : `Пробването тече · остават ${p.ostavat} ${p.ostavat === 1 ? 'ден' : 'дни'} (до ${p.do_}).`;
    case 'izteklo':
      return (
        `Пробването изтече на ${p.do_}. Нищо не е заключено — Журналът, износът и ` +
        'всеки екран си работят. Плащането е за да продължи да е така честно.'
      );
  }
}

/**
 * ИЗТЕКЛО ЛИ Е · единственият въпрос, който екраните задават.
 *
 * Отделна функция, за да НЯМА викащ, който сравнява `ostavat` сам: сравнение,
 * преписано на две места, се разминава при първата смяна на границата.
 */
export function probvanetoEIzteklo(p: Probvane): boolean {
  return p.sastoyanie === 'izteklo';
}

/**
 * СВЕРКАТА · вход↔изход по ВТОРИ независим път (правило 7).
 *
 * Входът е броят дни между началото и края, смятан от датите; изходът е
 * `DNI_PROBVANE`. Разлика значи, че границата се е разминала с числото — а то е
 * НЕГОВО и не се закръгля.
 */
export function sveriProbvaneto(p: Probvane, kogato: string): Sverka {
  const dni =
    p.nachalo === ''
      ? DNI_PROBVANE
      : Math.round((Date.parse(`${p.do_}T00:00:00Z`) - Date.parse(`${p.nachalo}T00:00:00Z`)) / DEN) +
        1;
  return sverka('пробване · дни', DNI_PROBVANE, dni, kogato, MERKA.broy);
}
