/**
 * РЪЧНИЯТ РЕД ПОБЕЖДАВА · колоната „поредност" (резен 34).
 *
 * ═══ НЕГОВИТЕ ДУМИ · и те са за РЕДОВЕТЕ ═══
 *
 * „★ Ръчният ред побеждава (колона „поредност"; Състоянието е бутон
 * „подреди")" *(ИЗВОР-2 · ред 1496)*
 *
 * „да може от редактора да местиш **редовете**, като задържаш на полето и го
 * движиш, за да го преместиш, както е в MS Project" *(ред 1982 · 10.08)*
 *
 * ═══ НАХОДКАТА · три живи места казваха „КОЛОНИТЕ" ═══
 *
 * Описът (M15), ADR-013 и `ИЗВОР-3` §11 носеха „ръчен ред на КОЛОНИТЕ".
 * Неговото изречение на СЪЩИЯ адрес казва РЕДОВЕТЕ, и §7 на същия файл го
 * цитира вярно, както и ADR-059: „редът вътре в едно ниво днес се СМЯТА…
 * Ръчният ред — неговата колона «поредност» — още не е построен."
 *
 * Грешната дума не беше дребна: колоните ВЕЧЕ имат номер и ред (Редакторът на
 * хедъри), значи редът изглеждаше наполовина построен и се отлагаше като
 * козметика. Редовете нямаха НИЩО.
 *
 * ═══ ЗАПИСВА СЕ ЦЕЛИЯТ РЕД, НЕ ДВИЖЕНИЕТО ═══
 *
 * Дословният прецедент е `podrediLentata` (ADR-066): разлика („мести Х с една
 * нагоре") зависи от състоянието в мига на записа, а при много вериги (ADR-055)
 * две едновременни размествания дават различен резултат според реда на
 * прочитане. Цял списък е самодостатъчен.
 *
 * ═══ И ТОЙ Е ЗАПИС, НЕ ПАМЕТ НА ЕКРАНА ═══
 *
 * Тук ръчният ред НЕ се разцепва на два слоя, както менюто. Менюто е поглед —
 * пунктове, които всеки си подрежда за себе си. Редът на ДЕЛАТА е самият план:
 * кое се прави преди кое. Личен ред на плана значи двама души да гледат различен
 * план и да не го знаят.
 */

import { sverka, MERKA, type Sverka } from '../yadro/sverka.js';
import { bezPovtoreniya, proveriSpisaka } from './red-ot-klyuchove.js';

export class GreshkaPorednost extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'GreshkaPorednost';
  }
}

/**
 * ПРОВЕРЯВА реда, преди да стане събитие. Връща го нормализиран.
 *
 * Празният ред е ПОЗВОЛЕН и значи „връщам се към сметнатата подредба" — това е
 * бутонът „Подреди" от неговото изречение. Отмяна без триене (правило 1).
 *
 * Сметката е ЕДНА с онази на лентата и живее в `red-ot-klyuchove.ts`: тя се
 * появи тук за втори път, буква по буква същата (правило 17).
 */
export function napraviRachniyaRed(red: readonly string[]): readonly string[] {
  return proveriSpisaka(
    red,
    { edinitsa: 'Дело', kakvo: 'място на дело', sKakvo: 'идентификатори', koeSeRisuva: 'делото' },
    (s) => new GreshkaPorednost(s),
  );
}

/** ЧЕТЕ ръчния ред от Журнала · снизходително, както `fold()` (правило 1). */
export function rachniyatRedOtZhurnala(red: readonly string[] | undefined): readonly string[] {
  return bezPovtoreniya(red);
}

/**
 * ПРЕМЕСТВАНЕТО · чисто, и екранът му подава ДВЕТЕ места.
 *
 * `ot` е откъде се вдига редът, `do_` — къде се пуска. И двете са позиции в
 * ТОЗИ списък, защото това е, което човекът вижда (дословният прецедент на
 * „навътре/навън" в ADR-059: редът идва от ЕКРАНА, не от Огледалото).
 *
 * Позиция извън списъка не се „поправя" мълчаливо — тя значи, че викащият е
 * сбъркал, и мълчаливата поправка би записала ред, който никой не е искал.
 */
export function sledPremestvane(
  red: readonly string[],
  ot: number,
  do_: number,
): readonly string[] {
  if (!Number.isInteger(ot) || !Number.isInteger(do_)) {
    throw new GreshkaPorednost('Позицията се брои с цели числа — половин ред няма.');
  }
  if (ot < 0 || ot >= red.length || do_ < 0 || do_ >= red.length) {
    throw new GreshkaPorednost(
      `Няма такава позиция: ${ot} → ${do_} при ${red.length} реда. Редът се мести ` +
        'вътре в списъка, а не извън него.',
    );
  }
  const nov = [...red];
  const [vdignat] = nov.splice(ot, 1);
  nov.splice(do_, 0, vdignat!);
  return Object.freeze(nov);
}

/**
 * КОЛОНАТА „ПОРЕДНОСТ" · номерът, който човекът вижда.
 *
 * Брои се от ЕДНО, защото се чете от човек, а не от масив. И се СМЯТА от реда,
 * не се записва: две места, които пазят едно и също число, се разминават при
 * първото преместване (правило 20 · „знакът се смята и не се записва").
 *
 * Дело без ръчен номер връща 0 — липсата е ЕДИН вид, и екранът я показва с тире.
 */
export function nomeratNa(rachen: readonly string[], id: string): number {
  const i = rachen.indexOf(id);
  return i < 0 ? 0 : i + 1;
}

/** Има ли изобщо ръчен ред · оттук екранът решава дали „Подреди" има смисъл. */
export function imaRachenRed(rachen: readonly string[]): boolean {
  return rachen.length > 0;
}

/**
 * СВЕРКАТА · вход↔изход, и нулата се записва (правило 7).
 *
 * Входът е броят дела, подадени за подреждане; изходът — броят в подредения
 * списък. Разлика значи, че подредбата е ИЗЯЛА или РОДИЛА ред — най-тихата
 * възможна повреда, защото списък с един ред по-малко изглежда наред.
 */
export function sveriPodredbata(
  vhod: readonly { readonly id: string }[],
  izhod: readonly { readonly id: string }[],
  kogato: string,
): Sverka {
  return sverka('подредба на делата · редове', vhod.length, izhod.length, kogato, MERKA.broy);
}
