import { deliZakragleno } from '../yadro/pari.js';

/**
 * ЗАКОНОВИЯТ КУРС, в стохилядни · 1,95583 лева за едно евро.
 *
 * Стохилядни, а не дробно число: така умножението остава цяло. Числото е пин
 * с ръка в теста — курс, който никой не проверява, е курс, който някой ще
 * „поправи".
 */
export const LEVA_ZA_EVRO_STOHIL = 195_583;

/** Валутата, която файловете още носят · сравнява се с шапката на плана. */
export const ZNAK_NA_LEVA = 'BGN';

/**
 * Лева в евро · и двете в цели най-малки единици.
 *
 * Закръглянето е към НАЙ-БЛИЗКОТО (`deliZakragleno`), както всяко деление,
 * което е част от сума. Нагоре се закръглят ЦЕНИ (правило 3), а това не е
 * цена, а превод на вече определено число.
 */
export function otLevaVEvro(leva_st: number): number {
  return deliZakragleno(leva_st * 100_000, LEVA_ZA_EVRO_STOHIL);
}

/** Обратното · за да може екранът да покаже колко лева е било едно евро. */
export function otEvroVLeva(evro_st: number): number {
  return deliZakragleno(evro_st * LEVA_ZA_EVRO_STOHIL, 100_000);
}

/**
 * ЧАСТИТЕ СЕ ПРЕВАЛУТИРАТ, СБОРЪТ СЕ СЪБИРА · закръгленото не влиза в сбор.
 *
 * Вратата иска главница + лихва = вноска ТОЧНО. Ако и трите се превалутират
 * поотделно, закръглянето разминава сбора с една стотинка и записът пада —
 * с право. Затова частите се превръщат, а вноската се СЪБИРА от тях: така
 * инвариантът остава цял, а разликата с превалутираната вноска (най-много
 * една стотинка) се вижда в сверката, вместо да чупи записа.
 */
export function vnoskaVEvro(glavnitsa_lv_st: number, lihva_lv_st: number): {
  readonly glavnitsa_st: number;
  readonly lihva_st: number;
  readonly vnoska_st: number;
} {
  const glavnitsa_st = otLevaVEvro(glavnitsa_lv_st);
  const lihva_st = otLevaVEvro(lihva_lv_st);
  return { glavnitsa_st, lihva_st, vnoska_st: glavnitsa_st + lihva_st };
}
