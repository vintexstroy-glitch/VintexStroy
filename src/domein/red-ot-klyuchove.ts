/**
 * СПИСЪК ОТ КЛЮЧОВЕ · ЕДИН дом за двете еднакви сметки (резен 34).
 *
 * Лентата (ADR-066) и ръчният ред на делата (ADR-094) записват едно и също
 * нещо: ЦЯЛ списък от идентификатори, в реда на човека. И правят с него две
 * еднакви неща — проверяват го на входа и го четат снизходително на изхода.
 *
 * ═══ ЗАЩО СА ЕДНО, А НЕ ДВЕ ═══
 *
 * Когато поредността се строеше, тези две функции се появиха за втори път —
 * буква по буква същите, само с друга дума в съобщението. Обход 8 щеше да ги
 * хване; но и без него, два дома за една сметка се разминават при първата
 * поправка, направена само на едното място (правило 17).
 *
 * ═══ ДВЕТЕ СТРАНИ · и защо са различни ═══
 *
 * На ВХОДА строгостта е пълна: дубликат, записан веднъж, остава ЗАВИНАГИ
 * (правило 1) и рисува реда два пъти при всяко следващо четене.
 *
 * На ИЗХОДА четенето е СНИЗХОДИТЕЛНО: писачът вече е отказал дубликата, но
 * книга може да дойде отвън — чужда верига, върнат архив, ръчно сглобено
 * събитие. Тогава екранът не бива да се чупи; пази се ПЪРВОТО появяване,
 * защото то е мястото, което човекът е избрал.
 *
 * Съобщението за грешка носи ДУМАТА на викащия („Екран", „Дело"), защото
 * човекът чете за своето нещо, а не за „ключ в списък".
 */

export interface DumiteNaSpisaka {
  /** как се казва ЕДИН ред · „Екран" · „Дело" */
  readonly edinitsa: string;
  /** какво се пише в него · „име на екран" · „номер на дело" */
  readonly kakvo: string;
  /** с какво се пише · „ключове" · „идентификатори" */
  readonly sKakvo: string;
  /** какво се рисува два пъти, ако дубликатът мине · „пунктът" · „делото" */
  readonly koeSeRisuva: string;
}

/**
 * ПРОВЕРЯВА списъка, преди да стане събитие. Връща го нормализиран.
 *
 * Празният списък е ПОЗВОЛЕН навсякъде и значи „отменям решението си" — начин
 * да се върнеш назад, без да се трие нищо (правило 1).
 */
export function proveriSpisaka(
  red: readonly string[],
  dumi: DumiteNaSpisaka,
  napraviGreshka: (s: string) => Error,
): readonly string[] {
  const chist = red.map((k) => k.trim());

  for (const k of chist) {
    if (k === '') {
      throw napraviGreshka(
        `Празно ${dumi.kakvo} в реда — редът се пише с ${dumi.sKakvo}, не с дупки.`,
      );
    }
  }

  const vidyani = new Set<string>();
  const dvazh = chist.filter((k) => (vidyani.has(k) ? true : (vidyani.add(k), false)));
  if (dvazh.length > 0) {
    throw napraviGreshka(
      `${dumi.edinitsa} „${dvazh[0]}" стои два пъти в реда. Записан така, ${dumi.koeSeRisuva} ` +
        'щеше да се рисува два пъти — а Журналът е само за добавяне и поправката ' +
        'не трие лошото.',
    );
  }

  return Object.freeze([...chist]);
}

/** ЧЕТЕ списъка от Журнала · снизходително, както `fold()` (правило 1). */
export function bezPovtoreniya(red: readonly string[] | undefined): readonly string[] {
  const vidyani = new Set<string>();
  const izhod: string[] = [];
  for (const k of red ?? []) {
    if (k === '' || vidyani.has(k)) continue;
    vidyani.add(k);
    izhod.push(k);
  }
  return Object.freeze(izhod);
}
