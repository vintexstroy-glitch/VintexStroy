/**
 * ПОТОКЪТ · сборът на колоната отива САМ в Приходи или Разходи.
 *
 * Негова поправка (23.08), която казва точно какво мърда и какво не:
 *
 *   „**Колоната не отива където си реши, а където я поставиш. Не си избира** —
 *    както **сумата от колоните с валута се изпраща директно автоматично към
 *    Приходи, ако е с +, и в Разходи, ако е с −**."
 *
 * Две неща в едно изречение, и дотук нито едното не беше вярно в кода:
 *
 * 1. КОЛОНАТА СТОИ. Тя си остава на мястото си в хедъра — екранът я рисува в
 *    реда на главата, а знакът е ЗНАЧКА на реда, не подредба. Дотук екранът
 *    изсипваше първо всички приходни, после всички разходни, и с това
 *    „колоната отиваше където си реши".
 *
 * 2. СБОРЪТ ОТИВА, И ТО САМ. Дотук в Журнала влизаше САМО колоната с роля
 *    „сума"; останалите се виждаха на екрана и толкова. Оттук нататък всяка
 *    колона, ОБЯВЕНА ЗА ЕВРО, пуска сбора си през Вратата — приход при +,
 *    разход при −.
 *
 * ЗАЩО САМО КОЛОНИТЕ В ЕВРО. Защото той го каза: „сумата от колоните С
 * ВАЛУТА". Видът живее в колоната (`vid-stoynost.ts`); процентът и броят не са
 * пари и нямат работа в двата сбора.
 *
 * ЕДИН РЕД НА КОЛОНА, не ред на всеки запис. Негови думи от изворите: „за
 * Приходи се появява падащо меню с името на избраната колона от тези възможни
 * с цифри, **сумарно от цялата колона**". Значи в Журнала влиза сборът, а името
 * на реда е заглавието на колоната.
 *
 * ПОВТОРНОТО ИЗПРАЩАНЕ НЕ УДВОЯВА. Партидата носи белег (модел · колона ·
 * период · сбор); еднакъв белег значи, че нищо не се е сменило, и не се пише
 * нищо. Това НЕ е `opId` — `opId` носи ДЕЙСТВИЕТО (правило 20), защото ключ от
 * съдържанието връща стария резултат, щом нещо се върне към предишния си вид.
 */

import { chislovi, znak, type ChislovaKolona, type Sbor } from './chisla.js';
import type { ModelNaTablitsa } from '../iztochnik/model.js';
import type { Tablitsa } from '../iztochnik/tablitsa.js';

/** Един сбор, тръгнал към Приходи или Разходи. */
interface RedZaIzprashtane {
  /** номерът на колоната — тя СТОИ там, оттук се и разпознава */
  readonly kolona: number;
  /** заглавието ѝ, както го е написал източникът — това става име на реда */
  readonly ime: string;
  /** накъде отива: приход при +, разход при − */
  readonly kam: Sbor;
  /** сборът на цялата колона, цели стотинки · винаги ПОЛОЖИТЕЛЕН */
  readonly suma_st: number;
  /** колко реда са го образували — за сверката вход↔изход */
  readonly broy: number;
}

/**
 * Кои сборове тръгват · и накъде.
 *
 * Изключените (`izklyucheni`) не влизат: те са махнати от човека и „не стигат
 * нито до Сметки, нито до Управление" — негово решение, вече записано в модела.
 *
 * Сумата се дава ПОЛОЖИТЕЛНА, а посоката е в `kam`: знакът е в името на сбора,
 * не в цифрата. Иначе на екрана стоят два минуса и никой не знае кой е кой.
 */
export function zaIzprashtane(
  m: ModelNaTablitsa,
  t: Tablitsa,
): readonly RedZaIzprashtane[] {
  return chislovi(m, t)
    .filter((k: ChislovaKolona) => !k.izklyuchena)
    .map((k) => ({
      kolona: k.kolona,
      ime: k.ime,
      kam: znak(k.sbor_st),
      suma_st: Math.abs(k.sbor_st),
      broy: k.broy,
    }));
}

/**
 * БЕЛЕГЪТ НА ЕДНА ПАРТИДА · „смени ли се нещо изобщо".
 *
 * Сверява се преди запис: еднакъв белег значи, че този сбор вече е изпратен
 * непроменен, и в Журнала не влиза нищо. Различен — влиза нов запис, защото
 * поправка = ново събитие (правило 1).
 *
 * НЕ става за `opId`, по същата причина както при моделите: върнеш ли колона
 * към предишното ѝ състояние, съдържанието се повтаря и повторният ключ би
 * върнал стария резултат — поправката щеше да изчезне мълчаливо.
 */
export function belegNaPartida(
  model: string,
  period: string,
  redove: readonly RedZaIzprashtane[],
): string {
  const chasti = [...redove]
    .sort((a, b) => a.kolona - b.kolona)
    .map((r) => `${r.kolona}:${r.kam}:${r.suma_st}:${r.broy}`);
  return `${model}|${period}|${chasti.join(';')}`;
}

/** Двата сбора на партидата — за сверката вход↔изход (правило 7). */
export function sboroveNaPartida(redove: readonly RedZaIzprashtane[]): {
  readonly prihod_st: number;
  readonly razhod_st: number;
} {
  let prihod_st = 0;
  let razhod_st = 0;
  for (const r of redove) {
    if (r.kam === 'prihod') prihod_st += r.suma_st;
    else razhod_st += r.suma_st;
  }
  return { prihod_st, razhod_st };
}

/** Едно изречение за екрана — какво ще тръгне и накъде. */
export function sDumiNaPartida(redove: readonly RedZaIzprashtane[]): string {
  const p = redove.filter((r) => r.kam === 'prihod').length;
  const r = redove.length - p;
  if (redove.length === 0) return 'няма колона в евро — нищо не тръгва';
  return `${p} към Приходи /+/ · ${r} към Разходи /−/`;
}
