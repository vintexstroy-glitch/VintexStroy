/**
 * ЛИЧНИЯТ ДОСТЪП · споделянето в ОБРАТНАТА посока (И99).
 *
 * Негови думи, дословно:
 *
 *   „Личния екран **се активира с даване на достъп до място в личния драйв**
 *    и ако иска да даде достъп на **работодателя си** става с позволение и от
 *    настройки даване на права, но този път **в обратната посока**, или да
 *    сподели на **външен имейл** личната си папка и личен таб. Например на
 *    жена си и да ѝ даде права."
 *
 * ═══ КОЕ Е „ОБРАТНАТА ПОСОКА" ═══
 *
 * Дотук правата вървяха в ЕДНА посока: главният акаунт → служителя. Стопанинът
 * раздава, служителят получава (И97 т.5). Тук потокът се обръща:
 *
 *   служителят → работодателя си       · „ако иска да даде достъп"
 *   служителят → външен имейл          · „например на жена си"
 *
 * И трите разлики от служебния случай са важни:
 *
 *   1 · РАЗДАВА СОБСТВЕНИКЪТ НА ЛИЧНОТО, не Стопанинът. Работодателят НЕ може
 *       да си вземе достъп до чуждо лично — може само да му бъде даден.
 *   2 · ВЪНШНИЯТ ИМЕЙЛ НЕ Е СЛУЖИТЕЛ. Жената не влиза в екипа на наемателя, не
 *       получава роля в служебния Журнал и не се брои никъде в него.
 *   3 · ЗАПИСВА СЕ В ЛИЧНИЯ ЖУРНАЛ. Кой е допуснат до личното е част от
 *       личното — служебният не научава нищо (И98).
 *
 * ═══ КАКВО ТУК НЕ СЕ ПРАВИ ═══
 *
 * Приложението НЕ споделя папката в драйва. Правило 14 е в сила и тук: „не
 * каним хора, не пазим чужди пароли, не отнемаме достъп". Самата папка се
 * споделя от драйва, с неговите средства; тук се записва кой е допуснат ВЪТРЕ
 * в приложението — точно както при служителите („събитието се казва Записан,
 * а не Поканен").
 *
 * Затова екранът го КАЗВА, вместо да остави човека да мисли, че е споделил
 * папка с едно натискане.
 */

import { svediImeyl } from './akaunt.js';
import { IMENA_NA_ROLITE, type Rolya } from '../yadro/samolichnost.js';

export class GreshkaDostap extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'GreshkaDostap';
  }
}

/** Какво се споделя · папката в драйва, табът в приложението, или двете. */
export const VIDOVE_SPODELYANE = ['papka', 'tab', 'dvete'] as const;

type VidSpodelyane = (typeof VIDOVE_SPODELYANE)[number];

export const IMENA_NA_SPODELYANETO: Readonly<Record<VidSpodelyane, string>> = Object.freeze({
  papka: 'папката в драйва',
  tab: 'личния таб в приложението',
  dvete: 'папката и таба',
});

/**
 * КОЙ Е ОТСРЕЩА · работодателят или външен човек.
 *
 * Разликата не е украса: работодателят вече съществува в служебния Журнал със
 * своя роля, а външният имейл го няма никъде и няма да го има. Записано
 * поименно, за да не се сметне някой ден външният за служител.
 */
export const KAKAV = ['rabotodatel', 'vanshen'] as const;

type Kakav = (typeof KAKAV)[number];

export const IMENA_NA_KAKAV: Readonly<Record<Kakav, string>> = Object.freeze({
  rabotodatel: 'работодателят · има роля и в служебния',
  vanshen: 'външен имейл · не е служител и не влиза в екипа',
});

export interface LichenDostap {
  readonly imeyl: string;
  readonly rolya: Rolya;
  readonly kakvo: VidSpodelyane;
  readonly kakav: Kakav;
  /**
   * ОТНЕТ ли е · достъпът НЕ се трие (правило 1).
   *
   * Отнемането е ново събитие върху същия имейл. Историята „дадох ѝ достъп през
   * август, отнех го през ноември" е точно онова, което append-only Журнал пази
   * — и точно онова, което триенето би направило недоказуемо.
   */
  readonly otnet: boolean;
}

/**
 * Прави и веднага проверява един достъп.
 *
 * Имейлът се свежда със същата функция като ключа на акаунта: „Ivo@Gmail.com"
 * и „ivo@gmail.com" са един човек при доставчика — ако тук станат двама, на
 * единия ще дадеш, а другият ще влиза.
 */
export function napraviDostap(n: {
  imeyl: string;
  rolya: Rolya;
  kakvo: VidSpodelyane;
  kakav: Kakav;
  otnet?: boolean;
}): LichenDostap {
  const imeyl = svediImeyl(n.imeyl);
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(imeyl)) {
    throw new GreshkaDostap(`„${n.imeyl}" не прилича на имейл — той е и подписът в Журнала.`);
  }
  if (!(n.rolya in IMENA_NA_ROLITE)) {
    throw new GreshkaDostap(`Непозната роля „${n.rolya}".`);
  }
  if (!VIDOVE_SPODELYANE.includes(n.kakvo)) {
    throw new GreshkaDostap(`Непознат вид споделяне „${n.kakvo}".`);
  }
  if (!KAKAV.includes(n.kakav)) {
    throw new GreshkaDostap(`Непознато „кой е отсреща": „${n.kakav}".`);
  }
  return Object.freeze({ imeyl, rolya: n.rolya, kakvo: n.kakvo, kakav: n.kakav, otnet: n.otnet ?? false });
}

/**
 * НА СЕБЕ СИ НЕ СЕ ДАВА ДОСТЪП · и това не е дребна проверка.
 *
 * Собственикът на личното вече има всичко. Ред „дадох на себе си" в списъка
 * прави отнемането двусмислено: махнеш го и изглежда, че си си отнел достъпа
 * до собствения Журнал — а `LichnoESamoTvoe` не пита списъка за него.
 */
export function proveriNeSamSiAz(dostap: LichenDostap, sobstvenik: string): void {
  if (dostap.imeyl === svediImeyl(sobstvenik)) {
    throw new GreshkaDostap(
      'На себе си не се дава достъп — личното вече е твое. Отнемането щеше да изглежда като заключване извън собствения Журнал.',
    );
  }
}

/** Кой е допуснат СЕГА · отнетите не влизат, но си остават в Журнала. */
export function dopusnati(vsichki: Iterable<LichenDostap>): readonly LichenDostap[] {
  return [...vsichki].filter((d) => !d.otnet).sort((a, b) => a.imeyl.localeCompare(b.imeyl));
}

/** Кой ВИЖДА · само имейлите. Това чете Вратата за четене и износ. */
export function dopusnatiImeyli(vsichki: Iterable<LichenDostap>): ReadonlySet<string> {
  return new Set(dopusnati(vsichki).map((d) => d.imeyl));
}

/**
 * Кой ПИША · допуснат и НЕ наблюдател. И това чете Вратата — с ДРУГ въпрос.
 *
 * Виждането и писането са различни неща и тук: жената, на която е даден табът
 * „да го вижда", не бива да мени сроковете. Ролята решава — същите релета като
 * при служителите, само че раздадени от друг човек.
 *
 * Двата списъка са РАЗДЕЛЕНИ нарочно. Един общ списък „допуснати" изглежда
 * достатъчен, докато не се сетиш, че Вратата пита ДВА пъти — веднъж за запис и
 * веднъж за износ — и общият отговор прави наблюдателя писач мълчаливо.
 */
export function pishatImeyli(vsichki: Iterable<LichenDostap>): ReadonlySet<string> {
  return new Set(dopusnati(vsichki).filter((d) => d.rolya !== 'nablyudatel').map((d) => d.imeyl));
}

/** Едно име · същият въпрос, зададен за един човек. */
export function mozheDaPishe(vsichki: Iterable<LichenDostap>, imeyl: string): boolean {
  return pishatImeyli(vsichki).has(svediImeyl(imeyl));
}

/** Едно изречение за екрана. */
export function sDumi(d: LichenDostap): string {
  return `${d.imeyl} · ${IMENA_NA_ROLITE[d.rolya]} · ${IMENA_NA_SPODELYANETO[d.kakvo]}`;
}

