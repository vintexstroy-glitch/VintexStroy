/**
 * МЯСТОТО · с което личното се АКТИВИРА (И99).
 *
 * Негово: „Личният екран **се активира с даване на достъп до място в личния
 * драйв**." Тоест активацията не е гол бутон: човекът посочва КЪДЕ ще живее
 * личното, преди то да тръгне.
 *
 * ЧЕСТНО ЗА ДНЕШНИЯ ДЕН: връзката с драйва още не е построена (резен Д — тя
 * иска друг обхват на разрешенията, ADR-021 „Какво НЕ влиза"). Затова тук се
 * записва ПЪТЯТ, а не се проверява, че папката съществува. Записаното чака
 * драйва и той го чете, вместо да пита наново — същият похват като при
 * бутоните, чиято папка е „име в Журнала, не директория" (правило 20).
 *
 * Пътят се пази ДОСЛОВНО (без свеждане на регистъра): имената на папки в
 * драйва различават главни от малки букви, и „Лично" не е „лично".
 */
export function proveriMyasto(myasto: string): string {
  const t = myasto.trim();
  if (t === '') {
    throw new GreshkaDostap(
      'Личното иска МЯСТО в твоя драйв, преди да тръгне — там ще живее и оттам се споделя. ' +
        'Без място то би било Журнал, който никой не може да намери.',
    );
  }
  if (t.length > 200) {
    throw new GreshkaDostap('Пътят е твърде дълъг — 200 знака стигат за име на папка.');
  }
  // Двойни разделители и водещ разделител се подравняват, както при менютата:
  // маха се излишното, регистърът НЕ се пипа (И97 т.13).
  return t.replace(/[\\/]+/g, '/').replace(/^\/+|\/+$/g, '');
}
