import type { Ogledalo } from '../ogledalo/ogledalo.js';

/**
 * ШЕСТТЕ РАБОТНИ · негови по смисъл, не изведени от кода (ADR-153 §3).
 *
 * Стоят ОТПРЕД и не се презаписват: добавеното е разширение на бизнеса, не
 * поправка на казаното — точно както при етапите на продажбата.
 */
export const BAZOVI_SASTOYANIYA_NA_IMOT = [
  'Строителство',
  'Ремонт',
  'Наем',
  'Продажба',
  'Продаден',
  'Собствено ползване',
] as const;

/** Едно състояние, както го носи списъкът · базово или добавено. */
export interface SastoyanieNaImot {
  readonly klyuch: string;
  /** негово ли е от начало, или е добавено от Стопанина */
  readonly bazov: boolean;
}

export class GreshkaSastoyanieNaImot extends Error {
  constructor(kakvo: string) {
    super(kakvo);
    this.name = 'GreshkaSastoyanieNaImot';
  }
}

/** Адресът на същността · `SASTOYANIE:<ключ>`. */
export function sashtnostNaSastoyanie(klyuch: string): string {
  return `SASTOYANIE:${klyuch}`;
}

/**
 * ВСИЧКИТЕ СЪСТОЯНИЯ · шестте плюс добавените, В ТОЗИ РЕД.
 *
 * Дубликат по ключ Вратата не пуска, но и тук се пази: книга може да дойде
 * отвън (правило 1).
 */
export function sastoyaniyataNaImota(o: Ogledalo): readonly SastoyanieNaImot[] {
  const bazovi: SastoyanieNaImot[] = BAZOVI_SASTOYANIYA_NA_IMOT.map((k) => ({
    klyuch: k,
    bazov: true,
  }));
  const dobaveni: SastoyanieNaImot[] = [];
  for (const s of o.sastoyaniyaNaImotite.values()) {
    if (bazovi.some((b) => b.klyuch === s.klyuch)) continue;
    if (dobaveni.some((d) => d.klyuch === s.klyuch)) continue;
    dobaveni.push({ klyuch: s.klyuch, bazov: false });
  }
  return Object.freeze([...bazovi, ...dobaveni]);
}

/**
 * ПРОВЕРКАТА при Вратата · какво НЕ се записва като ново състояние.
 *
 * Празно име — състояние без дума не се избира от меню. Негово от начало —
 * записът щеше да е втори ред за същия ключ, тоест дубликат в падащото меню,
 * без нищо да се промени.
 */
export function proveriSastoyanieNaImot(klyuch: string): string {
  const t = klyuch.trim();
  if (t === '') {
    throw new GreshkaSastoyanieNaImot(
      'Състоянието иска име — състояние без дума не се избира от меню.',
    );
  }
  if ((BAZOVI_SASTOYANIYA_NA_IMOT as readonly string[]).includes(t)) {
    throw new GreshkaSastoyanieNaImot(
      `„${t}" е състояние от начало и вече стои в менюто. Второ вписване не мени нищо.`,
    );
  }
  return t;
}
