/**
 * СЕМЕЙСТВАТА ХЕДЪРИ · таблиците с еднаква глава застават една до друга.
 *
 * Негови думи, 27.08: таблиците с еднакви хедъри се **подреждат една до друга**
 * в таба — „като сортиране"; таблица с различен хедър отива на друго място.
 * „Това е един от начините да ги сортираш в индивидуалния проект на Винтекс."
 *
 * И същото, негово, отпреди деветнайсет дни *(р70·[32] · 08.08 ·
 * `docs/izvori/02-po-temi.md:1038`)*:
 *
 *   „хедърите от еднаквите таблици Управленини и Сметки, Продажби и Стойност
 *    Състояние, Фактури и Извлечения… така когато **създаваш нови колони в
 *    хедърите те се появяват на таблици които работят с еднакви хедъри**. някой
 *    хедъри имат индивидуални колони за себе си"
 *
 * ═══ ОТПЕЧАТЪКЪТ НЕ СЕ ИЗМИСЛЯ ВТОРИ ПЪТ ═══
 *
 * Домейнът вече знае какво е „еднаква глава": `otpechatakNaGlavata`
 * (`src/iztochnik/model.ts:198`) свежда заглавията и ги слепва с „|", а
 * `semeystvo()` (`src/domein/redaktor.ts:534`) намира роднините по него.
 *
 * Тук се прилага СЪЩОТО правило върху НАРИСУВАНАТА глава, със СЪЩАТА функция за
 * свеждане (`svedenaGlava`). Второ свеждане би било четвърто копие на едно
 * правило — точно това, което коментарът в `model.ts:194` вече е платил веднъж:
 * „тук живееше четвърто копие без NFC — глава, писана на клавиатура, която
 * ражда NFD, даваше ДРУГ отпечатък за същата таблица".
 *
 * ═══ СОРТИРАНЕТО Е ДЕЙСТВИЕ, НЕ ПРАВИЛО ═══
 *
 * Той каза „КАТО СОРТИРАНЕ" — тоест човек го натиска, а не се случва само.
 * Затова резултатът се записва в СЪЩАТА памет, в която живее личната подредба
 * на секциите (`podredba.ts`): един дом за въпроса „какъв е редът на секциите
 * на този екран" (правило 17). Втора подредба, която се бори с първата, би
 * значела, че стрелките ▲▼ и този бутон казват различни неща за едно и също.
 *
 * ═══ КАКВО ТОЗИ РЕЗЕН НЕ ПИПА ═══
 *
 * Нито една таблица. Мести се РЕДЪТ на секциите в личната памет — поглед, не
 * факт (ADR-022 · правило 23). Затова границата, която той постави изрично
 * („таблиците в табовете Приходи и Разходи си остават както са"), се спазва по
 * УСТРОЙСТВО: тук няма път до определението на нито една таблица.
 */

import { svedenaGlava } from '../src/iztochnik/tablitsa.js';

/** Една секция, както влиза в подреждането. */
export interface SektsiyaSGlava {
  readonly klyuch: string;
  /** отпечатъкът на главата ѝ · празен, когато секцията няма таблица */
  readonly otpechatak: string;
}

/**
 * ОТПЕЧАТЪКЪТ на нарисувана глава · същото правило като в домейна.
 *
 * Празна глава дава празен отпечатък, а не низ от разделители: секция без
 * таблица няма семейство и не бива да се слее с друга такава.
 */
export function otpechatakNaEkrannaGlava(glavi: readonly string[]): string {
  const svedeni = glavi.map(svedenaGlava).filter((g) => g !== '');
  return svedeni.length === 0 ? '' : svedeni.join('|');
}

/**
 * ПОДРЕЖДА СЕМЕЙСТВАТА ЕДНО ДО ДРУГО · устойчиво.
 *
 * Всяко семейство застава на мястото на ПЪРВИЯ си член, а вътре в него редът
 * остава какъвто е бил. Секция без таблица не се мести: тя няма роднини и
 * местенето ѝ би било подредба без причина.
 *
 * Устойчивостта не е украса. Човек, който вече е наредил секциите си, натиска
 * това веднъж; ако редът вътре в семейството се разбърка, той губи своята
 * работа заради чужда прищявка.
 */
export function podrediPoSemeystvo(sektsii: readonly SektsiyaSGlava[]): string[] {
  const izlezli = new Set<string>();
  const red: string[] = [];
  for (const s of sektsii) {
    if (izlezli.has(s.klyuch)) continue;
    izlezli.add(s.klyuch);
    red.push(s.klyuch);
    if (s.otpechatak === '') continue;
    // Роднините се придърпват ВЕДНАГА след първия си член, в реда, в който са.
    for (const drug of sektsii) {
      if (izlezli.has(drug.klyuch) || drug.otpechatak !== s.otpechatak) continue;
      izlezli.add(drug.klyuch);
      red.push(drug.klyuch);
    }
  }
  return red;
}

/**
 * Колко семейства с ПОВЕЧЕ ОТ ЕДИН член има · за да се каже с думи.
 *
 * Бутон „подреди по хедър" на екран, чиито таблици са различни, не прави нищо —
 * и трябва да го КАЖЕ, вместо да изглежда счупен (правило 15).
 */
export function broySemeystva(sektsii: readonly SektsiyaSGlava[]): number {
  const broy = new Map<string, number>();
  for (const s of sektsii) {
    if (s.otpechatak === '') continue;
    broy.set(s.otpechatak, (broy.get(s.otpechatak) ?? 0) + 1);
  }
  return [...broy.values()].filter((n) => n > 1).length;
}
