/**
 * КОЙ РЕД НОСИ ИВИЦА · чиста функция, тества се без браузър.
 *
 * Приема ключа на групата за всеки ред, в реда на рисуване. Празен ключ значи
 * „този ред не е под никаква група".
 *
 * @returns масив със същата дължина: `true` значи „този ред носи ивицата".
 */
export function zebraPoGrupi(klyuchove: readonly string[]): boolean[] {
  // БЕЗ ГРУПИ (всички ключове са един и същ, включително всички празни) —
  // редува се през ред. Различен ли е поне един, редуването е по група.
  const imaGrupi = klyuchove.some((k) => k !== klyuchove[0]);
  if (!imaGrupi) return klyuchove.map((_, i) => i % 2 === 1);

  let ivitsa = false;
  let predishen: string | null = null;
  return klyuchove.map((k) => {
    if (predishen !== null && k !== predishen) ivitsa = !ivitsa;
    predishen = k;
    return ivitsa;
  });
}

/** Кой елемент отваря нова група · шапката на групата и редът на Мястото. */
const SHAPKI = '.grupata, .gant-myasto';
/** Кой елемент е РЕД · и в таблиците, и в лентата с имената на Ганта. */
const REDOVE = '.red, .gant-delo';

/**
 * Закача ивиците · вика се СЛЕД всяко рисуване.
 *
 * СМИСЛОВИЯТ ЦВЯТ БИЕ ЗЕБРАТА, и това не се решава тук, а в реда на правилата
 * в `stil.css`: зебрата стои ПРЕДИ `.red:hover` и преди `.red.sbor`, значи
 * посоченият ред и сборът я надвиват сами. Ивица, която гаси предупреждение, е
 * по-лоша от липсваща (ADR-032: цветът намира, знакът различава, думата
 * обяснява).
 */
export function zakachiZebrata(koren: ParentNode): void {
  for (const tablitsa of koren.querySelectorAll<HTMLElement>('.tablitsa, .gant-imena')) {
    const redove: HTMLElement[] = [];
    const klyuchove: string[] = [];
    let grupa = '';
    for (const dete of tablitsa.children) {
      if (!(dete instanceof HTMLElement)) continue;
      if (dete.matches(SHAPKI)) {
        grupa = dete.textContent?.trim() ?? '';
        continue;
      }
      if (!dete.matches(REDOVE)) continue;
      redove.push(dete);
      klyuchove.push(grupa);
    }
    const ivitsi = zebraPoGrupi(klyuchove);
    for (const [i, red] of redove.entries()) red.classList.toggle('zebra', ivitsi[i] === true);
  }
}
