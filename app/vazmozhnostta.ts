import { eIzklyuchena, mozhe, type Izbor, type Vazmozhnost } from '../src/domein/planove.js';
import { ekraniraj } from './obshto.js';

/**
 * КАК СЕ КАЗВА, ЧЕ ЕДНА ВЪЗМОЖНОСТ ЯДА ОТ ЕКРАНА · единственият дом (правило 17).
 *
 * ═══ ЗАЩО ИЗОБЩО ИМА ТАКЪВ ДОМ ═══
 *
 * Правило 15 казва: „Изключено ≠ липсващо. `mozhe()` пита ДВЕ неща: планът
 * позволява ли, и отметката включена ли е. Двете не се сливат — иначе всеки
 * скрит бутон почва да прилича на нещо, което се плаща."
 *
 * Дотук този отказ се пишеше НА РЪКА, на място, всеки път. Написан на ръка, той
 * стана ЕДИН текст („иска Драйв") и за двете състояния — тоест точно сливането,
 * от което правилото предпазва. А на едно място (`ogledala`) изобщо не се
 * написа: изгледите работеха и когато човекът свали отметката им, и отметката
 * беше НАДПИС.
 *
 * Затова тук стои ЕДНА функция с ДВЕ думи:
 *
 * | състояние | какво вижда човекът | какво може да направи |
 * | :---- | :---- | :---- |
 * | планът я няма | „няма я в този план" | нищо — иска друг план |
 * | планът я дава, отметката е свалена | „изключена от Таблото" | връща я сам |
 *
 * Двете НЕ се сливат, защото водят на различни места: едното е решение на
 * човека, другото е граница на плана.
 *
 * ═══ ЗАЩО БЛОКЪТ Е ФУНКЦИЯ, А НЕ НИЗ ═══
 *
 * `blok` се вика само когато възможността я има. Подаден като готов низ, целият
 * изглед щеше да се смята и при изключена отметка — и после да се изхвърли.
 * Изключеното не бива да струва.
 */
export interface OtkazatSDumi {
  /** `data-sektsiya` на отказа — същият като на блока, който замества. */
  readonly sektsiya: string;
  /** Заглавието, под което човекът търси изгледа. */
  readonly zaglavie: string;
  /** Едно изречение какво прави изгледът — за да се знае какво се пропуска. */
  readonly zashto: string;
}

/**
 * Блокът, ако възможността я има; иначе секция, която КАЗВА защо я няма.
 *
 * Отказът носи `data-bez="<възможност>"` — за да може машина да го намери,
 * без да чете думи (проходът и мерките).
 */
export function sVazmozhnostta(
  izbor: Izbor,
  v: Vazmozhnost,
  otkaz: OtkazatSDumi,
  blok: () => string,
): string {
  if (mozhe(izbor, v)) return blok();

  const izklyuchena = eIzklyuchena(izbor, v);
  const znak = izklyuchena ? 'изключена от Таблото' : 'няма я в този план';
  const dumite = izklyuchena
    ? `Отметката на тази възможност в Таблото е СВАЛЕНА. Изгледът не пази нищо —
       смята се от Журнала при всяко рисуване — затова нищо не е загубено: върни
       отметката и той се връща цял.`
    : `Възможността не е изключена, а я НЯМА в този план. Отметка за нея в
       Таблото няма да се появи — иска се друг план, не друга настройка.`;

  return `
    <section data-sektsiya="${ekraniraj(otkaz.sektsiya)}" data-bez="${ekraniraj(v)}">
      <div class="dyalglava">
        <h2>${ekraniraj(otkaz.zaglavie)}</h2>
        <span>${znak}</span>
      </div>
      <p class="drebno">${ekraniraj(otkaz.zashto)} ${dumite}</p>
    </section>`;
}
