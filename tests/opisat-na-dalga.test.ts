/**
 * ОПИСЪТ НА ДЪЛГА · всеки ред носи ЦИТАТ и ПОТВЪРДЕН адрес.
 *
 * ═══ ЗАЩО МАШИНА, А НЕ ДИСЦИПЛИНА ═══
 *
 * Негова дума, 27.08 (И103): „изпускаш актуални неща които не противоречат, но
 * ги няма в Плана — въобще ги няма никъде." Правилото, което излезе оттам, е
 * кратко: всяка ⬜ ражда или ред в плана, или изрично „чака негова дума"; трето
 * състояние няма.
 *
 * Обиколката по деветнайсетте теми намери, че третото състояние все пак
 * съществуваше — 48 негови думи, живи само в изворите. Описът им дава дом, а
 * този тест пази дома да не изгние: **адрес, който сочи никъде, е по-лош от
 * липсващ ред** — той изглежда проверим и не е.
 *
 * ═══ КАКВО ТОЧНО СЕ БРОИ ═══
 *
 * Не „добре ли е написан описът" — това не се мери. Броят се три неща, всяко
 * проверимо: файлът, който всеки адрес сочи, СЪЩЕСТВУВА; редът, който сочи,
 * СЪЩЕСТВУВА; и всеки ред носи цитат, не преразказ.
 */

import { describe, expect, it } from 'vitest';
import { existsSync, readFileSync } from 'node:fs';

const OPIS = readFileSync('docs/10-opisat-na-dalga.md', 'utf8');

/** Редовете на таблиците · само те носят дълг. */
const REDOVE = OPIS.split('\n').filter((r) => /^\| (M\d\d|⬜|🟡) /.test(r));

/** Всеки `път:ред` или `път:ред-ред` в описа. */
const ADRESI = [...OPIS.matchAll(/`([\w./-]+\.(?:md|ts|css)):(\d+)(?:-(\d+))?`/g)].map((m) => ({
  fayl: m[1]!,
  ot: Number(m[2]),
  do_: Number(m[3] ?? m[2]),
}));

describe('описът на дълга · съществува и се брои', () => {
  it('носи редове · празен опис би минавал на вяра', () => {
    // ПРАГЪТ ПАДА С ДЪЛГА, не расте с него. „Повече от 40" беше вярно, докато
    // описът само растеше; резен 19 плати четири реда наведнъж и прагът щеше
    // да ПАДНЕ заради платена работа — тоест да наказва точно онова, за което
    // описът съществува. Мери се, че описът НЕ Е ПРАЗЕН и че е ЧЕТИМ, а самото
    // число живее на един дом (`docs/09` §4) и се брои с командата до него.
    expect(REDOVE.length).toBeGreaterThan(0);
  });

  it('и всеки ред казва състоянието си с ЕДИН от двата знака', () => {
    for (const r of REDOVE) {
      const znaci = (r.match(/⬜|🟡/g) ?? []).length;
      expect(znaci, r.slice(0, 80)).toBe(1);
    }
  });
});

/**
 * СПЛАЙСЪТ · описанието на един ред, залепено с ОПАШКАТА на друг.
 *
 * ═══ КАКВО СЕ СЛУЧИ ═══
 *
 * Двайсет и осем от трийсет и осемте реда носеха описание, срязано по средата
 * и продължено с текст, който принадлежи на СЪСЕДЕН ред: „не съществува
 * никъде" + „ствува: нула попадения…". Прочетено дословно, това е дълг, който
 * казва нещо друго от онова, което е — а описът е ЕДИНСТВЕНИЯТ дом на факта
 * „какво чака".
 *
 * ═══ КАКВО ВИЖДА МАШИНАТА И КАКВО НЕ ═══
 *
 * ВИЖДА: къс от 70 знака, който стои в ДВЕ описания. Прагът е мерен, не
 * избран — на поправения файл дава НУЛА, на повредения дава ЧЕТИРИ. По-къс
 * прозорец лови и честните повторения („Заплати · Фактури Кеш · Фактури
 * Карта"), тоест би вдигал фалшива тревога, а тревога, която лъже, е по-скъпа
 * от липсваща (ADR-051).
 *
 * НЕ ВИЖДА: сплайс, при който и ДОНОРЪТ е бил срязан — тогава общ къс няма.
 * Затова тук стоят и другите две: описание без завършек и описание-огризка.
 * Трите заедно ловят ФОРМАТА на повредата; СМИСЪЛА чете човек.
 */
describe('описът на дълга · нито един ред не носи чужд текст', () => {
  const OPISANIYA = REDOVE.map((r) => {
    const k = r.replace(/^\||\|$/g, '').split('|').map((c) => c.trim());
    return { red: r, opis: k[k.length - 1] ?? '' };
  });

  /** Мерен, не избран · вж. шапката горе. */
  const PROZORETS = 70;

  it('ЕДИН и същ къс от 70 знака НЕ стои в две описания', () => {
    const nahodki: string[] = [];
    for (let i = 0; i < OPISANIYA.length; i += 1) {
      const a = OPISANIYA[i]!.opis;
      if (a.length < PROZORETS) continue;
      for (let j = 0; j < OPISANIYA.length; j += 1) {
        if (i === j) continue;
        const b = OPISANIYA[j]!.opis;
        if (b.length < PROZORETS) continue;
        let obshto = '';
        for (let k = 0; k + PROZORETS <= a.length; k += 1) {
          const kas = a.slice(k, k + PROZORETS);
          if (b.includes(kas)) { obshto = kas; break; }
        }
        if (obshto !== '') {
          nahodki.push(`${OPISANIYA[i]!.red.slice(0, 40)} ← „${obshto}"`);
          break;
        }
      }
    }
    expect(nahodki, nahodki.join('\n')).toHaveLength(0);
  });

  it('всяко описание СВЪРШВА · срязаното няма завършек', () => {
    for (const { red, opis } of OPISANIYA) {
      expect(/[.!?)»“"]$/.test(opis), red.slice(0, 60)).toBe(true);
    }
  });

  it('и нито едно не е огризка · под 40 знака не е описание', () => {
    for (const { red, opis } of OPISANIYA) {
      expect(opis.length, red.slice(0, 60)).toBeGreaterThanOrEqual(40);
    }
  });
});

describe('описът на дълга · адресите сочат НЯКЪДЕ', () => {
  it('намерени са адреси · иначе тестът долу мери нищо', () => {
    // Същата поука като горе: прагът НЕ бива да пада заедно с платения дълг.
    expect(ADRESI.length).toBeGreaterThan(0);
  });

  it('всеки посочен файл СЪЩЕСТВУВА', () => {
    const lipsvat = [...new Set(ADRESI.map((a) => a.fayl))].filter((f) => !existsSync(f));
    expect(lipsvat, `няма ги: ${lipsvat.join(' · ')}`).toEqual([]);
  });

  /**
   * РЕДЪТ СЪЩЕСТВУВА. Изворите растат само с добавяне (правило 21), но
   * огледалата се презастрояват — и точно тогава един адрес може да излезе
   * извън файла, без никой да забележи.
   */
  it('и всеки посочен РЕД съществува във файла си', () => {
    const izvan: string[] = [];
    for (const a of ADRESI) {
      if (!existsSync(a.fayl)) continue;
      const redove = readFileSync(a.fayl, 'utf8').split('\n').length;
      if (a.do_ > redove) izvan.push(`${a.fayl}:${a.do_} (файлът има ${redove})`);
    }
    expect(izvan, `адреси извън файла: ${izvan.join(' · ')}`).toEqual([]);
  });
});

/**
 * ДВАТА РАЗДЕЛА · и защо границата между тях се пази с машина.
 *
 * Раздел А обещава ДОСЛОВНА негова дума; раздел Б обявява открито, че такава
 * още няма. Правило 26: находка без дословен цитат не се слива — и точно
 * затова тя не бива да се промъкне в А по-късно, тихо. Тестът пази ГРАНИЦАТА
 * в двете посоки, не само в едната.
 */
const razdel = (zaglavie: string, sledvasht: string): string[] => {
  const ot = OPIS.indexOf(zaglavie);
  if (ot === -1) return [];
  const sled = sledvasht === '' ? -1 : OPIS.indexOf(sledvasht);
  const doo = sled === -1 ? OPIS.length : sled;
  return OPIS.slice(ot, doo)
    .split('\n')
    .filter((r) => /^\| (M\d\d|⬜|🟡) /.test(r));
};

/**
 * ИЗЧЕРПАН РАЗДЕЛ · липсата му е ВАЛИДНО състояние, но не е мълчаливо.
 *
 * Раздел В (последните от M14) се изчерпа в резен 28: платеното ИЗЧЕЗВА от
 * описа, следата остава в ADR-а и в git. Тъй че `razdel` вече връща празно
 * вместо да гърми — а за да не скрие това изтрит раздел А или Б, двата се
 * проверяват ПОИМЕННО, че още ги има.
 */
const IMA_RAZDEL = (zaglavie: string): boolean => OPIS.includes(zaglavie);

describe('описът на дълга · цитат, не преразказ', () => {
  /**
   * Брои се само дали ИМА кавички. Дали текстът вътре е дословен, проверява
   * човек при вписване — машина, която се преструва, че мери дословност, е
   * по-лоша от липсваща.
   */
  /** Докъде стига раздел А · следващият раздел, който наистина съществува. */
  const SLED_A = IMA_RAZDEL('## Б ·')
    ? '## Б ·'
    : IMA_RAZDEL('## В ·')
      ? '## В ·'
      : '## Какво НЕ е';

  it('всеки ред в раздел А носи негов цитат в кавички', () => {
    const bez = razdel('## А ·', SLED_A)
      .filter((r) => !r.includes('„'))
      .map((r) => r.slice(0, 70));
    expect(bez, `редове без цитат в А: ${bez.join(' | ')}`).toEqual([]);
  });

  /**
   * ЖИВИЯТ раздел е ЕДИН, и точно това пази проверката.
   *
   * Дотук тук стоеше „и Б го има" — вярно, докато Б имаше редове. Резен 58
   * плати последния (M17) и разделът си отиде цял, защото празно заглавие не
   * стои да чака някой да го напълни (правило 16).
   *
   * Проверката НЕ отслабва: А не бива да изчезне НИКОГА, докато има дълг, а
   * изчезналият раздел не бива да остави редовете си да изпаднат мълчаливо —
   * това го пази сверката вход↔изход отдолу.
   */
  it('раздел А го ИМА, докато има дълг · липсата му не минава за празнота', () => {
    expect(IMA_RAZDEL('## А ·'), 'раздел А изчезна').toBe(true);
    expect(razdel('## А ·', SLED_A).length, 'раздел А остана без редове').toBeGreaterThan(0);
  });

  it('раздел В е ИЗЧЕРПАН · а докато го имаше, всеки негов ред носеше цитат', () => {
    // Резен 28 плати последното от него. Проверката ОСТАВА: върне ли се
    // разделът някога, редовете му пак ще трябва да носят дословна негова дума.
    const redove = razdel('## В ·', '## Какво НЕ е');
    if (!IMA_RAZDEL('## В ·')) {
      expect(redove).toEqual([]);
      return;
    }
    const bez = redove.filter((r) => !r.includes('„')).map((r) => r.slice(0, 70));
    expect(bez, `редове без цитат в В: ${bez.join(' | ')}`).toEqual([]);
  });

  /**
   * И ОБРАТНАТА ПОСОКА · мерена по СТРУКТУРА, не по знак.
   *
   * Раздел Б НЯМА колона за цитат — редовете му са четириклетъчни. Кавички в
   * тях се срещат, но в описанието („Бутонът „…"" · „Контакти"), не като негова
   * дума; затова търсене на знака „ дава лъжливи находки, а броенето на клетки
   * е еднозначно.
   *
   * Пазù се, защото ред от Б, преместен в А без цитат, би изглеждал като негова
   * дума — а измислена негова дума е по-скъпа от липсваща.
   */
  const kletki = (r: string): number => r.split('|').length - 2;


  it('раздел А носи ПЕТ клетки · колоната за цитат е една от тях', () => {
    for (const r of razdel('## А ·', SLED_A)) expect(kletki(r), r.slice(0, 60)).toBe(5);
  });

  it('а раздел Б носи ЧЕТИРИ · няма колона за цитат, защото няма цитат', () => {
    // РАЗДЕЛ Б МОЖЕ ДА ГО НЯМА, и това не е повреда: последният му ред падна
    // (резен 58 · M17), а празно заглавие не стои да чака някой да го напълни
    // (правило 16). Появи ли се пак ред без цитат, разделът се прави наново — и
    // тогава това условие пак мери него.
    for (const r of razdel('## Б ·', IMA_RAZDEL('## В ·') ? '## В ·' : '## Какво НЕ е'))
      expect(kletki(r), r.slice(0, 60)).toBe(4);
  });

  it('разделите заедно дават ЦЕЛИЯ опис · сверка вход↔изход', () => {
    const kray = IMA_RAZDEL('## В ·') ? '## В ·' : '## Какво НЕ е';
    const a = razdel('## А ·', SLED_A).length;
    const b = razdel('## Б ·', kray).length;
    const v = razdel('## В ·', '## Какво НЕ е').length;
    expect(a + b + v).toBe(REDOVE.length);
    // И ДВАТА раздела носят редове. Празен раздел значи, че редове са изпаднали
    // при преместване — най-тихата повреда, защото сборът пак излиза, ако
    // някой е броил само него.
    //
    // Дотук тук стоеше `a > b` — „повечето редове носят негова дума". То не е
    // инвариант, а моментна снимка: резен 34 премести M15 от А в Б, ЗАЩОТО за
    // колоните дословен цитат няма (правило 26), и снимката се обърна. Оставено,
    // условието щеше да натиска следващия резен да ЗАДЪРЖИ горе ред, чието място
    // е долу — тоест да пази числото за сметка на честността.
    // РАЗДЕЛ, КОЙТО ГО ИМА, НОСИ РЕДОВЕ. Празен раздел значи, че редове са
    // изпаднали при преместване — най-тихата повреда, защото сборът пак излиза,
    // ако някой е броил само него.
    //
    // Дотук тук стоеше `b > 0` БЕЗУСЛОВНО, тоест „раздел Б винаги съществува".
    // То не е инвариант, а снимка: резен 58 плати последния му ред и разделът
    // си отиде цял. Условието се мери за РАЗДЕЛИТЕ, КОИТО ГИ ИМА.
    expect(a).toBeGreaterThan(0);
    if (IMA_RAZDEL('## Б ·')) expect(b).toBeGreaterThan(0);
    if (IMA_RAZDEL('## В ·')) expect(v).toBeGreaterThan(0);
  });
});
