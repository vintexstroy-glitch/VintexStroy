/**
 * ОПИСЪТ НА ДЪЛГА · всеки ред носи ЦИТАТ и ПОТВЪРДЕН адрес.
 *
 * ═══ ЗАЩО МАШИНА, А НЕ ДИСЦИПЛИНА ═══
 *
 * Негова дума, 27.08 (И103): „изпускаш актуални неща които не противоречат, но
 * ги няма в Плана — въобще ги няма никъде." Правилото, което излезе оттам, е
 * кратко: всяка ⬜ ражда или ред в плана, или изрично „чака негова дума"; трето
 * състояние няма.
 *
 * Обиколката по деветнайсетте теми намери, че третото състояние все пак
 * съществуваше — 48 негови думи, живи само в изворите. Описът им дава дом, а
 * този тест пази дома да не изгние: **адрес, който сочи никъде, е по-лош от
 * липсващ ред** — той изглежда проверим и не е.
 *
 * ═══ КАКВО ТОЧНО СЕ БРОИ ═══
 *
 * Не „добре ли е написан описът" — това не се мери. Броят се три неща, всяко
 * проверимо: файлът, който всеки адрес сочи, СЪЩЕСТВУВА; редът, който сочи,
 * СЪЩЕСТВУВА; и всеки ред носи цитат, не преразказ.
 */

import { describe, expect, it } from 'vitest';
import { existsSync, readFileSync } from 'node:fs';

const OPIS = readFileSync('docs/10-opisat-na-dalga.md', 'utf8');

/** Редовете на таблиците · само те носят дълг. */
const REDOVE = OPIS.split('\n').filter((r) => /^\| (M\d\d|⬜|🟡) /.test(r));

/** Всеки `път:ред` или `път:ред-ред` в описа. */
const ADRESI = [...OPIS.matchAll(/`([\w./-]+\.(?:md|ts|css)):(\d+)(?:-(\d+))?`/g)].map((m) => ({
  fayl: m[1]!,
  ot: Number(m[2]),
  do_: Number(m[3] ?? m[2]),
}));

describe('описът на дълга · съществува и се брои', () => {
  it('носи редове · празен опис би минавал на вяра', () => {
    expect(REDOVE.length).toBeGreaterThan(40);
  });

  it('и всеки ред казва състоянието си с ЕДИН от двата знака', () => {
    for (const r of REDOVE) {
      const znaci = (r.match(/⬜|🟡/g) ?? []).length;
      expect(znaci, r.slice(0, 80)).toBe(1);
    }
  });
});

describe('описът на дълга · адресите сочат НЯКЪДЕ', () => {
  it('намерени са адреси · иначе тестът долу мери нищо', () => {
    expect(ADRESI.length).toBeGreaterThan(40);
  });

  it('всеки посочен файл СЪЩЕСТВУВА', () => {
    const lipsvat = [...new Set(ADRESI.map((a) => a.fayl))].filter((f) => !existsSync(f));
    expect(lipsvat, `няма ги: ${lipsvat.join(' · ')}`).toEqual([]);
  });

  /**
   * РЕДЪТ СЪЩЕСТВУВА. Изворите растат само с добавяне (правило 21), но
   * огледалата се презастрояват — и точно тогава един адрес може да излезе
   * извън файла, без никой да забележи.
   */
  it('и всеки посочен РЕД съществува във файла си', () => {
    const izvan: string[] = [];
    for (const a of ADRESI) {
      if (!existsSync(a.fayl)) continue;
      const redove = readFileSync(a.fayl, 'utf8').split('\n').length;
      if (a.do_ > redove) izvan.push(`${a.fayl}:${a.do_} (файлът има ${redove})`);
    }
    expect(izvan, `адреси извън файла: ${izvan.join(' · ')}`).toEqual([]);
  });
});

/**
 * ДВАТА РАЗДЕЛА · и защо границата между тях се пази с машина.
 *
 * Раздел А обещава ДОСЛОВНА негова дума; раздел Б обявява открито, че такава
 * още няма. Правило 26: находка без дословен цитат не се слива — и точно
 * затова тя не бива да се промъкне в А по-късно, тихо. Тестът пази ГРАНИЦАТА
 * в двете посоки, не само в едната.
 */
const razdel = (zaglavie: string, sledvasht: string): string[] => {
  const ot = OPIS.indexOf(zaglavie);
  const doo = sledvasht === '' ? OPIS.length : OPIS.indexOf(sledvasht);
  expect(ot, `няма раздел „${zaglavie}"`).toBeGreaterThan(-1);
  return OPIS.slice(ot, doo)
    .split('\n')
    .filter((r) => /^\| (M\d\d|⬜|🟡) /.test(r));
};

describe('описът на дълга · цитат, не преразказ', () => {
  /**
   * Брои се само дали ИМА кавички. Дали текстът вътре е дословен, проверява
   * човек при вписване — машина, която се преструва, че мери дословност, е
   * по-лоша от липсваща.
   */
  it('всеки ред в раздел А носи негов цитат в кавички', () => {
    const bez = razdel('## А ·', '## Б ·')
      .filter((r) => !r.includes('„'))
      .map((r) => r.slice(0, 70));
    expect(bez, `редове без цитат в А: ${bez.join(' | ')}`).toEqual([]);
  });

  it('и всеки ред в раздел В също · той е сверен на ръка', () => {
    const bez = razdel('## В ·', '## Какво НЕ е')
      .filter((r) => !r.includes('„'))
      .map((r) => r.slice(0, 70));
    expect(bez, `редове без цитат в В: ${bez.join(' | ')}`).toEqual([]);
  });

  /**
   * И ОБРАТНАТА ПОСОКА · мерена по СТРУКТУРА, не по знак.
   *
   * Раздел Б НЯМА колона за цитат — редовете му са четириклетъчни. Кавички в
   * тях се срещат, но в описанието („Бутонът „…"" · „Контакти"), не като негова
   * дума; затова търсене на знака „ дава лъжливи находки, а броенето на клетки
   * е еднозначно.
   *
   * Пазù се, защото ред от Б, преместен в А без цитат, би изглеждал като негова
   * дума — а измислена негова дума е по-скъпа от липсваща.
   */
  const kletki = (r: string): number => r.split('|').length - 2;

  it('раздел А носи ПЕТ клетки · колоната за цитат е една от тях', () => {
    for (const r of razdel('## А ·', '## Б ·')) expect(kletki(r), r.slice(0, 60)).toBe(5);
  });

  it('а раздел Б носи ЧЕТИРИ · няма колона за цитат, защото няма цитат', () => {
    for (const r of razdel('## Б ·', '## В ·')) expect(kletki(r), r.slice(0, 60)).toBe(4);
  });

  it('и двата раздела заедно дават ЦЕЛИЯ опис · сверка вход↔изход', () => {
    const a = razdel('## А ·', '## Б ·').length;
    const b = razdel('## Б ·', '## В ·').length;
    const v = razdel('## В ·', '## Какво НЕ е').length;
    expect(a + b + v).toBe(REDOVE.length);
    expect(a).toBeGreaterThan(b);
  });
});
