/**
 * ЗЕБРАТА · ивицата се сменя при СМЯНА НА ГРУПАТА, не през ред.
 *
 * Негови думи, 27.08: „се редуват когато се сменят задачи от, в моя случай,
 * Имот." Тоест групата решава, не позицията — и точно това не може да се каже
 * с `nth-child`.
 */

import { describe, expect, it } from 'vitest';
import { zebraPoGrupi } from '../app/zebra.ts';

describe('зебрата · по група, не по ред', () => {
  it('без групи редува през ред · неговата дума от 08.08', () => {
    expect(zebraPoGrupi(['', '', '', ''])).toEqual([false, true, false, true]);
  });

  it('с групи ивицата се сменя на ГРАНИЦАТА, не през ред', () => {
    // Малинова има ТРИ реда, Лозенец — ЕДИН. Ивицата се сменя веднъж, на
    // границата, а не три пъти вътре в Малинова.
    expect(zebraPoGrupi(['Малинова', 'Малинова', 'Малинова', 'Лозенец'])).toEqual([
      false,
      false,
      false,
      true,
    ]);
  });

  it('група с ЕДИН ред пак обръща ивицата', () => {
    expect(zebraPoGrupi(['А', 'Б', 'В'])).toEqual([false, true, false]);
  });

  it('връщането към предишна група пак е СМЯНА · подредбата решава, не името', () => {
    // Ако таблицата е подредена така, че една група се появи два пъти, всяко
    // появяване е свой блок. Ивицата следва СЪСЕДСТВОТО, не историята.
    expect(zebraPoGrupi(['А', 'А', 'Б', 'А'])).toEqual([false, false, true, false]);
  });

  it('редовете без група след група се броят за своя група', () => {
    expect(zebraPoGrupi(['', '', 'А', 'А'])).toEqual([false, false, true, true]);
  });

  it('празна таблица не гърми', () => {
    expect(zebraPoGrupi([])).toEqual([]);
  });

  it('един ред няма с какво да се редува', () => {
    expect(zebraPoGrupi(['А'])).toEqual([false]);
  });

  it('дължината на отговора е дължината на въпроса · винаги', () => {
    for (const n of [0, 1, 2, 5, 17]) {
      expect(zebraPoGrupi(Array.from({ length: n }, (_, i) => `Г${i % 3}`))).toHaveLength(n);
    }
  });
});
