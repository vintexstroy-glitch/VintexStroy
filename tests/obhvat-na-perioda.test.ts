/**
 * ПЕРИОДЪТ С КРАЙ (резен 70 · И124 т.11): „В Перид при Сметки липсва
 * възможност за въвеждане на края на раз глеждания периода."
 */

import { describe, expect, it } from 'vitest';
import { mesetsiteVObhvata } from '../src/domein/smetki.ts';

describe('месеците в обхвата · от началото до края, включително', () => {
  it('един месец е обхват от един', () => {
    expect(mesetsiteVObhvata('2026-02', '2026-02')).toEqual(['2026-02']);
  });

  it('февруари до април са три месеца, по ред', () => {
    expect(mesetsiteVObhvata('2026-02', '2026-04')).toEqual(['2026-02', '2026-03', '2026-04']);
  });

  it('преминаването през годината не губи месец', () => {
    expect(mesetsiteVObhvata('2026-11', '2027-02')).toEqual([
      '2026-11', '2026-12', '2027-01', '2027-02',
    ]);
  });

  it('край преди началото дава САМО началния месец · не върти назад', () => {
    expect(mesetsiteVObhvata('2026-05', '2026-01')).toEqual(['2026-05']);
  });

  it('кривият вход се реже на 120 месеца · десет години, заковани с ръка', () => {
    expect(mesetsiteVObhvata('2026-01', '2099-01')).toHaveLength(120);
  });
});
