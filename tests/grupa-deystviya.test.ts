/**
 * ГРУПАТА ДЕЙСТВИЯ · един бутон с дума и стрелкичка (ADR-057).
 *
 * Двете функции тук са ЧИСТИ нарочно — по същата причина като при подредбата:
 * свиването на бутони се вижда с очи и се проверява от прохода, а правилата
 * „кой е ключът" и „кое се вижда" трябва да се доказват без браузър.
 */

import { describe, expect, it } from 'vitest';
import { klyuchNaGrupata, koeDaSeVidi } from '../app/grupa-deystviya.js';

describe('ключът на групата · думите СА самоличността', () => {
  it('едни и същи думи дават един и същ ключ', () => {
    expect(klyuchNaGrupata(['Дръпни', 'Бутни'])).toBe(klyuchNaGrupata(['Дръпни', 'Бутни']));
  });

  /**
   * РЕДЪТ Е ЧАСТ ОТ КЛЮЧА. Разменени действия значат друга подредба на екрана
   * — а запомненият избор е за подредбата, която човекът е виждал.
   */
  it('разменените думи дават ДРУГ ключ', () => {
    expect(klyuchNaGrupata(['Дръпни', 'Бутни'])).not.toBe(klyuchNaGrupata(['Бутни', 'Дръпни']));
  });

  it('добавено действие прави групата друга', () => {
    expect(klyuchNaGrupata(['Провери', 'Изнеси'])).not.toBe(
      klyuchNaGrupata(['Провери', 'Изнеси', 'Внеси']),
    );
  });
});

describe('кое се вижда · запомненото, ако още го има', () => {
  it('без памет се вижда ПЪРВОТО · редът, в който екранът ги е нарисувал', () => {
    expect(koeDaSeVidi(['Дръпни', 'Бутни'], '')).toBe(0);
  });

  it('запомненото се намира по ДУМАТА си, не по позиция', () => {
    expect(koeDaSeVidi(['Провери', 'Изнеси', 'Внеси'], 'Внеси')).toBe(2);
  });

  /**
   * УСЛОВНИЯТ БУТОН, КОЙТО ТОЗИ ПЪТ ГО НЯМА, не оставя празна група: пада се
   * обратно на първото. Индекс извън списъка би скрил ВСИЧКИ бутони и лостът
   * щеше да изчезне мълчаливо — най-лошият възможен изход.
   */
  it('изчезналото действие пада обратно на първото', () => {
    expect(koeDaSeVidi(['Провери', 'Изнеси'], 'Внеси')).toBe(0);
  });

  it('една дума, местена и после върната, се намира пак', () => {
    const imena = ['Приемам', 'Отхвърлям'];
    expect(koeDaSeVidi(imena, imena[koeDaSeVidi(imena, 'Отхвърлям')]!)).toBe(1);
  });
});
