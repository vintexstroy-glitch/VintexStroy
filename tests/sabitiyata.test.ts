/**
 * СЪБИТИЯТА · всяко, което Вратата може да напише, има четец в Огледалото.
 *
 * ЗАЩО ТОЗИ ТЕСТ СЪЩЕСТВУВА. `fold()` завършва с `default: break` и това е
 * НАРОЧНО — стар код трябва да може да прочете по-нов Журнал, без да се
 * събори. Но същият този `default` мълчи и когато името е сгрешено: записът
 * влиза в Журнала, брои се като приложен и не мени нищо. Тих загубен запис в
 * система, чието първо правило е нула загуба на данни.
 *
 * Затова строгостта е при ВХОДА: `#pusni` иска `TipSabitie`, не `string`.
 * А този тест пази втората половина — че всеки тип от съюза наистина има
 * `case` в `fold()`.
 *
 * Тестът чете ИЗВОРА, не типовете: типовете се изтриват при компилация, а
 * договорът между писача и четеца трябва да се провери такъв, какъвто е
 * написан. Същият похват като `tests/imena.test.ts`.
 */

import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';

const SABITIYA = readFileSync('src/domein/sabitiya.ts', 'utf8');
const OGLEDALO = readFileSync('src/ogledalo/ogledalo.ts', 'utf8');
const DEYSTVIYA = readFileSync('src/domein/deystviya.ts', 'utf8');

/** Имената от съюза `TipSabitie`, извадени от самия извор. */
function vidoveOtSayuza(): string[] {
  const nachalo = SABITIYA.indexOf('export type TipSabitie =');
  expect(nachalo, 'TipSabitie трябва да съществува').toBeGreaterThan(-1);
  const kray = SABITIYA.indexOf(';', nachalo);
  const blok = SABITIYA.slice(nachalo, kray);
  return [...blok.matchAll(/'([^']+)'/g)].map((m) => m[1]!);
}

/** Имената, за които `fold()` има `case`. */
function vidoveSChetets(): string[] {
  return [...OGLEDALO.matchAll(/case '([^']+)':/g)].map((m) => m[1]!);
}

/** Имената, които `Deystviya` наистина подава на Вратата. */
function vidoveSPisach(): string[] {
  return [...DEYSTVIYA.matchAll(/#pusni\(\s*'([^']+)'/g)].map((m) => m[1]!);
}

describe('договорът между писача и четеца', () => {
  it('ВСЯКО събитие от съюза има case в fold() — иначе е тих загубен запис', () => {
    const sayuz = vidoveOtSayuza();
    const chetets = new Set(vidoveSChetets());
    // „Сторно" се обработва в първото минаване на `fold()` (погасяванията),
    // не в switch-а на второто — затова има свое изключение, назовано поименно.
    const OBRABOTENI_INAKVE = new Set(['Сторно']);
    const bezChetets = sayuz.filter((v) => !chetets.has(v) && !OBRABOTENI_INAKVE.has(v));
    expect(bezChetets).toEqual([]);
  });

  it('ВСЯКО име, което Действията подават, е в съюза — не просто низ', () => {
    const sayuz = new Set(vidoveOtSayuza());
    const izvan = vidoveSPisach().filter((v) => !sayuz.has(v));
    expect(izvan).toEqual([]);
  });

  it('Вратата иска ТИПА, не низ — иначе печатна грешка минава мълчешком', () => {
    expect(DEYSTVIYA).toContain('type: TipSabitie');
    expect(DEYSTVIYA).not.toMatch(/#pusni\(\s*\n?\s*type: string/);
  });

  it('fold() ОСТАВА снизходителен — стар код чете по-нов Журнал', () => {
    // Обратното на горното и също толкова важно: строгостта е при ВХОДА, не
    // при изхода. Махне ли се този `default`, едно бъдещо събитие ще събори
    // Огледалото на всеки, който още не се е обновил.
    expect(OGLEDALO).toContain('default:');
    expect(OGLEDALO).toContain('НЕПОЗНАТ тип не събаря Огледалото');
  });

  it('ЗНАЕН, но пренебрегнат тип има ПОИМЕНЕН случай, не пада в default', () => {
    // „ВалутаИзбрана" вече не се пише (ADR-014: валутата е една и живее в
    // колоната). Старите Журнали я носят. Ако падаше в `default`, тя щеше да е
    // неразличима от печатна грешка в име — затова има свой случай.
    expect(OGLEDALO).toContain("case 'ВалутаИзбрана'");
    expect(OGLEDALO).toContain("case 'НАПВръзкаПревключена'");
    expect(OGLEDALO).toContain('ЗНАЕН тип, НАРОЧНО пренебрегнат');
  });

  it('и пренебрегнатият НЯМА товар · и двата, еднакво (резен 93 · ADR-151)', () => {
    // Прецедентът е „ВалутаИзбрана": случаят остава, типът на товара — не.
    // Товар, който никой не чете, не документира нищо; той изглежда като жив
    // договор, а е спомен. „НАПВръзкаПревключена" стоеше с товар цял месец
    // след като подаването отпадна — жив само защото два файла го ВНАСЯХА,
    // без да го ползват. Тук двата се държат еднакво, за да няма трети път.
    for (const ime of ['ValyutaIzbrana', 'NAPVrazkaPrevklyuchena']) {
      expect(SABITIYA, `Payload${ime} пак се е родил`).not.toContain(`interface Payload${ime}`);
    }
  });

  it('сверка вход↔изход · и разликата се КАЗВА, дори когато е нула', () => {
    const sayuz = vidoveOtSayuza();
    const pisachi = new Set(vidoveSPisach());
    const chetets = new Set(vidoveSChetets());

    // Двете изключения са назовани ПОИМЕННО, не хванати с формула. Формулата
    // мълчи, когато светът се промени; поименният списък пада на глас.
    const bezChetets = sayuz.filter((v) => !chetets.has(v));
    const bezPisach = sayuz.filter((v) => !pisachi.has(v));

    // „Сторно" се обработва в ПЪРВОТО минаване на fold() (погасяванията), не
    // в switch-а на второто. Затова няма `case` — и това е нарочно.
    expect(bezChetets).toEqual(['Сторно']);

    // ДВА типа вече не се ПИШАТ; и двата се ЧЕТАТ поименно и се пренебрегват.
    // „ВалутаИзбрана" — валутата е една и живее в колоната (ADR-014).
    // „НАПВръзкаПревключена" — подаването към НАП отпадна (резен 53), но старите
    // Журнали я носят, а Журналът не се пипа (правило 1).
    expect(bezPisach).toEqual(['НАПВръзкаПревключена', 'ВалутаИзбрана']);

    // Разликата, изписана: по едно изключение от всяка страна, по едно изключение
    // от всяка страна — и двете обяснени горе. (Бяха 20/19/19, преди „АгентЗаписан"
    // и „ПредложениеЗаписано" с ИИ-таблото — И92 т.10 · ADR-026; после 22/21/21,
    // преди „ТабЗаписан" с табовете и секциите — И92 т.9 · ADR-027; после 23/22/22,
    // преди „ЗадачаЗаписана" с разписанията — И94 т.1 · ADR-029; после 24/23/23,
    // преди „СвръзкаЗаписана" с Журнала от таблица — И96 т.8 · ADR-035; после
    // 25/24/24, преди ТРИТЕ на личния таб — „ЛичноПревключено", „ДелоПрехвърлено"
    // и „ПреносОтчетен" — И98 · ADR-036; после 28/27/27, преди
    // „ЛиченДостъпЗаписан" — обратната посока на споделянето, И99 · ADR-037;
    // после 29/28/28, преди ПЕТТЕ на личните пари — „ЛичнаТемаЗаписана",
    // „ЛичноДвижениеЗаписано", „ЛиченРедИзключен", „ЛиченКредитЗаписан" и
    // „ЛичноИзвлечениеПрието" — И96 т.10 · ADR-038; после 34/33/33, преди
    // „СтопанинЗаписан" — първото събитие в Журнала, И97 т.8 · ADR-043; после
    // 35/34/34, преди „ЗапасенКонтактЗаписан" и „СтопанинСменен" — пътят
    // обратно, И100 · ADR-044; после 37/36/36, преди „ПараметърНаВходаЗаписан" —
    // параметрите при въвеждане получиха екран, И96 т.1 · ADR-046; после
    // 38/37/37, преди „КонтрагентЗаписан" — ЕИК-ът и адресът, които одитният
    // файл иска, И96 т.11 · ADR-047; после 39/38/38, преди „ЗадачаИзпратена" и
    // „ОтговорНаЗадача" — задачите към хората, които се пращат и се ПРИЕМАТ,
    // И110 · резен 14а; после 41/40/40, преди „ЛентаПодредена" — НАЧАЛНИЯТ ред
    // на менюто, който Стопанинът записва за всички, докато личното
    // пренареждане остава ПОГЛЕД и не влиза тук (И111 · резен 15); после
    // 42/41/41, преди „НАПВръзкаПревключена" — активирането, което дава достъп
    // на служител и мени какво напуска устройството, значи не може да е
    // отметка в браузъра (И108 · И112 · резен 17); после 43/42/42, преди
    // „ДокументиЗакачени" — хартията към разхода, делото и имота, закачена
    // като ОТПЕЧАТЪК, не като качен файл (резен 17б · ADR-073); после 44/43/43,
    // преди „ПродажбаЗаписана" и „ДвижениеПоПродажба" — сделката и вноските ѝ.
    // ДВЕ събития, не едно: сделката се ПРЕПИСВА при поправка, а движенията се
    // ДОБАВЯТ. Слети, поправката на купувача щеше да пренапише вноските му
    // (резен 18б · ADR-078); после 46/45/45, преди „ЕтапНаПродажбаЗаписан" —
    // новата КОЛОНА в таблица Продажби. Негово, 29.08: „какъвто и да е той може
    // да се добави като колона… да може всеки да рзвие своя бизнес." Своя
    // същност, защото етапът е НОМЕНКЛАТУРА: добавен веднъж, важи за всички
    // редове и за всяка бъдеща сделка (резен 18в); после 47/46/46, преди
    // „КредитЗаписан" и „ПлащанеПоКредит" — фирменият кредит и вноските по
    // него. ПАК ДВЕ, по същата причина като при сделката: договорът се
    // ПРЕПИСВА при поправка, плащанията се ДОБАВЯТ. Слети, поправката на
    // лихвения процент щеше да пренапише историята на вноските (резен 19 ·
    // ADR-079); после 49/48/48, преди „ЗаплатаЗаписана", „СедмицаПрехвърлена"
    // и „КешЗахранен" — заплатите. ТРИ, и всяко е РАЗЛИЧНО решение на човек:
    // редът е договорено число за човек и седмица; прехвърлянето е РЪЧНО
    // („да се прави ръчно, когато се актуализира в Петък", р48·[83]) и носи
    // следата; захранването е движение по кеша със своя дата. Слети,
    // поправката на дните щеше да пренапише вече прехвърлен разход, а второто
    // захранване щеше да изтрие първото (резен 20 · ADR-080); после 52/51/51,
    // преди „ТаблицаОтФайлСъздадена" — неговият експеримент с Фактури: качената
    // таблица се ЧЕТЕ и вътрешната се СЪЗДАВА, с формулите, ако се превеждат.
    // Своя същност, а не поле на модела: моделът описва как се чете ЧУЖДА
    // таблица, а това е раждането на НАША (резен 21 · ADR-081); после 53/52/52,
    // преди „КатегорияЗададена" — четиринайсетата колона на Плащания Архив.
    // Своя същност, а не поле на разхода: полето щеше да иска поправка на самия
    // разход заради ПРЕЦЕНКА върху него, а заплатата няма къде другаде да я
    // носи (резен 25 · ADR-085); после 54/53/53, преди „ГодинаЗатворена" —
    // затварянето на календарна година. Товарът носи САМО мига (брой и сбор в
    // момента на затварянето): съдържанието на годината е ФУНКЦИЯ от Журнала и
    // се смята по всяко време, а записано, то щеше да е второ копие, което се
    // разминава с първото при първата поправка (резен 28 · ADR-088); после
    // 55/54/54, преди „МястоЗаписано" — мястото (проектът) става ЗАПИС, с
    // отговорник-ФИРМА и линк към папката. Своя същност, а не поле на делото:
    // делата сочат мястото по ИМЕ от първия ден, тъй че ключ-id щеше да иска
    // пренаписване на всяко вече записано дело — смяна на смисъла им назад във
    // времето (резен 31 · ADR-091); после 56/55/55, преди „ДелаПодредени" —
    // РЪЧНИЯТ ред на делата, „★ Ръчният ред побеждава" *(ред 1496)*. Своя
    // същност, а не поле на делото: редът е ОТНОШЕНИЕ между делата, и записан
    // като число в всяко от тях, едно преместване щеше да иска поправка на
    // всеки засегнат ред — тоест десет записа за едно човешко движение
    // (резен 34 · ADR-094); после 57/56/56, преди „КонтактЗаписан" и
    // „ПреписказЗаписана" — ДВЕ, не едно: контактът е ЧОВЕК, преписката е
    // РАБОТА с човек. Един контакт носи много преписки, и записана като поле
    // на контакта, втората щеше да изтрие първата — дословно същата сметка
    // като при сделката и вноските ѝ (резен 38 · ADR-098); после 59/58/58,
    // преди „СрещаЗаписана" — срещата с контакт, „за контактите среща добавяш"
    // *(р57·[30])*. Своя същност по СЪЩАТА причина като преписката: един контакт
    // носи много срещи. И е ЕДНА, не две — авто-делото, което тя ражда, се
    // СМЯТА и не влиза в Журнала: записано, то би раждало дубликат на всяко
    // прерисуване (резен 39 · ADR-099); после 60/59/59, преди „ПолеЗаписано" —
    // полето с формула в Отчети, „с формули между всички таблици" *(И90)*.
    // Своя същност, защото е РЕШЕНИЕ на човек — кое число до кое число казва
    // нещо; самата стойност се СМЯТА и не влиза в Журнала (правило 20 ·
    // резен 42 · ADR-102).)
    // И ТРИТЕ пораснаха с ЕДНО (резен 54): „КоефициентЗаписан" дойде със своя
    // коефициент — има и писач, и четец, тъй че изключенията остават същите.
    //
    // ПИСАЧИТЕ бяха станали 59 от 60 (резен 53): „НАПВръзкаПревключена" загуби своя
    // писач, когато подаването към НАП отпадна. Типът и четецът му ОСТАВАТ —
    // старите Журнали го носят, а Журналът не се пипа (правило 1). Оттук и
    // двете изключения от страната на писача, вместо едно.
    // И ТРИТЕ пораснаха с ДВЕ (резен 56 · ADR-110): „РедовеЗакачени" и
    // „РедовеРазкачени" дойдоха с много-към-много. Двете са ЕДНО решение,
    // казано в два момента — закачането и махането са различни дни и различни
    // хора, тъй че са ДВА типа, не един с обръщач. И двете имат писач и четец.
    // И ТРИТЕ пораснаха с ЕДНО (резен 57 · ADR-111): „РедНаТаблицаЗаписан" —
    // редовете на създадената таблица влизат в Журнала. ЕДИН тип за трите
    // неща (запис · поправка · махане): последната дума за същия ключ бие, а
    // „махнат" е поле, не втори тип — върнатият ред е СЪЩИЯТ ред.
    // И ТРИТЕ пораснаха с ЕДНО (резен 62 · ADR-116): „СемействоГлавиЗаписано" —
    // кои таблици работят с ЕДНА глава. ЕДИН тип за трите неща (запис ·
    // поправка · разпускане): последната дума за същия ключ бие, а „разпуснато"
    // е поле, не втори тип — върнатото семейство е СЪЩОТО, не ново.
    // И ТРИТЕ пораснаха с ЕДНО (резен 73 · ADR-128): „ПогасителенПланВкаран" —
    // планът на банката за един кредит. Има и писач (zapishiPogasitelenPlan),
    // и четец; ново вкарване заменя целия план — последната дума бие.
    // И ТРИТЕ пораснаха с ЕДНО (резен 79 · ADR-137): „КлеткаНаДобавкаЗаписана" —
    // стойността в ДОБАВЕНА колона на вградена таблица. ЕДИН тип за записа и
    // поправката: последната дума за адреса „таблица · ред · колона" бие, а
    // сторното на първото писане гаси клетката (седмият с поправка на място).
    // И ТРИТЕ пораснаха с ЕДНО (резен 86 · ADR-144): „НачаленИзгледЗададен" —
    // редът на секциите и сгънатите на един екран, от Стопанина за всички.
    // Цяла снимка по екран, последната дума бие; празните списъци са отмяна.
    // И ТРИТЕ пораснаха с ЕДНО (резен 99 · ADR-157): „СъстояниеНаИмотЗаписано" —
    // състоянието на Имота е НОМЕНКЛАТУРА, не поле: добавено веднъж, важи за
    // всеки Имот и за всеки бъдещ, точно както етапът на продажбата. Шестте
    // работни (Строителство · Ремонт · Наем · Продажба · Продаден · Собствено
    // ползване) живеят в кода и НЕ се пишат — тук влиза само растежът, а
    // ключът е самото име: преименуване е ново състояние, вече записаните
    // Имоти пазят своя (правило 1). Трите ПОЛЕТА на Имота (стойност ·
    // квадратура · състояние) не са нов тип — те влязоха в товара на
    // „МястоЗаписано", защото Имотът вече го има.
    // И ТРИТЕ пораснаха с ОЩЕ ЕДНО (резен 111 · ADR-170):
    // „СъстояниеОтбелязаноКатоЗемя" — негово, 04.09: „земя е Имот с различен
    // Статут. Ще се добавят и трият статутите." Отметката иска СВОЕ събитие, а
    // не поле в записа на номенклатурата, защото трябва да ляга и върху
    // шестте БАЗОВИ състояния, които живеят в кода и нямат запис.
    expect({ sayuz: sayuz.length, pisachi: pisachi.size, chetets: chetets.size }).toEqual({
      sayuz: 71,
      pisachi: 69,
      chetets: 70,
    });
  });
});
