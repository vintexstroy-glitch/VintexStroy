/**
 * ПРАВИЛО 16 · ЧИСТОТО И АРХИВЪТ · с МАШИНА, не с дисциплина.
 *
 * ═══ ЗАЩО ТОЗИ ТЕСТ СЕ РОДИ ЧАК СЕГА (резен 18) ═══
 *
 * Голямата сверка мина през всичките 28 правила и зададе на всяко ДВА въпроса:
 * има ли негов адрес, и има ли ВИКАЩ в живия код. Отговорът раздели правилата
 * на три:
 *
 *   · правилата за КОДА (1–15 · 17–20 · 23 · 25) — всяко има пазач в тест или
 *     в прохода, макар да се вика под името на механизма си, не по номер;
 *   · правилата за ПРОЦЕСА (24 · 26 · 27 · 28) — те казват КАК се пита и КАК се
 *     сверява. Машина не може да ги провери и това е честно състояние;
 *   · и ЕДНО, което МОЖЕ да се провери с машина и не се проверяваше — това.
 *
 * ADR-056 плати урока с думи: „обход, който само стои в правило, разчита на
 * дисциплина вместо на машина." Правило 16 беше точно такова — и нарушението му
 * е НЕВИДИМО по устройство: следа в жив файл „изглежда като решение в сила и се
 * цитира с години".
 *
 * ═══ КАКВО НАМЕРИ ПРИ ПЪРВОТО СИ ПУСКАНЕ ═══
 *
 * ТРИ архивирани файла без обяснение вътре — разчитаха на описа
 * `00-KAKVO-IMA-TUK.md`. А който отвори файла ПРЯКО (от препратка, от търсене,
 * от git) никога не минава през описа: за него докладът отпреди месеци изглежда
 * действащ. Стъпка 2 от реда на архивиране беше пропусната при трите.
 */

import { describe, expect, it } from 'vitest';
import { readdirSync, readFileSync } from 'node:fs';

const ZHIVI = [
  'CLAUDE.md',
  'README.md',
  ...readdirSync('docs')
    .filter((f) => f.endsWith('.md'))
    .map((f) => `docs/${f}`),
];

const ARHIVIRANI = readdirSync('docs/arhiv')
  .filter((f) => f.endsWith('.md') && f !== '00-KAKVO-IMA-TUK.md')
  .map((f) => `docs/arhiv/${f}`);

describe('правило 16 · архивът обяснява себе си', () => {
  it('архивът НЕ е празен · иначе тестът минава на вяра', () => {
    expect(ARHIVIRANI.length).toBeGreaterThan(3);
  });

  /**
   * ОБЯСНЕНИЕТО Е ВЪТРЕ, не само в описа. Описът е КАРТА — като `docs/00` за
   * живите; картата не е дом на факта, а показалец към него (правило 17).
   */
  it('всеки архивиран файл казва В ПЪРВИТЕ СИ РЕДОВЕ, че е архивиран', () => {
    const bez: string[] = [];
    for (const p of ARHIVIRANI) {
      const glava = readFileSync(p, 'utf8').split('\n').slice(0, 14).join('\n');
      if (!/АРХИВИРАН|надживя|заменен|приключил|ПРИКЛЮЧИЛ/i.test(glava)) bez.push(p);
    }
    expect(bez, `без обяснение вътре: ${bez.join(' · ')}`).toEqual([]);
  });

  it('и казва КАКВО важи вместо него · иначе читателят остава без път напред', () => {
    const bez: string[] = [];
    for (const p of ARHIVIRANI) {
      const glava = readFileSync(p, 'utf8').split('\n').slice(0, 14).join('\n');
      if (!/вместо него|Заменен от|Живото решение|остава в сила/i.test(glava)) bez.push(p);
    }
    expect(bez, `без „какво важи вместо": ${bez.join(' · ')}`).toEqual([]);
  });
});

describe('правило 16 · в живото не остават следи', () => {
  /**
   * ДВЕТЕ ЗАБРАНЕНИ ФОРМИ, дословно от CLAUDE.md: „нито ⚠ заглавки „заменен",
   * нито „старото пише X, но вярното е Y"".
   *
   * ИЗКЛЮЧЕНИЯТА са ДВЕ и са обявени поименно: файловете, които САМИ описват
   * правилото, неизбежно го цитират. Списък от изключения е по-честен от хитра
   * редовна форма, която мълчаливо пропуска нещо друго.
   *
   * СПИСЪКЪТ СЕ ПАЗИ КЪС НАРОЧНО. Още при първото пускане сверката в `docs/09`
   * §5 се спъна в него: тя описваше какво е проверила и с това цитираше
   * забранената фраза. Правилният ход беше да се преформулира ЗАПИСЪТ, не да се
   * разшири списъкът — иначе най-големият файл с числа щеше да излезе изпод
   * обхода заради едно изречение. Изключение, дадено за удобство, изяжда точно
   * онова, което обходът пази.
   */
  const KOITO_OPISVAT_PRAVILOTO = ['CLAUDE.md', 'docs/00-CHETI-PARVO.md'];

  it('нито един жив документ не носи следа „заменен · но вярното е"', () => {
    const nameri: string[] = [];
    for (const p of ZHIVI) {
      if (KOITO_OPISVAT_PRAVILOTO.includes(p)) continue;
      const tekst = readFileSync(p, 'utf8');
      for (const [i, red] of tekst.split('\n').entries()) {
        if (/старото пише|но вярното е|⚠ *заглавк|^> *⚠ *ЗАМЕНЕН/i.test(red)) {
          nameri.push(`${p}:${i + 1}`);
        }
      }
    }
    expect(nameri, `следи в живи файлове: ${nameri.join(' · ')}`).toEqual([]);
  });

  /**
   * И ОБРАТНОТО · нищо ЖИВО да не е заседнало в архива.
   *
   * Архивиран файл, който още се сочи като действащ от жив документ, е същата
   * болест от другата страна: решение в сила, което никой не сверява.
   */
  it('жив документ не сочи архивиран файл като ДЕЙСТВАЩ', () => {
    const nameri: string[] = [];
    for (const p of ZHIVI) {
      for (const [i, red] of readFileSync(p, 'utf8').split('\n').entries()) {
        if (!red.includes('arhiv/')) continue;
        // Позволено: да се каже КЪДЕ е архивираното. Забранено: да се цитира
        // като в сила — „виж", „по", „според" пред пътя.
        if (/(според|по правилата на|виж) [^\n]*arhiv\//i.test(red)) nameri.push(`${p}:${i + 1}`);
      }
    }
    expect(nameri, `сочени като действащи: ${nameri.join(' · ')}`).toEqual([]);
  });
});
